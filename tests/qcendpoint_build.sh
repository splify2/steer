#!/bin/sh
# Explicit Linux QUIC endpoint lab build, using already verified dependency libs.
set -eu
NGLIB=${1:?ngtcp2 archive required}
WLIB=${2:?server-enabled wolfSSL archive required}
OUT=${3:?isolated output directory required}
CC=${CC:-cc}
HERE=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
mkdir -p "$OUT"
OUT=$(CDPATH= cd -- "$OUT" && pwd)
cd "$HERE"
[ -r "$NGLIB.cflags" ] && [ -r "$WLIB.cflags" ]
grep -q -- '-DSTEER_WOLFSSL_SERVER' "$WLIB.cflags" || { echo 'server-enabled wolfSSL archive required' >&2; exit 2; }
find src -type d -print | sed 's|.*|"-I&"|' > "$OUT/includes.rsp"
NGFLAGS=$(cat "$NGLIB.cflags")
WFLAGS=$(cat "$WLIB.cflags")
FLAGS='-O1 -g -Wall -Wextra -Werror'
if [ "${SANITIZE:-0}" = 1 ]; then FLAGS="$FLAGS -fsanitize=address,undefined -fno-omit-frame-pointer"; fi
# Flags are generated by the repository's dependency recipes, never peer input.
# shellcheck disable=SC2086
$CC $FLAGS $NGFLAGS $WFLAGS @"$OUT/includes.rsp" -Itests -DQC_WITH_ENDPOINT \
    tests/qcendpoint.c src/proto/quic/quic.c src/proto/quic/qcssl.c "$NGLIB" "$WLIB" -lpthread -lm -o "$OUT/server"
# Preserve old single-server/client tests without defining the new endpoint flag.
# shellcheck disable=SC2086
$CC $FLAGS $NGFLAGS $WFLAGS @"$OUT/includes.rsp" -Itests -DQC_WITH_SERVER \
    tests/qcloop.c src/proto/quic/quic.c src/proto/quic/qcssl.c "$NGLIB" "$WLIB" -lpthread -lm -o "$OUT/qcloop"
# shellcheck disable=SC2086
$CC $FLAGS $NGFLAGS $WFLAGS @"$OUT/includes.rsp" -Itests -DQC_WITH_SERVER \
    tests/qcbatch.c src/proto/quic/quic.c src/proto/quic/qcssl.c "$NGLIB" "$WLIB" -lpthread -lm -o "$OUT/qcbatch"
"$OUT/qcloop"
"$OUT/qcbatch"
