/* Профиль сборки — то, чем бинарники одного дерева отличаются друг от друга, кроме состава
 * модулей (docs/architecture.md, раздел 2, правило 3: «Сборка — набор модулей, а не набор
 * макросов»).
 *
 * ПРОФИЛЬ — ЭТО ФАЙЛ. Какие виды, протоколы и команды есть в бинарнике, решает список файлов
 * профиля в build/sources.mk: вид — слабой ссылкой из реестра (src/kinds/kind.c), команда —
 * слабой ссылкой из точки входа (src/daemon/main.c). Но у профиля есть и ДАННЫЕ, которые
 * модулем не выражаются: как сборка называет себя, в каком бите метки и в каком ряду таблиц
 * живёт мини-сборка микропакета tgws, поднимает ли она резолвер. Их держит один файл
 * src/profile/<профиль>.c с определением steer_profile — у базового профиля такого файла нет, и
 * действует умолчание (profile.c). Два файла профиля в одной сборке — ошибка компоновки
 * (steer_profile определён дважды), и это нарочно: профиль у бинарника один.
 *
 * Раньше то же самое решали ключи -DSTEER_EXTENDED, -DSTEER_SERVER, -DSTEER_TGWS, и каждый путь
 * сборки (Makefile, build-ext.sh, Android.bp, стенды) обязан был передать ровно тот ключ, что
 * соответствовал его списку файлов; забытый ключ давал бинарник, который компоновался и
 * вёл себя как соседний профиль. Теперь список файлов и есть профиль.
 *
 * ПОЛЯ — ТОЛЬКО ОТЛИЧИЯ. Ноль (NULL) значит «как у базовой сборки», и prof() подставляет
 * умолчание: файл профиля пишет только то, чем профиль особенный, а числа базовой сборки живут
 * в одном месте (profile.c). */
#ifndef STEER_PROFILE_H
#define STEER_PROFILE_H
#include <stdint.h>

struct profile {
    /* Вариант сборки в `steer version`. */
    const char *build;
    /* Полный роутерный пакет: клиенты туннелей и мост Telegram в одном бинарнике. Справка тогда
     * не помечает команды [steer-extended], а мост kind=tgws поднимает супервизор. */
    unsigned extended : 1;
    /* Резолвера нет: заворот DNS не ставится, needs-dnsd отвечает «нет», доменный канал —
     * отказ apply (мини-сборка tgws). */
    unsigned no_resolver : 1;

    /* Поле метки на платформе mark_platform — вместо поля из её таблицы (src/platform). Своё
     * поле нужно мини-сборке tgws, которая ставится рядом с полным движком (marks.h). */
    const char *mark_platform;
    uint32_t mark_base;
    unsigned mark_bits;
    /* Первый номер таблицы маршрутизации (registry.c), имя файла имён таблиц в rt_tables.d и
     * первый порт моста kind=tgws (marks.h). */
    int table_base;
    const char *rt_tables_file;
    int tgws_port_base;
    /* Первый порт слушателей TCP модулей с KC_TCP_REDIR (marks.h, out_tcp_port). */
    int tcp_port_base;
};

/* Профиль этой сборки: steer_profile из файла профиля, дополненный умолчаниями. */
const struct profile *prof(void);

#endif
