#ifndef STEER_DNSD_TABFMT_H
#define STEER_DNSD_TABFMT_H

/* ФОРМАТ ТАБЛИЦЫ ДОМЕННЫХ КАНАЛОВ — контракт между демоном и резолвером (docs/architecture.md,
 * раздел 4а, «dnsd»: резолвер принимает таблицу из управляющей трубы).
 *
 * ЗАЧЕМ ЭТОТ ФАЙЛ. Сегодня резолвер сам читает спеку и сам решает (dch_build, table.c), какой
 * канал в какой набор nft кладёт домены и в каком режиме. Демон 1.8 отбирает у него вторую
 * половину этой работы: он читает спеку САМ (там же, где читает всё остальное — apply, реестр
 * меток), а резолверу присылает уже готовое РЕШЕНИЕ — то самое, что раньше строил dch_build,
 * только текстом по трубе, а не разбором JSON внутри резолвера. Спеку резолвер в этом режиме
 * (--table-fd) не открывает вовсе: труба самодостаточна, в ней есть всё нужное для матчинга
 * без единого обращения к файлу спеки.
 *
 * ЧТО ИМЕННО ПЕРЕДАЁТСЯ. Ровно то, что дальше нужно резолверу от КАЖДОГО доменного канала
 * (struct dchan, dnsd_int.h) — то же самое подмножество, которое dch_build (table.c) сегодня
 * вычисляет из struct spec:
 *   - `set`   — имя набора nft, куда резолвер кладёт поддельный или настоящий адрес;
 *   - `out`   — выход, которому набор принадлежит (только для журнала имён, dlog.c);
 *   - realip  — 0 (fakeip: клиенту уходит поддельный адрес из пула) или 1 (realip: набор
 *               получает настоящие адреса ответа, клиенту — правда);
 *   - family  — «4», «6» или «46» — какие семейства адресов у канала (1.9, IPv6). «46» —
 *               у доменной группы есть половина IPv6 (dom6_ok, spec.h): парный набор «<set>6»
 *               и v6-двойник правила у компилятора, и резолвер отвечает на AAAA имён канала
 *               адресом — поддельным IPv6 в «<set>6» (fake-IP) или настоящим (real-ip), — а не
 *               пустым ответом. У спеки v1 — всегда «4» (sp->dns.names_v4, spec.h): на AAAA её
 *               имён пустой ответ, как до 1.9, хотя набор «<set>6» у компилятора есть; резолвер
 *               этого различия не видит — ему хватает поля. Имя набора IPv6 отдельным полем не
 *               передаётся: оно всегда «<set>6» (group_set6_name у компилятора). tabfmt_build
 *               пишет «4» или «46»;
 *               «6» разбор принимает (канал без IPv4 не забирает ответы A);
 *   - `chan`  — имя ПРАВИЛА спеки, под которым канал показывается в журнале имён (dlog.c);
 *   - пути файлов доменных правил канала (rules_path) — их резолвер читает САМ (dch_rules_load,
 *     rules.c): содержимое списков по трубе не идёт, идут только пути к ним на диске. Путь к
 *     `.lst` или `.srs` — как есть (набор узнаётся по подписи «SRS»). Канал с наборами sing-box
 *     (srs_files) передаёт ещё ВЫБОР — какие клаузы набора его (src/model/srsplan.c), а у
 *     составного набора и сужение каждой:
 *       srs:<клаузы>:<путь>   клаузы — номера и диапазоны через запятую («0,2-5»), у составного
 *                             набора с сужением («0=udp/50000-65535,1=-»);
 *       cl:<сужение>:<путь>   собственный список канала в составном наборе: все его имена — с
 *                             сужением канала («-» — без сужения).
 *     Канал, у которого хоть один источник несёт сужение, — составной: резолвер кладёт адрес
 *     имени элементом «адрес . протокол . порты» (dch_add, fakeip.c).
 * Порядок каналов в таблице — это ПОРЯДОК ПРИОРИТЕТА: тот же порядок, в котором были бы
 * заведены каналы у dch_build, и тот же смысл — первый совпавший в цепочке побеждает
 * (dch_first, dch_match_mask, dnsd_int.h).
 *
 * Внутренний build-time признак `chan_dom` (table.c: какое из правил группы старше — доменное
 * или адресное, «чьё имя показывать») в таблицу НЕ входит: это решение уже принято к тому
 * моменту, когда dch_build выбрал `chan`, и после него не нужно — а нужно было бы, только если
 * бы резолвер сам пересобирал группы, чего в этом режиме он больше не делает.
 *
 * ФОРМАТ — текстовый, построчный, самодостаточный (тот же довод, что у dch_signature, table.c:
 * «его сравнивает оболочка, а не мы» — здесь читает резолвер, но тем же простым построчным
 * разбором, без парсера JSON внутри процесса, которому и так велено быть маленьким).
 *
 * РАСШИРЕНИЕ 1.11 (апстримы и кэш, dup.h). Если у спеки есть апстримы каналов или кэш, первая
 * строка — `N U кэш min max neg` (число апстримов, записей кэша, пределы срока в секундах), после N
 * строк каналов идут U строк апстримов `имя|адрес|выход|метка|адреса|bootstrap` (`-` — пусто;
 * метка — число, 0 — не метить; выход — имя для status или `-`, «напрямую»), а у канала последним
 * полем стоит `dns:<номер апстрима с единицы>`. Без апстримов и кэша строка — просто `N`, и таблица
 * такая же, как до 1.11, до байта.
 *
 * ГРУППЫ И dns.other. Группа серверов (dupgrp.c) — строка апстрима `имя|group:race|-|0|1,2,3|-` (или
 * `group:failover`): в поле адресов — номера строк членов с единицы, члены стоят раньше группы. Сервер
 * для имён вне правил (`dns.other`) — седьмое число заголовка, номер его строки; только когда он
 * задан, иначе заголовок прежний. Члены-группы и номера вне таблицы разбор выбрасывает из группы.
 *
 *   N\n
 *   строка канала 0\n
 *   ...
 *   строка канала N-1\n
 *
 * Первая строка — ДЕСЯТИЧНОЕ ЧИСЛО СТРОК КАНАЛОВ, а не пустая строка-разделитель: признак
 * конца таблицы обязан быть однозначным ДО того, как текст разобран, а число, известное
 * заранее, читается за один проход без заглядывания вперёд — резолвер получает трубу
 * потоком (см. tabfmt_feed) и обязан сам понимать, сколько ещё строк ждать, а «встретил
 * пустую строку» неотличимо от «канал с нулём путей» на выбранном ниже разделителе полей.
 *
 * Строка канала — поля через `|`, без экранирования (тот же разделитель и то же отсутствие
 * экранирования, что уже в dch_signature: имена наборов и правил задаёт спека, а пути списков
 * — движок сам, при apply; ни то, ни другое не бывает произвольным текстом человека):
 *
 *   set|out|realip|family|chan|path1|path2|...\n
 *
 * `realip` — «0» или «1». `family` — «4», «6» или «46» (см. выше). Путей
 * может быть ноль (поле `chan` — последнее перед ними, `\n` сразу за ним, если путей нет) или
 * несколько — ровно rules_n этого канала. Ни одно поле не несёт символов `|` и `\n` — это то же
 * ограничение, что дисциплинирует dch_signature, и оно того же происхождения: все поля — это
 * то, что задаёт спека (имена) или сам движок (пути списков), а не текст, который вводит
 * человек в свободной форме.
 *
 * ДВЕ ФУНКЦИИ КОНТРАКТА:
 *   - tabfmt_build (tabfmt.c) — сборка: собирает g_dch из struct spec (dch_build, table.c) и
 *     печатает его текстом выше в `out`. Её зовёт демон (в трубу дочернему резолверу) и команда
 *     `steer dnsd-table --spec` (в stdout, для стендов и ручной отладки). Файл tabfmt.c не
 *     зависит от proxy.c и остального резолвера (сети, epoll, fake-IP) — демон вправе слинковать
 *     только его и table.c, без всего резолвера (build/sources.mk, DNSD_TABLE_SRC).
 *   - tabfmt_parse (tabfmt.c) — разбор: заменяет g_dch/g_dch_n тем, что описано в буфере (ровно
 *     одна таблица целиком). Её зовёт резолвер — как при первом чтении трубы (до начала
 *     обслуживания), так и при каждой следующей полной таблице (замена без перезапуска, тем
 *     же путём, что SIGHUP сегодня перечитывает файлы правил, — см. proxy.c, reload_rules).
 *
 * Разбор ВЛАДЕЕТ памятью, которую он выделяет (chan/out/set — фиксированные поля struct dchan,
 * а вот rules_path[] под tabfmt_parse — это strdup: строки не могут указывать в буфер трубы,
 * который переживёт только один этот вызов). Поэтому в режиме --table-fd компилятора спеки в
 * процессе нет вовсе — а значит, и dch_build в этом процессе не вызывается ни разу, и конфликта
 * владения (чьё это — struct spec, из которой dch_build, table.c, заимствует пути списков, не
 * копируя, или tabfmt.c со своими strdup) не возникает: пока используется tabfmt_parse, ВСЕ
 * rules_path каналов принадлежат ему, и следующий вызов освобождает их сам (см. tabfmt.c).
 *
 * tabfmt_feed — приёмник таблицы из трубы (не часть контракта, а его несущая конструкция):
 * труба отдаёт байты чанками вперемешку с прочими событиями epoll, а не готовым текстом целиком
 * (тот же случай, что уже решён у DNS по TCP, proxy.c: tcpc_read). Копит байты между вызовами,
 * распознаёт конец ровно одной таблицы (первая строка досчитана до `\n`, затем досчитаны все
 * N строк) и тогда зовёт tabfmt_parse сама, сдвигая буфер на остаток (следующая таблица, если
 * демон прислал две подряд одной записью в трубу). Один установленный предел на весь буфер
 * (TABFMT_FEED_CAP) — переполнение здесь означает, что демон прислал текст не по контракту, и
 * резолвер обязан считать трубу сломанной, а не гадать, где у чужого текста граница строки.
 */

#include <stddef.h>
#include <stdio.h>

struct spec;

/* Собрать g_dch из спеки sp (тем же dch_build, что и раньше) и напечатать таблицу текстом
 * выше в out. g_dch/g_dch_n после вызова отражают ровно то, что напечатано — как и раньше у
 * dnsd_sig_print (table.c), который печатает подпись по тому же построению. */
void tabfmt_build(const struct spec *sp, FILE *out);

/* Разобрать РОВНО ОДНУ таблицу, целиком лежащую в buf[0, len), и заменить ею g_dch/g_dch_n.
 * Прежнее содержимое g_dch (если оно было заведено предыдущим вызовом tabfmt_parse) освобождается
 * первым: и строки путей (strdup'нутые прошлым разбором), и загруженные наборы правил (struct
 * ruleset — их содержимое читает reload_rules, proxy.c, уже ПОСЛЕ этого вызова, по свежим
 * rules_path). Возвращает 0 при успехе; -1 — текст испорчен (счётчик не число, за ним меньше
 * заявленных строк, число каналов больше заявленного в шапке, поле family — не «4»/«6»/«46») — g_dch в
 * этом случае мог остаться разобранным лишь частично, и вызывающий обязан считать резолвер в
 * нерабочем состоянии. g_dch_n после успеха — число строк таблицы, семейства канала — в его
 * поле fam (DCH_V4, DCH_V6). */
int tabfmt_parse(const char *buf, size_t len);

/* Буфер приёмника растёт по размеру таблицы (раньше — статические 64 КиБ, и таблица длиннее них
 * считалась нарушением контракта: резолвер завершался, а доменные правила переставали
 * работать вовсе). Потолок TABFMT_FEED_MAX — не размер таблицы, а защита от трубы, которая
 * несёт не то, что обещает контракт (нет конца строки, бесконечный поток): настоящая таблица на
 * тысячи каналов — мегабайты, а не десятки. Переполнение потолка — та же ошибка контракта. */
#define TABFMT_FEED_MAX (64u << 20)

struct tabfmt_feed {
    char *buf;
    size_t len, cap;
    /* Где остановился подсчёт строк таблицы (смещение за последней найденной и сколько их): новый
     * кусок трубы досматривается с этого места, а не с начала — иначе таблица в мегабайты,
     * пришедшая кусками по 4 КиБ, перечитывалась бы заново на каждый. 0 — счёт не начат. */
    size_t scan_pos;
    long scan_lines;
};

/* Скормить n свежепрочитанных байт трубы (n == 0 — не читали ничего нового, просто ещё раз
 * проверить, не собралась ли таблица целиком из уже накопленного — нужно, когда демон одной
 * записью в трубу прислал две таблицы подряд). Возвращает:
 *   1  — таблица собралась целиком, tabfmt_parse её разобрал и g_dch заменился; в st->buf мог
 *        остаться хвост — начало следующей таблицы, если она пришла той же записью;
 *   0  — данных пока недостаточно, g_dch не тронут;
 *  -1  — труба несёт не то, что обещает контракт (переполнение буфера или испорченный текст):
 *        g_dch мог остаться разобранным частично, восстанавливаться не из чего, резолвер
 *        обязан завершиться. */
int tabfmt_feed(struct tabfmt_feed *st, const char *data, size_t n);

/* Блокирующее чтение ПЕРВОЙ таблицы с дескриптора fd — до начала обслуживания LAN (см. шапку
 * выше и docs/architecture.md, раздел 4а). Читает fd напрямую (read(2), с повтором на EINTR),
 * не трогая epoll резолвера: цикл событий на этот момент ещё не поднят. st — состояние приёмника,
 * ОБЩЕЕ с тем, которым резолвер затем кормит трубу из цикла epoll (run_proxy): демон вправе
 * прислать вторую таблицу следом за первой одной записью, и её хвост, недочитанный до конца
 * первым вызовом, обязан остаться в том же буфере, а не потеряться между двумя разными
 * структурами. Возвращает 0, когда g_dch заменился первой таблицей; -1 — труба закрылась или
 * испортилась до того, как первая таблица собралась целиком (демон умер до первого слова —
 * резолверу в этом режиме отвечать не на что, и запускаться незачем). */
int tabfmt_read_first(int fd, struct tabfmt_feed *st);

/* --table-fd N (proxy.c). g_table_fd — дескриптор трубы, -1 — флага не было (резолвер читает
 * спеку сам, как раньше — dnsd_main). g_table_feed — состояние приёмника, общее между первым
 * блокирующим чтением (dnsd_main, tabfmt_read_first) и последующими из цикла epoll (run_proxy):
 * см. рационале у tabfmt_read_first выше. */
extern int g_table_fd;
extern struct tabfmt_feed g_table_feed;

/* Демон пропал (труба закрылась) — сколько секунд резолвер отвечает по последней таблице и ждёт
 * нового демона (--orphan-timeout, proxy.c); 0 — выйти сразу, как прежде. Новый демон забирает
 * живой резолвер через его управляющий сокет — <каталог состояния>/DNSD_CTL_SOCK (src/dnsd/
 * adopt.c: протокол и доводы; сторона демона — src/daemon/supd.c, adopt_dnsd). */
extern int g_orphan_sec;
#define DNSD_CTL_SOCK "dnsd-ctl.sock"

#endif
