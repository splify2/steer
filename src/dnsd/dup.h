#ifndef STEER_DNSD_DUP_H
#define STEER_DNSD_DUP_H

/* АПСТРИМЫ РЕЗОЛВЕРА: DNS по UDP, TCP, TLS (DoT), HTTPS (DoH) и QUIC (DoQ), путь запроса через
 * выход, кэш.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ СЛОЙ. До 1.11 резолвер знал один сервер наверху: петлю 127.0.0.1:53 (dnsmasq)
 * или на телефоне тот адрес, куда шёл запрос клиента. Теперь у доменного правила может быть свой
 * сервер (`dns:` правила, `dns.upstream` общий), и он говорит на любом из пяти транспортов и
 * достижим по своему пути — напрямую или через выход. Всё это собрано за тремя вызовами
 * (dup_apply, dup_ask, dup_event/dup_tick), чтобы proxy.c, и без того на две тысячи строк, не
 * узнал ни про TLS, ни про HTTP, ни про bootstrap: он спрашивает «ответь на этот вопрос сервером
 * N» и получает ответ обратным вызовом ровно один раз.
 *
 * ЦИКЛ СОБЫТИЙ — ТОТ ЖЕ, ПОТОКОВ НА ЗАПРОС НЕТ. Сокеты апстримов живут в epoll резолвера (g_epfd),
 * читаются и пишутся неблокирующе. Единственное, что делается вне цикла, — установка ОДНОГО
 * соединения TLS: разрешение имени сервера через bootstrap, connect и рукопожатие
 * (tls13_handshake_auth блокирующее по устройству, наш TLS не умеет продолжаться с середины). Оно
 * идёт в короткоживущем потоке (dupdial.c), который отдаёт готовый сокет циклу через socketpair, —
 * тот же приём, что у замера urltest по HTTPS (src/proto/tls/urltls.c). Поток заводится на
 * соединение, а не на запрос: долгоживущее соединение переживает тысячи запросов, и поток нужен
 * ему только при первой установке и переподключении. У DoQ поток ещё скромнее: рукопожатие QUIC
 * неблокирующее и идёт событиями цикла (обёртка src/proto/quic, qc_on_readable/qc_on_timer), поэтому
 * потоку остаётся один шаг — найти адреса сервера через bootstrap.
 *
 * ПУТЬ ЗАПРОСА. Сокет апстрима метится (SO_MARK) меткой выхода, если в таблице для апстрима она
 * есть. Метку выхода ip rule ведёт в таблицу его устройства, а postrouting_guard
 * (compile/generate.c) отбрасывает помеченный пакет, уходящий не в устройство выхода, — поэтому
 * лёгший выход даёт не утечку в WAN, а тишину, и апстрим честно показывает «нет ответа». Апстрим
 * «через выход», которому метка не выдана (резолвер запущен без демона), не используется вовсе:
 * слать «через туннель» без метки значило бы слать напрямую.
 *
 * BOOTSTRAP. Имя сервера DoT/DoH/DoQ не разрешается системным резолвером: он либо сам зависит от
 * этого резолвера, либо (dnsmasq, https-dns-proxy) настройка человека, которой мы не касаемся.
 * Имя разрешается обычным DNS по UDP у серверов bootstrap, с той же меткой пути, что и сам
 * апстрим, а если адреса записаны в спеке (`ips`) — вообще не разрешается. Результат хранится по
 * TTL ответа; пока bootstrap молчит, а старые адреса есть, соединяются со старыми. Сам bootstrap
 * никогда не спрашивает ни резолвера, ни его апстримов, поэтому замкнуться на себе ему нечем. */

#include <stddef.h>
#include <stdint.h>
#include <stdio.h>
#include "spec.h"

/* Настройка одного апстрима, как её несёт таблица (tabfmt.h). */
struct dup_cfg {
    struct spec_dns_up u;       /* url разобран (proto, host, port, path); ips и boot — итоговые:
                                 * boot уже дополнен общими серверами bootstrap спеки */
    char via[32];               /* имя выхода для status; "" — напрямую */
    unsigned mark;              /* метка сокета; 0 — не метить */
    int need_mark;              /* через выход: без метки слать нельзя (см. выше) */
    int own;                    /* u.ips и u.boot — куча, отданная этой записи (разбор текста таблицы);
                                 * 0 — указатели взаймы у спеки (сборка таблицы демоном) */
    /* Группа серверов (`servers`, `mode` в dns.upstreams): DNSG_RACE или DNSG_FAILOVER (spec.h); 0 —
     * это сервер. gm — номера членов в этой же настройке (с нуля), по порядку спеки; куча самой
     * записи при любом own (dup_cfg_list_reset освобождает). Члены — только серверы. */
    int grp;
    unsigned *gm;
    size_t gm_n;
};

/* Кэш ответов для имён под правилами (dcache.c). entries == 0 — кэша нет. */
struct dcache_cfg { long entries, ttl_min, ttl_max, ttl_neg; };

/* Разобранное таблицей: резолвер берёт настройку отсюда (tabfmt_parse, dup_cfg_from_spec). */
extern struct dup_cfg *g_dup_cfg;      /* куча, растёт по числу апстримов таблицы */
extern size_t g_dup_cfg_n, g_dup_cfg_cap;
/* Сервер или группа для имён вне правил (`dns.other`): номер в g_dup_cfg плюс один; 0 — нет, имена вне
 * правил спрашиваются прежним путём. */
extern unsigned g_dup_other;
/* Список апстримов — пустым; массивы адресов освобождаются у владельцев (cfg.own). */
void dup_cfg_list_reset(void);
extern struct dcache_cfg g_dcache_cfg;

/* Ответ апстрима или отказ. Зовётся ровно один раз на принятый dup_ask. ans == NULL — отказ
 * (нет соединения, сервер не ответил, таймаут); тогда q и qn — исходный вопрос с его номером,
 * чтобы вызывающий мог ответить клиенту SERVFAIL. При ответе q не нужен: ans уже несёт номер,
 * с которым вопрос был принят. */
typedef void (*dup_done_fn)(void *ctx, const uint8_t *ans, size_t n, const uint8_t *q, size_t qn);

/* Привести апстримы к настройке c[0..n): совпавшие по имени и полям остаются (с соединениями и
 * найденными адресами), изменившиеся и исчезнувшие закрываются, а их вопросы получают отказ. */
void dup_apply(const struct dup_cfg *c, size_t n);

/* Принять вопрос q[0..n) к апстриму idx (номер в настройке, с нуля). 0 — принят, обратный вызов
 * будет; -1 — не принят (нет такого, не пригоден, очередь полна): обратного вызова не будет, и
 * вызывающий отвечает клиенту сам. Апстрим-группа (cfg.grp) отвечает как один сервер: обратный
 * вызов — ровно один, с первым годным ответом члена или отказом, когда годного не дал никто
 * (dupgrp.c). */
int dup_ask(size_t idx, const uint8_t *q, size_t n, dup_done_fn cb, void *ctx);

/* Событие epoll с data.ptr == ptr. 1 — ptr наш и событие обработано; 0 — чужой. */
int dup_event(void *ptr, uint32_t evs);

/* Сроки: снять просроченные вопросы, закрыть простоявшие соединения, переподключиться. Зовётся
 * каждый виток цикла. dup_wait_ms — через сколько миллисекунд позвать снова (-1 — незачем). */
void dup_tick(void);
int dup_wait_ms(void);

/* Есть ли что-то живое (вопрос в пути, соединение): цикл тогда не спит бесконечно. */
int dup_busy(void);

/* Закрыть всё (выход резолвера). */
void dup_close_all(void);

/* Состояние для `dns-log`/status: элементы JSON-массива апстримов, через запятую, без скобок. */
void dup_render(FILE *f);

/* ГОДНЫЙ ОТВЕТ — любой, кроме SERVFAIL и REFUSED: сервер, ответивший так, не смог или не стал отвечать,
 * и спросить стоит другой (группа серверов, dns.other). NXDOMAIN и пустой ответ — годные: это ответ
 * об имени, а не отказ сервера. 1 — годный. */
int dup_ans_good(const uint8_t *ans, size_t n);

/* ПАУЗА ПОСЛЕ ОТКАЗА: член группы (failover и race) и сервер для имён вне правил, не ответившие (таймаут, нет
 * соединения, SERVFAIL/REFUSED у члена), на время уходят из первых: группа спрашивает сперва других,
 * резолвер имён вне правил — сразу прежний путь. Пауза нарастает (5, 10, 20 … 300 с) и сбрасывается
 * первым годным ответом; по её истечении сервер снова спрашивается первым — так он и проверяется,
 * настоящим вопросом. STEER_DNSD_PAUSE_MS (не меньше 100) — первая пауза, только для стендов. */
struct dpause {
    long until_ms, step_ms;     /* до какого момента пауза; её нынешняя длина (0 — отказов не было) */
    long fail_ms;               /* когда был последний отказ (0 — не было) */
    unsigned long ok, fail;     /* годных ответов и отказов с запуска */
};
long dup_now_ms(void);
void dpause_ok(struct dpause *p);
/* Годный ответ на вопрос, отправленный в sent_ms: паузу снимает, только если вопрос ушёл ПОСЛЕ
 * последнего отказа. Победа не должна пережить более поздний отказ (иначе сервер, который только что
 * отказал, вернулся бы первым из-за запоздавшего ответа на старый вопрос и дёргался туда-сюда). */
void dpause_ok_at(struct dpause *p, long sent_ms);
void dpause_fail(struct dpause *p, long now);
int dpause_on(const struct dpause *p, long now);

/* Есть ли в сборке TLS (DoT/DoH пригодны). */
int dup_have_tls(void);
/* Есть ли в сборке обёртка QUIC (DoQ пригоден): слабые ссылки на qc_*, как у TLS. */
int dup_have_quic(void);

/* Свой файл корней для проверки сертификата вместо системного (флаг --ca-file, для стендов). */
extern const char *g_dup_ca_file;

/* ---- кэш (dcache.c) ------------------------------------------------------------------------- */

void dcache_config(const struct dcache_cfg *c);        /* задать и сбросить */
void dcache_flush(void);
int dcache_on(void);
/* Положить ответ апстрима up (номер настройки плюс один; 0 — прежний путь наверх). 1 — положен. */
int dcache_put(unsigned up, const uint8_t *ans, size_t n, long now_s);
/* Ответ на вопрос q из кэша: в out (cap), с номером вопроса и вопросом как у q, со сроками,
 * уменьшенными на возраст. Длина или 0 — в кэше нет. */
size_t dcache_get(unsigned up, const uint8_t *q, size_t qn, uint8_t *out, size_t cap, long now_s);
void dcache_render(FILE *f);

#endif
