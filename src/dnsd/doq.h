#ifndef STEER_DNSD_DOQ_H
#define STEER_DNSD_DOQ_H

/* DNS ПО QUIC (RFC 9250): КАДРЫ И КОДЫ — БЕЗ СЕТИ.
 *
 * Здесь только то, что в DoQ проверяется по байтам и не требует соединения: как выглядит запрос
 * на потоке, когда ответ на потоке целый и что делать с прочим, и коды закрытия. Соединение,
 * потоки и таймеры — в dup.c поверх обёртки QUIC (src/proto/quic/quic.h); вынесено в отдельный
 * файл затем, чтобы стенд dupmatch проверял кадры без ngtcp2 и без сокетов.
 *
 * ЧТО ГОВОРИТ RFC 9250.
 *   - Один вопрос — один двунаправленный поток, открытый клиентом. Запрос: две байта длины
 *     сообщения (сетевой порядок) и само сообщение DNS, потом FIN. Ответ на том же потоке — тот же
 *     формат, потом FIN сервера. Клиент не шлёт по потоку ничего сверх одного вопроса.
 *   - Номер сообщения (ID) в запросе — 0 (раздел 4.2.1): поток и есть номер, а нулевой ID держит
 *     сообщение кэшируемым и не даёт одному номеру ходить по двум потокам. Ответ приходит с ID 0;
 *     подставить номер вопроса клиента обратно — дело того, кто принял вопрос (dup.c это делает).
 *   - Ошибки приложения: закрытие соединения и сброс потока несут 62-разрядный код DOQ_*. Клиент,
 *     бросивший вопрос по таймауту, сбрасывает поток кодом DOQ_REQUEST_CANCELLED; простаивающее
 *     соединение закрывается DOQ_NO_ERROR; сервер, нарушивший формат (сообщение длиннее заявленной
 *     длины, ответ без длины, оборванный поток), закрывается DOQ_PROTOCOL_ERROR. */

#include <stddef.h>
#include <stdint.h>

#define DOQ_NO_ERROR          0x0u
#define DOQ_INTERNAL_ERROR    0x1u
#define DOQ_PROTOCOL_ERROR    0x2u
#define DOQ_REQUEST_CANCELLED 0x3u
#define DOQ_EXCESSIVE_LOAD    0x4u
#define DOQ_UNSPECIFIED_ERROR 0x5u

#define DOQ_ALPN "doq"

/* Наибольшее сообщение DNS в кадре: длина — 16 бит (RFC 1035, 4.2.2), больше не выразить. Предел
 * не наш, а формата: буфер потока не растёт дальше 2 + 65535 байт. */
#define DOQ_MSG_MAX 65535u

/* Кадр запроса: две байты длины и сообщение q[0..qn) с ID, обнулённым в кадре (q не меняется).
 * Байт в dst — 2 + qn, или 0, если не поместилось (cap мал) или qn < 12 (не сообщение DNS). */
size_t doq_frame_query(uint8_t *dst, size_t cap, const uint8_t *q, size_t qn);

/* Разбор накопленных байт потока rx[0..rn) как ответа.
 *   1  — ответ целый: *msg и *mlen указывают в rx; больше в rx ничего нет
 *   0  — ждём ещё байт
 *  -1  — формат нарушен: сообщение короче заголовка DNS, либо после сообщения есть лишние байты
 *        (по потоку идёт ровно одно сообщение) */
int doq_take_answer(const uint8_t *rx, size_t rn, const uint8_t **msg, size_t *mlen);

/* Название кода для журнала (не для показа человеку). */
const char *doq_err_name(uint64_t code);

#endif
