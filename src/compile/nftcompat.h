#ifndef STEER_NFTCOMPAT_H
#define STEER_NFTCOMPAT_H
#include <stddef.h>
#include <stdio.h>

/* ---- пробы ядра: что примет nftables этой машины ---------------------------------------
 *
 * Раскладка набора правил одна — современная: nat в семействе inet (Linux 5.2 и новее). Раскладку
 * для Linux 4.9 (nat в ip/ip6, доменный набор надвое, цепочка route в ip, без notrack) убрали
 * вместе с ядром телефона 4.9 (I-541, решение владельца: «4.9 пропускаем»): на ядре без nat в
 * inet apply отказывает, и отказ называет это сам, а не гадание.
 *
 * Здесь остались две пробы — составной интервальный набор (nft_concat_ok) и цепочка inet ingress
 * (nft_ingress_ok), обе пробной таблицей через `nft -c`. Определены в nftcompat.c. */

/* Раскладка набора правил ЭТОГО ЗАПУСКА — флаги NFTC_*. Единственный флаг — NFTC_INGRESS: ядро и
 * nft принимают базовую цепочку на хуке ingress в семействе inet (Linux 5.10, nftables 0.9.7), и
 * разметку каналов ставит цепочка ingress_mark (generate.c, «разметка на ingress»). Его добавляет
 * apply_prepare по nft_ingress_ok, а дальше он ходит вместе с раскладкой — план apply-сверки
 * печатает g_nftc, демон отдаёт его следующим планам через --nftc, — и проба не повторяется на
 * каждый apply. */
#define NFTC_INGRESS 8
extern int g_nftc;

/* Примет ли ядро цепочку inet ingress: проба `nft -c` пробной таблицей с такой цепочкой на lo
 * (1 — да). STEER_NFT_INGRESS переопределяет ответ для стендов: 0 — нет; 1 — да (устройства
 * раздачи всё равно проверяются: цепочка встаёт только на существующие); all — да, и все
 * устройства раздачи считаются существующими (стенды генератора на машине без br-lan). Ответ
 * запоминается на процесс. */
int nft_ingress_ok(void);
/* STEER_NFT_INGRESS=all: устройства раздачи не проверяются на существование. */
int nft_ingress_all_devs(void);
/* Примет ли ядро составной интервальный набор ipv4_addr . inet_proto . inet_service — для
 * каналов со смешанным сужением списка (см. nftcompat.c). 1 — да, 0 — делить по группам.
 * STEER_NFT_CONCAT (0 или 1) переопределяет ответ для стендов. */
int nft_concat_ok(void);

#endif
