/* Чтение gzip (RFC 1952) из памяти потоком: заголовок, DEFLATE через puff_stream, CRC-32 и длина
 * из хвоста. Одно место на всё дерево: им читают и подписку (subfetch.c, панель сжала тело), и
 * пакеты плагинов (untar.c). */
#ifndef STEER_GZ_H
#define STEER_GZ_H
#include <stddef.h>

struct gz;

/* Разобрать заголовок gzip в z[0..n) и завести поток. NULL — это не gzip (нет 1f 8b 08), заголовок
 * оборван или нет памяти. Данные z должны жить до gz_close: поток читает их на месте. */
struct gz *gz_open(const void *z, size_t n);

/* Следующая порция распакованного (до cap байт). > 0 — столько байт; 0 — поток кончился И хвост
 * сошёлся (CRC-32 и длина по модулю 2^32), больше данных не будет; -1 — испорчено: DEFLATE, хвост
 * оборван или не сошёлся. Конец без хвоста — тоже -1: половина файла не «конец». */
long gz_read(struct gz *g, void *dst, size_t cap);

void gz_close(struct gz *g);

#endif
