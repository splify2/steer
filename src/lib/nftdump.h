/* nf_tables по netlink — ЧТЕНИЕ: счётчики и комментарии правил, число элементов набора, наличие
 * таблицы и цепочки, текст набора правил. То, что status и diag раньше узнавали запуском `nft`.
 *
 * ЗАЧЕМ. `steer status` интерфейс опрашивает раз в несколько секунд, и каждый вызов стоил двух
 * `sh -c nft …` — около семи процессов (счётчики четырёх цепочек и дамп ruleset для fw_check);
 * diag — около двадцати. Принцип владельца (docs/architecture.md, раздел 2): пользовательский
 * процесс — только там, где без него нельзя. Вопросы здесь те же, что задавал `nft`, и ядро
 * отвечает на них тем же сообщением NFT_MSG_GET*, только без fork, exec и разбора текста.
 *
 * ПИСАТЬ — НЕ ЗДЕСЬ. Транзакции (элементы наборов от резолвера) живут в nftnl.c со своим
 * долгоживущим сокетом; этот файл сокет открывает на вызов и ничего в ядре не меняет. Разделены
 * они потому, что nftnl.c — библиотека резолвера со своими глобалами (таблица, раскладка
 * интервалов), а читателям — демону, status, diag, kinds — ни то ни другое не нужно.
 *
 * СТАРОЕ ЯДРО. Фильтр дампа правил по таблице и цепочке ядро понимает не всегда (на 4.9 его нет),
 * поэтому отбор повторяется здесь по атрибутам ответа. Одиночный запрос элемента на 4.9 не
 * работает — число элементов считается дампом, и он работает везде.
 *
 * Синхронно: ядро отвечает на запрос внутри того же системного вызова. Зовёт только основной
 * поток. */
#ifndef STEER_NFTDUMP_H
#define STEER_NFTDUMP_H

#include <stdint.h>
#include <stddef.h>

/* Пределы самого ядра, не наши: имя таблицы, цепочки, набора — до 255 байт (NFT_NAME_MAXLEN 256 с
 * нулём), значение данных элемента — до 64 (NFT_DATA_VALUE_MAXLEN). Буфер меньше обрезал бы
 * имя молча, и дамп называл бы чужую цепочку своей. */
#define NFD_NAME 256
#define NFD_DATA_MAX 64

/* Семейства — числа NFPROTO_* (linux/netfilter.h): inet 1, ip 2, ip6 10. */
#define NFD_INET 1
#define NFD_IP   2
#define NFD_IP6  10

/* Правила перечисленных цепочек таблицы по одному, одним дампом: комментарий (userdata, как его
 * пишет nft; "" — нет), счётчик (has_counter 0 — выражения counter в правиле нет). 0 — таблицу
 * прочитали (в том числе без этих цепочек или без самой таблицы: nft о них тоже молчит), иначе
 * errno. */
typedef void (*nfd_rule_fn)(void *arg, const char *comment, int has_counter,
                            uint64_t packets, uint64_t bytes);
int nfd_chain_rules(uint8_t family, const char *table, const char *const *chains, size_t n,
                    nfd_rule_fn fn, void *arg);

/* Сколько элементов в наборе — столько, сколько их напечатал бы `nft list set`: у интервального
 * набора диапазон — один элемент (конец диапазона ядро хранит отдельной записью, она не в счёт).
 * -1 — набора нет или ядро не ответило. */
long nfd_set_count(uint8_t family, const char *table, const char *set);

/* Есть ли таблица; есть ли цепочка в таблице. 1 — есть, 0 — нет или ядро не ответило. */
int nfd_table_exists(uint8_t family, const char *table);
int nfd_chain_exists(uint8_t family, const char *table, const char *chain);

/* Отпечаток таблиц ИМЯ для сверки демона с ядром (src/daemon/recon.c): FNV-1a 64 по цепочкам,
 * правилам по порядку и заголовкам наборов — без номеров объектов, без состояния выражений
 * (counter, quota, last) и без элементов наборов (их кладут резолвер и сторож; что входит и
 * почему — в nftdump.c). Одинаков, пока таблицу меняют только элементами.
 *
 * Сразу во всех семействах, где таблица с этим именем бывает у движка: inet — всегда, ip и ip6 —
 * у раскладки старого ядра (legacy.c). Появившаяся или пропавшая таблица семейства — тоже другой
 * отпечаток. Четыре обмена с ядром на все семейства вместе (таблицы, цепочки, наборы, правила —
 * по дампу на вид, без фильтра по семейству): сверка идёт на каждом проходе сторожа демона, и
 * дамп на семейство утроил бы её. Номер таблицы inet (NFTA_TABLE_HANDLE, с Linux 4.16; 0 — ядро
 * его не отдаёт) — из того же дампа таблиц.
 *
 * 0 — снят (в том числе когда таблиц нет вовсе: fams 0); -1 — ядро не ответило. */
struct nfd_tfp {
    uint64_t fp;
    uint64_t handle;            /* номер таблицы inet; 0 — нет таблицы или ядро номеров не даёт */
    unsigned fams;              /* какие таблицы есть: 1 — inet, 2 — ip, 4 — ip6 */
};
int nfd_table_fp(const char *table, struct nfd_tfp *out);

/* Именованные наборы и карты таблиц ИМЯ во всех семействах — заголовком: семейство, имя, флаги
 * (NFT_SET_*), длина ключа. Безымянные (флаг NFT_SET_ANONYMOUS) тоже приходят: отбирает
 * вызывающий. Один дамп на все семейства, как у nfd_table_fp. 0 — прочитаны; иначе errno. */
struct nfd_set {
    uint8_t family;
    char name[NFD_NAME];
    uint32_t flags;
    uint32_t klen;
};
typedef void (*nfd_set_fn)(void *arg, const struct nfd_set *s);
int nfd_sets(const char *table, nfd_set_fn fn, void *arg);

/* Элементы одного набора — по одному, как их отдаёт ядро: ключ (и конец диапазона у набора из
 * нескольких полей — NFTA_SET_ELEM_KEY_END), флаги элемента (NFT_SET_ELEM_INTERVAL_END — маркер
 * конца у интервального набора из одного поля), есть ли у элемента срок и данные. Порядок —
 * порядок хранилища ядра, он не обещан. reset — перед повтором дампа, который ядро прервало
 * (NLM_F_DUMP_INTR): накопленное надо сбросить. *stable (NULL — не нужно) — 1, если у всех ответов
 * дампа один номер поколения набора правил (nfgenmsg.res_id), то есть посреди дампа не прошло ни
 * одной транзакции и снимок цельный; 0 — кто-то писал, и элементы могли выпасть или прийти
 * дважды (ядро обходит набор, пропуская уже отданное по счёту). 0 — прочитаны; иначе errno
 * (ENOENT — набора нет). */
struct nfd_elem {
    const uint8_t *key;
    size_t klen;
    const uint8_t *key_end;     /* NULL — нет */
    size_t kelen;
    uint32_t flags;
    int timeout;                /* у элемента свой срок (NFTA_SET_ELEM_TIMEOUT или EXPIRATION) */
    int data;                   /* у элемента данные (карта) */
};
typedef void (*nfd_elem_fn)(void *arg, const struct nfd_elem *e);
int nfd_set_elems(uint8_t family, const char *table, const char *set, nfd_elem_fn fn,
                  void (*reset)(void *arg), void *arg, int *stable);

/* Есть ли в таблице правило `redirect to :PORT` (выражение redir с портом из immediate).
 * 1 — есть, 0 — нет. */
int nfd_has_redirect(uint8_t family, const char *table, uint16_t port);

/* Весь набор правил текстом в форме `nft -t list ruleset` — в объёме того, что читает fw_check
 * (src/daemon/fwcheck.c): заголовки таблиц, наборов, flowtable и цепочек (с устройствами хуков),
 * а в правилах — имена устройств (iifname/oifname/iif/oif, в том числе в безымянных наборах и
 * картах вердиктов), состояние и статус ct, семейство правила (`meta nfproto ipv4|ipv6` — по нему
 * fw_check отличает masq от masq6 зоны fw4), переходы и вердикты, masquerade/snat/dnat/redirect,
 * префикс log и комментарии. Прочие выражения (адреса, порты, метки) не печатаются: проверка их
 * не читает, а печать заново повторяла бы nft целиком. Строка malloc'ом; NULL — ядро не ответило
 * или нет памяти. */
char *nfd_ruleset_text(void);

#endif
