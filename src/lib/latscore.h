/* Оценка узла или члена группы по нескольким пробам задержки — одна на пул узлов подписки
 * (src/tunnel/pool.c) и на группы pick: latency (src/daemon/folat.c). Формула — в docs/spec-v2.md,
 * «Оценка узла».
 *
 * ПОЧЕМУ НЕ ОДИН ЗАМЕР. Один ответ не отличает быстрый, но рвущийся узел от ровного: узел, у которого
 * из трёх проб одна потеряна, а две другие разбросаны, выигрывает у ровного на пять миллисекунд —
 * и человек получает «самый быстрый» узел, на котором страницы не открываются. Потери и разброс —
 * то, что выбирающий и так назвал бы «хуже», поэтому они входят в оценку в тех же миллисекундах, и
 * допуск (`tolerance`, гистерезис против скачков) остаётся в единицах оценки.
 *
 * ФОРМУЛА. Из ответивших проб: среднее m и джиттер j — среднее отклонение от среднего. Оценка
 * m + 2·j + 1000 · доля потерь, мс; ни одной ответившей пробы — -1 (не отвечает). Вес джиттера 2 —
 * разброс в одну сторону от среднего мешает так же, как и «в другую», а пик не усреднялся; тысяча
 * миллисекунд на потерю — одна потеря из трёх проб (333 мс) перевешивает разницу между быстрым и
 * медленным узлом (меньше допуска, умноженного на несколько), но не делает ответивший узел мёртвым. */
#ifndef STEER_LATSCORE_H
#define STEER_LATSCORE_H

#define LAT_SAMPLES 3           /* проб на узел за круг замера */
#define LAT_LOSS_MS 1000        /* штраф за потерю всех проб, мс; за долю — пропорционально */

/* s — n проб, мс (< 0 — не прошла). mean, jitter (мс) и loss (%) — необязательны. Возврат — оценка, мс,
 * или -1. */
static inline int lat_score(const int *s, int n, int *mean, int *jitter, int *loss) {
    int ok = 0;
    long sum = 0;
    for (int i = 0; i < n; i++)
        if (s[i] >= 0) { ok++; sum += s[i]; }
    if (loss) *loss = (n - ok) * 100 / n;
    if (!ok) {
        if (mean) *mean = 0;
        if (jitter) *jitter = 0;
        return -1;
    }
    long m = sum / ok, dev = 0;
    for (int i = 0; i < n; i++)
        if (s[i] >= 0) dev += s[i] > m ? s[i] - m : m - s[i];
    long j = dev / ok;
    if (mean) *mean = (int)m;
    if (jitter) *jitter = (int)j;
    return (int)(m + 2 * j + (long)(n - ok) * LAT_LOSS_MS / n);
}

#endif
