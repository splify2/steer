/* Живые процессы по командной строке — обходом /proc, без pgrep.
 *
 * Спрашивают трое: выход kind=zapret (жив ли обработчик своей очереди), сторож (работает ли обход
 * вообще) и diag (запущены ли резолвер и обфускатор). Раньше diag спрашивал `pgrep -f` через
 * system() — два процесса на вопрос, — а обход /proc в движке уже был, у zapret. Один обход на
 * всех: две копии разбора cmdline разошлись бы на первой правке (буфер, замена нулей, пропуск
 * не-цифр).
 *
 * Отличие от `pgrep -f` одно, и оно в нашу пользу: pgrep вызывался через `sh -c`, и командная
 * строка самой оболочки содержала искомый текст — то есть ответ мог найти сам вопрос. */
#ifndef STEER_PROCSCAN_H
#define STEER_PROCSCAN_H

/* Есть ли процесс, в командной строке которого (аргументы через пробел, вся строка целиком)
 * встречается NEEDLE. digit_end — сразу за NEEDLE не должна стоять цифра: так «--qnum=830» не
 * находится в «--qnum=8300». Процесс, который спрашивает, не исключается: его командная строка
 * («steerd daemon …», «steerd diag …») искомого не содержит. */
int proc_cmdline_find(const char *needle, int digit_end);

#endif
