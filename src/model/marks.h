/* ---- метка пакета: НАШИ биты, а не всё слово --------------------------------
 *
 * Слово метки — общий ресурс системы. В нём работают mwan3 (маской 0x3F00), pbr, sqm и всё,
 * что метит пакеты для политики маршрутизации. Пока движок ставил метку перезаписью слова
 * (`meta mark set 0x00100000`) и искал её точным совпадением (`ip rule add fwmark ...`), это
 * ломалось в обе стороны и молча: чужую метку мы стирали, а свою теряли, если её затирали
 * после нас, — и во втором случае помеченный пакет уходил по таблице main, то есть напрямую,
 * минуя таблицу, где при on_fail=drop лежит запрет (I-135).
 *
 * Поэтому диапазон объявлен и стал частью контракта (docs/contract-v1.md): восемь бит с
 * двадцатого. Восемь бит — размер поля, а число выходов с меткой выводится из него
 * (steer_mark_slots ниже), и распорядитель отдаёт значение на выход, см. registry_assign. Маска ВЫВОДИТСЯ из базы и числа бит: три записанных руками числа
 * разошлись бы при первом изменении любого из них.
 *
 * ПОЛЕ НЕ СВОБОДНО ЦЕЛИКОМ — на битах 20-23 оно пересекается с Tailscale и pbr, и об этом
 * надо знать, а не читать ниже «16-23 заняты» как «рядом, но не у нас». Оба держат свою
 * метку маской 0x00ff0000 (биты 16-23); наше поле — 0x0ff00000 (биты 20-27). Общие у них
 * четыре бита: 20, 21, 22, 23. Что это значит на деле:
 *   - Tailscale на каждом пакете с tailscale0 делает в хуке forward
 *     `meta mark set mark and 0xff00ffff xor 0x40000` (снято с роутера, I-265), то есть
 *     стирает биты 20-23 нашей метки. Маршрут это не ломает — ip rule выхода решается раньше,
 *     в prerouting, — но всякий, кто читает метку ПАКЕТА после forward, видит не ту метку
 *     у каждого выхода, чья метка задевает биты 20-23 (у всех, кроме шестнадцатого:
 *     0x01000000). Поэтому такие читатели обязаны читать метку СОЕДИНЕНИЯ (так сделано у
 *     очереди kind=zapret, см. zapret_emit в kinds/zapret.c);
 *   - правило, которое метит тот же пакет маской 0x00ff0000 в prerouting ПОСЛЕ нашей
 *     разметки, стирает наши биты 20-23 — пакет уходит по таблице main, мимо выхода и мимо
 *     запрета on_fail=drop (тот же I-135, только с другой стороны). Правило ДО нашей
 *     разметки теряет свои биты 20-23 уже от нас, и его `fwmark X/0x00ff0000` на этом пакете
 *     перестаёт совпадать;
 *   - пока ЗНАЧЕНИЯ соседа умещаются в биты 16-19 (у Tailscale на роутере видно 0x40000), с
 *     нашими они не совпадают: наши кратны 0x00100000. Пересекаются маски, а не метки, —
 *     поэтому пакет, который метит только один из двух, не страдает. Сколько значений
 *     занимает pbr, зависит от его настройки; на роутере это не сверялось.
 * Раскладка при этом НЕ МЕНЯЕТСЯ: это контракт (docs/contract-v1.md), и сдвиг поля выдал бы
 * новые метки всем выходам на всех роутерах, а мини-сборке пришлось бы переезжать тоже. Вместо
 * этого apply называет соседа, если видит его в наборе правил (report_mark_overlap в
 * daemon/fwcheck.c), — предупреждением, а не отказом: с Tailscale рядом движок работает, и отказ снял
 * бы маршрутизацию у людей, у которых всё в порядке. */
/* МИНИ-СБОРКА ЖИВЁТ В СВОЁМ БИТЕ, а не в диапазоне полного движка. Микропакет tgws ставится
 * рядом с полным движком, и оба метят пакеты в prerouting на одном приоритете. Разные ЗНАЧЕНИЯ
 * меток (STEER_MARK_ORDER=top раздавал биты сверху) этого не решали: правило разметки пишет
 * `mark and ~МАСКА or метка`, и при общей маске тот, чья цепочка идёт второй, стирает метку
 * первого. Порядок цепочек одного приоритета — порядок их загрузки, то есть менялся при каждом
 * apply любого из двух: Telegram то уходил в туннель полного движка, то в мост, и «после stgws
 * Telegram отдыхает» зависело от того, кто применился последним. Своя маска у мини-сборки не
 * пересекается с 0x0ff00000 полного движка — каждый чистит и сравнивает только своё, и на
 * одном пакете обе метки живут вместе: маршрут ставит полный, перенаправление в мост — мини
 * (nat идёт после mangle, и перенаправленный пакет становится локальным — мост побеждает,
 * когда он стоит, и это то, ради чего его ставили). Бит 28: 29 и 30 заняты zapret (см.
 * ниже), 16-23 — Tailscale и pbr, 8-13 — mwan3. Один бит — один выход: у микропакета их
 * ровно один. Таблица маршрутизации, порт моста и файл имён таблиц тоже свои — см. TABLE_BASE
 * в src/model/registry.c и TGWS_PORT_BASE ниже. Числа — в файле профиля src/profile/tgws.c;
 * поле метки из него подменяет поле таблицы роутера (plat(), src/platform/platform.c). */

/* РАСКЛАДКА — ДАННЫЕ ПЛАТФОРМЫ, а не константы сборки (src/platform/platform.h): поле метки у
 * телефона другое (биты 22-27, почему — src/platform/android.c), и один бинарник выбирает
 * платформу при запуске. Имена остались прежними, заглавными, чтобы выражения по всему движку
 * не менялись, но за каждым стоит чтение таблицы выбранной платформы, а не число: в #if, в
 * размере массива и в статическом инициализаторе их писать нельзя. */
#define STEER_MARK_BASE (plat()->mark_base)
#define STEER_MARK_BITS (plat()->mark_bits)
#define STEER_MARK_MASK (plat()->mark_mask)
/* Номера первого и последнего бита поля — для сообщений человеку («биты 20-27»). Числом из
 * базы, а не строкой: у телефона поле другое, и записанные руками «20-27» в
 * предупреждении врали бы ровно там, где его читают реже всего. */
#define STEER_MARK_LOBIT (__builtin_ctz(STEER_MARK_BASE))
#define STEER_MARK_HIBIT (STEER_MARK_LOBIT + STEER_MARK_BITS - 1)

/* ПРИОРИТЕТ ПРАВИЛ ip rule, по которым помеченный трафик уходит в таблицу выхода, и правила
 * пробы сторожа. На роутере приоритет не указывается вовсе (0 — не передавать pref): ядро
 * ставит правило сразу перед первым ненулевым, то есть выше main (32766). На телефоне — ниже
 * лестницы netd (почему — src/platform/android.c). */
#define STEER_RULE_PREF  (plat()->rule_pref)
#define STEER_PROBE_PREF (plat()->probe_pref)
/* Бит перемаршрутизации каналов на сам телефон в старой раскладке, метка собственного трафика
 * движка, бит собственного трафика туннеля через via и первый UID приложений — всё это есть
 * только у платформы с каналами на само устройство (подробно — у значений в
 * src/platform/android.c). На роутере все четыре — ноль: «нет такого». */
#define STEER_REROUTE_BIT (plat()->reroute_bit)
#define STEER_SELF_MARK   (plat()->self_mark)
#define STEER_TUNNEL_BIT  (plat()->tunnel_bit)
#define STEER_APP_UID_MIN (plat()->app_uid_min)

/* СКОЛЬКО ВЫХОДОВ ВЛЕЗАЕТ В ПОЛЕ МЕТКИ.
 *
 * Раньше выход получал БИТ: метка была `база << номер`, и восемь бит поля значили ровно
 * восемь помеченных выходов. Поле расширить нельзя — слева от нашего диапазона бит 28 у
 * мини-сборки, 29 и 30 у zapret, а справа 16-23 занимают Tailscale и pbr (и уже заходят в
 * наше поле на битах 20-23, см. выше), — поэтому выходу
 * выдаётся ЗНАЧЕНИЕ: `база * (место + 1)`. Правило разметки пишет `mark and ~МАСКА or
 * метка`, а правило маршрутизации сравнивает `mark and МАСКА == метка`, и обоим
 * безразлично, одинокий там бит или число: в поле помещается столько выходов, сколько в
 * нём умещается ненулевых значений, то есть 255 вместо 8.
 *
 * Раньше число выходов дополнительно резалось константой MAX_OUTPUTS = 16 «по номерам таблиц»
 * (300..315, дальше стояла мини-сборка). Константы больше нет: пределом служит само поле,
 * а мини-сборке с её единственной таблицей 316 место оставлено внутри ряда (steer_slot_table
 * в model/registry.c пропускает этот номер), поэтому полный движок не упирается в неё.
 *
 * ЧТО ИЗ ПОЛЯ НЕЛЬЗЯ РАЗДАВАТЬ. Значения раздаются не подряд, и причин две, обе — про соседей,
 * которые метят пакеты в тех же битах (STEER_MARK_NEIGHBOURS ниже):
 *   - Чужая цепочка (Tailscale, pbr) может перезаписать биты 16-23 — у нас это младшие биты
 *     поля, `cm` ниже — и обнулить их. Метка, которая после этого совпала бы с ДРУГОЙ нашей
 *     меткой, увела бы пакет в чужой туннель, а не потеряла бы выход. Метки 1..P (P = cm + 1;
 *     на роутере 16) после обнуления становятся нулём или собой — это прежняя раздача, и её
 *     номера сохранены как есть. Дальше раздаются только значения со ВСЕМИ старшими битами
 *     не совпадающими с уже выданной меткой: старшая часть h >= 2 и ненулевая младшая l; тогда
 *     обнулённое `h * P` не выдаётся никому. Число h == FIELD_MAX / P (все старшие биты
 *     единицы) не раздаётся вовсе — это STEER_INGRESS_SEEN, «разобран на ingress, выхода нет».
 *   - Итог на роутере (8 бит, P = 16): 16 прежних + 13 * 15 = 211 мест. Это НАСТОЯЩИЙ предел
 *     числа выходов с меткой, и он свойство раскладки: чтобы его поднять, надо менять поле
 *     метки, а поле менять нельзя (контракт, docs/contract-v1.md). У телефона (6 бит, P = 4) —
 *     4 + 13 * 3 = 43. У мини-сборки (1 бит) — 1. Отказ при нехватке мест называет эту цифру
 *     (registry_assign). */
#define STEER_MARK_FIELD_MAX ((1u << STEER_MARK_BITS) - 1u)
#define STEER_MARK_NEIGHBOURS 0x00ff0000u
/* Младшие биты поля, которые сосед может обнулить: как значение поля (на роутере 0x0f). */
static inline unsigned steer_mark_clobber(void) {
    return (unsigned)((STEER_MARK_MASK & STEER_MARK_NEIGHBOURS) / STEER_MARK_BASE);
}
/* Сколько мест раздаётся из поля (см. выше). */
static inline unsigned steer_mark_slots(void) {
    unsigned fm = STEER_MARK_FIELD_MAX, cm = steer_mark_clobber(), p = cm + 1u;
    if (!cm) return fm;                         /* мини-сборка: соседей в поле нет */
    unsigned top = fm / p;
    if (top < 2u) return p - 1u < fm ? p - 1u : fm;
    return p + (top - 2u) * (p - 1u);
}
/* Значение поля метки (1-based) места slot и обратно (-1 — такое значение не раздаётся). */
static inline unsigned steer_slot_value(unsigned slot) {
    unsigned cm = steer_mark_clobber(), p = cm + 1u;
    if (!cm || slot < p) return slot + 1u;
    unsigned k = slot - p;
    return (2u + k / (p - 1u)) * p + 1u + k % (p - 1u);
}
static inline int steer_value_slot(unsigned v) {
    unsigned fm = STEER_MARK_FIELD_MAX, cm = steer_mark_clobber(), p = cm + 1u;
    if (v < 1u || v > fm) return -1;
    if (!cm || v <= p) return (int)(v - 1u) < (int)steer_mark_slots() ? (int)(v - 1u) : -1;
    unsigned h = v / p, l = v % p;
    if (!l || h < 2u || h >= fm / p) return -1;
    return (int)(p + (h - 2u) * (p - 1u) + (l - 1u));
}
#define STEER_MARK_SLOTS (steer_mark_slots())

/* «РАЗОБРАН НА INGRESS, ВЫХОДА НЕТ» — значение поля метки, которым цепочка ingress_mark
 * говорит цепочке prerouting_mark: «этот пакет я уже проверила по всем правилам, и ни одно не
 * дало ему метки выхода» (совпало правило direct или не совпало ничего). Подробно, зачем
 * prerouting надо это знать, — у построителя в compile/generate.c, «разметка на ingress».
 * Живёт значение от хука ingress до prerouting_mark (mangle + 1), и там оно снимается: дальше
 * пакет идёт с тем же пустым полем, что и без ingress.
 *
 * КАКОЕ ЗНАЧЕНИЕ. Все биты нашего поля, КРОМЕ общих с Tailscale и pbr (0x00ff0000, см. выше):
 * на роутере это 0x0f000000, биты 24-27. Требований три, и каждое закрывает свою поломку.
 *   - Не метка выхода: выходы получают `база * значение` по steer_slot_value (значения 1..16 и
 *     дальше только те, чьи старшие биты не все единицы), а здесь 240 — оно из раздачи
 *     исключено. Совпади оно с меткой выхода — пакет «без выхода» ушёл бы в чужой туннель.
 *   - Не задевает биты 16-23. Между ingress и нашей prerouting_mark отрабатывают чужие цепочки
 *     prerouting (mangle у pbr и mwan3, -150). Правило, которое проверяет «помечен ли уже пакет
 *     маской 0x00ff0000», увидело бы наше значение на КАЖДОМ пакете локальной сети и перестало
 *     бы действовать вовсе — а без ingress оно на таких пакетах видит ноль.
 *   - Переживает чужую перезапись битов 16-23 (`mark and 0xff00ffff xor …` — так метят
 *     Tailscale и pbr): у значения там нулей нет, и оно остаётся собой. А метки выходов 1..15
 *     лежат ЦЕЛИКОМ в битах 20-23 и от такой перезаписи становятся нулём, метка 16 — целиком в
 *     бите 24 и остаётся собой. Ни одна из них не превращается в ДРУГУЮ нашу метку, и
 *     prerouting, не узнав значения, разбирает пакет заново — как без ingress.
 * У мини-сборки tgws поле из одного бита, и места под такое значение в нём нет (оно совпало бы с
 * её единственной меткой): steer_ingress_seen_ok() отвечает «нет», и её разметка остаётся на
 * prerouting. */
#define STEER_INGRESS_SEEN (STEER_MARK_MASK & ~STEER_MARK_NEIGHBOURS)
static inline int steer_ingress_seen_ok(void) {
    uint32_t v = STEER_INGRESS_SEEN;
    /* Значение не раздаётся никому из выходов (steer_value_slot его не знает). */
    return v && v % STEER_MARK_BASE == 0 && steer_value_slot(v / STEER_MARK_BASE) < 0;
}

/* МЕТКА, КОТОРОЙ МЕТИТЬ СОБСТВЕННЫЙ ТРАФИК ТУННЕЛЯ ВЫХОДА o (сокет наверх клиента vless/xsteer/
 * обфускатора, WGDEVICE_A_FWMARK у выхода awg).
 *
 * При `via` — метка выхода-цели: по ней ip rule цели уводит пакет в её таблицу, то есть в её
 * устройство. Метка у цели появляется в registry_assign, поэтому звать эту функцию можно только
 * после него — до реестра она вернула бы «мимо каналов», то есть «напрямую», молча.
 *
 * Без `via` — обычное «мимо каналов». На роутере это ноль (сокет не метится вовсе): трафик самого
 * роутера каналы не трогают, они на prerouting. На телефоне — STEER_SELF_MARK, значение «сам
 * движок»: маршрута на него нет (пакет идёт обычным путём сети netd), зато его узнают заворот DNS
 * приложений (не заворачивает туннель с сервером на 53-м порту обратно к резолверу) и список
 * соединений. Поля netd в этом значении нулевые, а FwmarkServer при connect() переписывает
 * только свои поля — наши биты 22-27 он оставляет, как оставляет их резолверу.
 *
 * Возвращается ЗНАЧЕНИЕ поля (биты STEER_MARK_MASK), без чужих битов — кроме одного нашего: на
 * телефоне при via к метке цели добавлен STEER_TUNNEL_BIT (он вне поля и маршрутизации не
 * касается). Сокет, которому ставят метку целиком, других битов не несёт, а кто ставит её поверх
 * своей (netd), тот сам сохраняет свои поля. */
static inline uint32_t out_underlay_mark(const struct spec *sp, const struct output *o) {
    const struct output *v = out_over(sp, o);
    /* Цель без метки (реестр ещё не прочитан) — «напрямую»: метка 0 значила бы ровно то же, но
     * на телефоне «мимо каналов» — это значение «сам движок», а не ноль. */
    /* На телефоне к метке цели — бит «собственный трафик туннеля»: по нему заворот DNS на output
     * пропускает туннель, чей сервер слушает 53-й порт (см. STEER_TUNNEL_BIT). На роутере бит
     * и «сам движок» — нули, и остаётся метка цели или ноль. */
    if (v && v->mark) return v->mark | STEER_TUNNEL_BIT;
    return STEER_SELF_MARK;
}

/* ИМЯ ТАБЛИЦЫ ПРАВИЛ — НЕ КОНСТАНТА, потому что движок на роутере бывает не один.
 *
 * Рядом с полным движком ставится микропакет tgws: своя спека, своё состояние, свой бинарник
 * с другим именем. Таблица же у обоих называлась `steer`, а `nft -f` со своим определением
 * таблицы ЗАМЕЩАЕТ её целиком — то есть кто применил спеку последним, тот и стёр правила
 * другого. Из-за этого микропакет отказывался работать рядом с полным движком вовсе; отказ
 * владелец потребовал убрать: «stgws должен работать параллельно со steer, не глядя,
 * установлен он или нет».
 *
 * Имя берётся из STEER_NFT_TABLE, умолчание прежнее. Проверка символов не педантизм: имя
 * уходит в командную строку nft, и пробел или кавычка в нём означали бы чужую команду.
 *
 * В заголовке, а не в компиляторе (src/compile): имя нужно и сторожу (failover.c, набор
 * failopen), а сторож собирается и без компилятора — стенды компонуют его файл отдельно. Кэш у каждой единицы
 * трансляции свой, но переменная окружения на процесс одна, так что ответ у всех одинаков. */
static inline const char *nft_table(void) {
    static const char *cached;
    if (cached) return cached;
    const char *e = getenv("STEER_NFT_TABLE");
    cached = "steer";
    if (e && *e && strlen(e) < 32) {
        const char *p = e;
        for (; *p; p++)
            if (!((*p >= 'a' && *p <= 'z') || (*p >= 'A' && *p <= 'Z') ||
                  (*p >= '0' && *p <= '9') || *p == '_' || *p == '-'))
                break;
        if (!*p) cached = e;
    }
    return cached;
}

/* ---- биты, которыми объясняются с zapret ------------------------------------
 *
 * Все три принадлежат НЕ НАМ: значения задал zapret, и мы их только соблюдаем. Взяты они не
 * из документации, а из живого набора правил на роутере — /etc/config/zapret объявляет
 * `DESYNC_MARK 0x40000000` и `DESYNC_MARK_POSTNAT 0x20000000`, и оба бита стоят в условиях
 * его цепочек (postnat_hook, predefrag, predefrag_nfqws; полная выписка — у генерации
 * цепочки zapret_queue, zapret_chains в src/kinds/zapret.c).
 *
 * ZAPRET_SKIP_MARK мы СТАВИМ САМИ, и это единственный способ сказать системному обходу «этот
 * трафик не твой»: его цепочка входит по условию `meta mark & 0x40000000 == 0`.
 *
 * Ставится он трафику ВСЯКОГО выхода, кроме kind=direct (кому именно и почему — у
 * out_skips_zapret выше). Сначала он стоял только у kind=zapret, где без него трафик
 * разбирали бы двое — сначала общий обход своей стратегией, потом наш экземпляр своей, — и
 * вышло бы не то, что выбрал человек, ни в одном из двух смыслов. Потом выяснилось, что у
 * туннельных выходов беда не меньше, только другая: обходу там разбирать нечего (снаружи
 * виден сам туннель), а рассинхронизировать ВНЕШНИЕ пакеты он всё равно принимается, и
 * рукопожатие туннеля может не сойтись. Проверить это глазами нельзя ни в том, ни в другом
 * случае: правила у обоих выглядят исправно.
 *
 * НО ДО НАШЕГО ОБРАБОТЧИКА ЭТОТ БИТ ДОЕЗЖАТЬ НЕ ДОЛЖЕН: nfqws считает своим порождённым
 * любой пакет, у которого с его --dpi-desync-fwmark есть общий бит, а в ZAPRET_OWN_MARK бит
 * 0x40000000 входит. Поэтому цепочка очереди снимает его с пакета перед `queue` — см.
 * zapret_queue (zapret_chains в kinds/zapret.c) и почему без этого выход не обрабатывал ни одного пакета.
 *
 * ZAPRET_OWN_MARK — то, чем метит свои пакеты НАШ экземпляр (ключ --dpi-desync-fwmark). В нём
 * подняты ОБА бита, и каждый нужен по своей причине. 0x40000000 уводит порождённые пакеты и
 * от общего обхода, и — главное — в цепочку predefrag_nfqws, где их снимают с учёта
 * conntrack: без этого ядро отбрасывает их как INVALID, то есть обход перестаёт работать
 * совсем. Такая цепочка есть у zapret, но она пропадает вместе с его службой, поэтому своя
 * (zapret_predefrag) стоит и в нашей таблице — см. zapret_chains в kinds/zapret.c. 0x20000000
 * (ZAPRET_MINE_BIT) выводит их из НАШЕЙ очереди.
 *
 * Почему нельзя одним битом: у исходного пакета и у порождённого 0x40000000 есть у обоих, и
 * различить их в цепочке нечем — один бит на двоих дал бы либо круг (свой пакет снова в свою
 * очередь), либо неразобранный исходный.
 *
 * Диапазон свободен от нас: наши восемь бит — 0x0FF00000, зонные метки fw4 живут в младшем
 * слове (проверено на роутере: кроме перечисленного и нашей маски, в наборе правил меток
 * нет). */
#define ZAPRET_SKIP_MARK 0x40000000u
#define ZAPRET_OWN_MARK  0x60000000u
#define ZAPRET_MINE_BIT  0x20000000u

/* Сколько первых пакетов соединения отдавать обработчику.
 *
 * Без предела в userspace уезжает КАЖДЫЙ пакет соединения: весь поток видео идёт через
 * копирование в nfqws и обратно, и на 880 МГц это не «немного дороже», а другой порядок
 * пропускной способности. Обходу нужны только первые пакеты — там SYN, ClientHello и QUIC
 * Initial. Девять — число самого zapret (NFQWS_TCP_PKT_OUT и NFQWS_UDP_PKT_OUT в его
 * /etc/config/zapret, умолчание), и брать другое значило бы спорить с автором обхода о его
 * же стратегиях: они писались под этот предел. */
#define ZAPRET_FIRST_PACKETS 9

/* Номер очереди nfqueue у выхода kind=zapret ВЫВОДИТСЯ ИЗ МЕТКИ, а не задаётся в спеке.
 *
 * Второе поле в спеке означало бы второй источник правды о том, какой процесс какой трафик
 * разбирает, и первое же расхождение выглядело бы как «стратегия применилась, но не
 * действует». Метка выхода уже уникальна и уже переживает перезапуск (реестр в
 * /var/lib/steer/registry), поэтому номер очереди из неё выводится однозначно и стабильно.
 *
 * База 8300 выбрана подальше от того, чем пользуется сам zapret: его init-скрипт на OpenWrt
 * раздаёт номера с 200, и пересечение означало бы, что два процесса слушают одну очередь —
 * ядро отдаст пакет одному из них, и какому именно, зависит от порядка запуска. */
#define ZAPRET_QUEUE_BASE 8300

/* МЕСТО ВЫХОДА В РЕЕСТРЕ, выведенное из его метки. Метка — это `база * (место + 1)`,
 * поэтому место читается делением. Прежняя раздача давала биты (`база << номер`), и метка
 * из старого реестра даёт здесь не номер бита, а его степень двойки: 0, 1, 3, 7, 15 и
 * дальше. Это НЕ ошибка — от места требуется только быть своим у каждого выхода, а
 * распорядитель (registry_assign) держит занятые места и новому выходу их не выдаёт. */
static inline int out_mark_slot(const struct output *o) {
    uint32_t m = o->mark / STEER_MARK_BASE;
    return m ? (int)(m - 1) : 0;
}

/* Номер очереди выхода. Из метки: место выхода в реестре — это и есть его номер. */
static inline int out_zapret_queue(const struct output *o) {
    return ZAPRET_QUEUE_BASE + out_mark_slot(o);
}

/* ---- выход kind=tgws: Telegram через веб-сокет --------------------------------------
 *
 * ЧТО ЭТО. Telegram ходит в свои дата-центры по TCP на их адреса, и там его и режут. Но у
 * веб-клиента есть второй путь: тот же протокол MTProto, завёрнутый в WebSocket поверх TLS
 * к `wss://kwsN.web.telegram.org/apiws`, а эти имена стоят за Cloudflare — блокировать их
 * означает блокировать Cloudflare. Выход этого вида ПЕРЕХВАТЫВАЕТ соединения приложения с
 * дата-центрами и уводит их этим путём, поэтому в самом приложении ничего настраивать не
 * надо (в отличие от прокси, которому в клиенте прописывают адрес и секрет).
 *
 * ПОЧЕМУ ПОТОК ИДЁТ НАСКВОЗЬ, А НЕ ПЕРЕШИФРОВЫВАЕТСЯ. Обфускация MTProto к дата-центру
 * ключей не согласовывает: клиент шлёт 64 случайных байта, и ключ с вектором — это байты
 * [8..40] и [40..56] ПРЯМО ИЗ НИХ, без секрета (секрет подмешивается только у MTProxy, см.
 * core.telegram.org/mtproto/mtproto-transports). Дата-центр за веб-сокетом ждёт ровно такой
 * же пакет. Значит поток клиента годится как есть: мы отдаём его 64 байта первым бинарным
 * кадром и дальше переливаем байты в обе стороны, ничего не расшифровывая. Читать переписку
 * нечем и не нужно — прикладной слой всё равно закрыт auth_key.
 *
 * ЧТО ВСЁ-ТАКИ ПРАВИТСЯ. В хвосте [56..64] лежат метка транспорта и НОМЕР ДЦ (signed LE,
 * отрицательный — медийный). У прямого соединения номера там нет, там случайные байты, а
 * точке `apiws` он нужен. Мы его вписываем: расшифровываем хвост теми же сырыми ключами,
 * подставляем номер и шифруем обратно. Ключи при этом не меняются — они выводятся из байт
 * [8..56], которых мы не трогаем, — поэтому остаток потока остаётся верным.
 *
 * ОТКУДА НОМЕР ДЦ. Из АДРЕСА НАЗНАЧЕНИЯ, а не из рукопожатия: у прямого соединения его в
 * рукопожатии нет. Адреса дата-центров публичные и меняются редко; неизвестный адрес мы не
 * перехватываем вовсе — пусть идёт как шёл. Это единственный безопасный ответ: увести
 * соединение не в тот дата-центр значит сломать то, что работало.
 *
 * ЗВОНКИ СЮДА НЕ ПОПАДАЮТ. Голос идёт отдельным каналом по UDP (P2P или через рефлекторы),
 * MTProto участвует только в установке звонка. Перехват здесь только TCP, и это не
 * недоделка: завернуть UDP в этот веб-сокет нечем. Кому нужны звонки — тому туннель. */
/* Первый порт — данные профиля (src/profile/profile.h): у мини-сборки tgws свой ряд (8490..),
 * почему — в src/profile/tgws.c. */
#define TGWS_PORT_BASE (prof()->tgws_port_base)

/* Порт, на котором ждёт мост этого выхода. Выводится из метки по той же причине, что номер
 * очереди у zapret: второе поле в спеке — это второй источник правды. */
static inline int out_tgws_port(const struct output *o) {
    return TGWS_PORT_BASE + out_mark_slot(o);
}

/* Порт слушателя TCP модуля этого выхода (KC_TCP_REDIR, R-152): туда правило nat перенаправляет
 * TCP клиентов, чья метка ведёт в выход. Из метки — по той же причине, что порт моста: модуль и
 * демон выводят его каждый сам, и второго поля в спеке, которое могло бы разойтись, нет. */
#define TCP_PORT_BASE (prof()->tcp_port_base)
static inline int out_tcp_port(const struct output *o) {
    return TCP_PORT_BASE + out_mark_slot(o);
}

