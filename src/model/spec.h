/* Кому ПРИНАДЛЕЖИТ устройство: выход, чей процесс его создал (vless, xsteer). NULL, если
 * такого нет, — тогда устройством владеет система, и отвечает за него сам выход.
 *
 * Заведено потому, что одно и то же устройство может быть названо ДВАЖДЫ: сначала выходом,
 * который его создаёт, а потом — членом группы, собранной из разнородных туннелей с порядком
 * предпочтения (локация подписки, wireguard, хаб xsteer в одном пуле `devices` спеки v1 —
 * перевод делает из каждого устройства безымянный член-интерфейс). Так его собирает интерфейс
 * splify2, и так его может написать человек руками.
 *
 * Всё, что решается ВИДОМ выхода, но относится к устройству, обязано спрашивать здесь, а не
 * у выхода, который устройство назвал: мера здоровья и способ оживления (failover.c), нужен
 * ли masquerade (apply и diag). Иначе у группы с устройством
 * VLESS-туннеля проба была бы ICMP, который через него не идёт принципиально, а диагностика
 * требовала бы masquerade, которого этому устройству не нужно.
 *
 * Ищется только среди выходов out_engine_managed: устройство, которым владеет netifd, ничьей
 * собственностью здесь не считается, и обычный wireguard в пуле проверяется как прежде.
 * Совпадение имён (выход kind=xsteer, названный «wg0» при живом интерфейсе wg0) остаётся
 * ошибкой настройки: два разных устройства с одним именем система и сама не различит.
 *
 * Объявлена здесь, а определена в failover.c — тот же случай, что bind_device: спрашивают её
 * из трёх мест, а живёт она там, где появилась первая нужда. Переносить определение в модель
 * (src/model) нельзя без потерь: стенд failovermatch компилирует failover.c со своими выходами и без
 * парсера, и копия функции в стенде стала бы вторым источником правды, который разойдётся с
 * первым молча. */
const struct output *device_owner(const struct spec *sp, const char *dev);
/* Тот же вопрос с готовым запасным ответом: владелец устройства, а если владельца нет — сам
 * выход. Отдельно от device_owner, потому что все три места зовут именно эту форму, и
 * `owner ? owner : o` в каждом из них — три шанса забыть его в одном. */
const struct output *out_for_device(const struct spec *sp, const struct output *o, const char *dev);

/* Заполнить `device` каждого выхода тем устройством, через которое трафик идёт СЕЙЧАС.
 *
 * Зовут её команды, читающие спеку своим процессом: apply — перед привязкой таблиц, status
 * и diag — перед тем, как рассказывать о выходе. Без неё `device` у них означает первого
 * кандидата, то есть предпочтение, а не факт, и пул с рабочим запасным устройством
 * выглядит сломанным. Порядок выбора и его доводы — у определения в failover.c. */
void outputs_adopt_active(struct spec *sp);

/* ЗАПАСНОЙ ЗАПРЕТ В ТАБЛИЦЕ ВЫХОДА С on_fail=drop: `blackhole default metric <это>`.
 *
 * Маршрут выхода — `default dev X` — ссылается на устройство, и когда устройство исчезает, ядро
 * вычищает маршрут само, в тот же миг: TUN помощника пропадает вместе с процессом (supervise
 * перезапускает его через пять секунд и дольше), устройство awg пересоздаётся при смене модуля,
 * интерфейс падает. Таблица становится пустой, а пустая таблица — это не «нет пути», а «ищи
 * дальше»: помеченный пакет уходит по main, напрямую, и так до следующего прохода сторожа (до
 * минуты) или до привязки нового TUN. Для выхода, который обещал «лучше ничего, чем мимо
 * туннеля», это утечка, и её не закрыть никаким порядком команд — её создаёт ядро.
 *
 * Поэтому у такого выхода в таблице всегда лежит второй маршрут по умолчанию — запрет с
 * наибольшей метрикой. Пока есть маршрут в устройство (метрика 0), решает он; исчез — остаётся
 * запрет, и пакет отбрасывается, а не утекает. Сверка сторожа запасной запрет за «запрет в
 * таблице» не считает (иначе живой выход выглядел бы упавшим), а у выхода с direct/zapret его
 * нет вовсе: пустота там — обещанное поведение. Число — любое заметно большее нуля; взято
 * круглое, чтобы строку `ip route show` было видно глазами. */
#define STEER_BACKSTOP_METRIC 65535

/* ---- подложка: `over` (прежнее `via`) -------------------------------------------------
 *
 * ЗАЧЕМ. Туннель одного выхода бывает нужно пустить ВНУТРИ другого: WireGuard, у которого UDP
 * к серверу режут, — внутри VLESS (пример владельца: выход awg поверх выхода vless), или
 * наоборот, VLESS, чей сервер виден только из сети WireGuard, — внутри интерфейса. Правила
 * здесь ни при чём: они решают, в какой выход идёт трафик КЛИЕНТОВ, а `over` решает, куда
 * идёт трафик САМОГО ТУННЕЛЯ — его соединение с сервером. В спеке v1 поле зовётся `via`, перевод
 * кладёт его сюда; в спеке v2 слово `via` больше ничего не значит.
 *
 * КАК. Ровно тем же механизмом, которым движок и так ведёт трафик в выход: меткой. У выхода-
 * цели уже есть своя метка, ip rule «fwmark метка/маска → таблица выхода» и маршрут по
 * умолчанию в его устройство. Сокет наверх внутреннего выхода получает метку выхода-цели
 * (SO_MARK у клиентов vless, xsteer и обфускатора; WGDEVICE_A_FWMARK у выхода awg), и ядро
 * уводит его пакеты в таблицу цели при поиске маршрута — ещё до того, как пакет родился:
 * connect() на помеченном сокете выбирает и устройство, и адрес источника по таблице цели.
 * Новых правил ip rule для этого не нужно, и каналы трафик туннеля не трогают — он локальный
 * (хук output), а каналы роутера живут на prerouting, каналы телефона — на output только для
 * приложений (skuid от 10000), а помощники движка работают под root. Вывод generate() от `over`
 * зависит в одном месте, и только на телефоне: заворот DNS приложений на output берёт и root
 * (DnsResolver), поэтому туннель пропускается по своему биту — см. STEER_TUNNEL_BIT.
 *
 * ЧТО С ОТКАЗОМ. Если выход-цель лёг, внутренний туннель по нему не доедет — поэтому сторож
 * считает внутренний выход нерабочим, пока лежит цель, и применяет ЕГО on_fail к его
 * каналам (failover.c). Проб и таймеров ради этого не заводится: ответ «цель жива» у сторожа
 * уже есть в том же проходе, выходы просто обходятся в порядке зависимостей. Сам транспорт
 * внутреннего туннеля при этом подчиняется on_fail ЦЕЛИ: при drop в её таблице blackhole и
 * соединение не встанет, при direct её правило снято и транспорт уйдёт обычным путём.
 *
 * Глубина цепочки — не больше MAX_OVER_DEPTH переходов: каждый слой — это заголовки и
 * шифрование ещё раз, и цепочка длиннее трёх означает скорее описку, чем замысел. */
#define MAX_OVER_DEPTH 3

/* Выход, у которого ЕСТЬ СВОЙ СОКЕТ НАВЕРХ, — только ему `over` и имеет смысл: метку ставит тот,
 * кто открывает соединение с сервером. vless и xsteer — наш процесс; interface с obfs — наш
 * обфускатор (его сырой сокет к серверу обфускации несёт UDP WireGuard); awg — ядро WireGuard,
 * но настраивает его движок, и метку сокета туннеля он задаёт сам (WGDEVICE_A_FWMARK, src/kinds/awg.c).
 * Обычный interface — НЕТ: его сокет открывает ядро WireGuard по настройке netifd, и метку ему
 * ставить не нам. Бит KC_OVER: у interface он зависит от obfs и приходит из caps_of вида. */
static inline int out_over_capable(const struct output *o) { return out_has_cap(o, KC_OVER); }

/* Годится ли выход в подложки `over`: у него должны быть устройство и таблица маршрутизации, иначе
 * метке некуда вести. Это ровно out_has_device (interface, vless, xsteer, awg) — direct, zapret
 * и tgws отпадают (у первых двух
 * пакет уходит обычным маршрутом, у tgws перехват стоит на prerouting и трафика самого роутера
 * не касается). Отдельным именем, а не прямым вызовом, чтобы смысл читался в проверке. */
static inline int out_over_target_ok(const struct output *o) {
    return out_has_device(o);
}

/* Подложка выхода или NULL, если её нет. Поиск по sp->out, а не out_by_name: этот заголовок
 * включают стенды без парсера (failovermatch), и функция из parse.c у них не собралась бы. */
static inline const struct output *out_over(const struct spec *sp, const struct output *o) {
    if (!o->over[0]) return NULL;
    for (size_t i = 0; i < sp->out_n; i++)
        if (!strcmp(sp->out[i].name, o->over)) return &sp->out[i];
    return NULL;
}

/* Сколько переходов over от выхода до выхода без подложки: 0 — туннель идёт напрямую. Нужна тем, кто
 * обходит выходы в порядке зависимостей (сторож, супервизор помощников): цель — раньше
 * зависящего. Спека круги и цепочки длиннее MAX_OVER_DEPTH отвергает (over_check в v1.c);
 * предел здесь — только чтобы стенд, собирающий выходы в обход парсера, не зациклился. */
static inline int out_over_depth(const struct spec *sp, const struct output *o) {
    int d = 0;
    for (const struct output *t = out_over(sp, o); t && d < MAX_OVER_DEPTH; t = out_over(sp, t)) d++;
    return d;
}

