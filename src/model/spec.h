/* ГРУППА ВЫХОДОВ (kind: group, src/kinds/group.c; docs/architecture.md, «4в»).
 *
 * Группа — тоже выход: своя метка, своя таблица, свой on_fail, её выбирает правило. Трафик она
 * отдаёт одному из членов, и КАК выбрать, говорит pick:
 *   order   — первый живой по порядку members (прежний пул `devices`);
 *   latency — самый быстрый с допуском (прежний `prefer: latency`), замер — urltest;
 *   manual  — член, выбранный командой `select` (или default до первой команды);
 *   balance — ядро раскидывает новые соединения по живым членам (карта numgen, метка
 *             соединения), и спека v1 такого не рождает.
 * Члены — индексы в sp->out: и именованные выходы (в том числе другие группы), и безымянные,
 * которых рождает перевод v1 (по выходу на устройство). Индекс, а не указатель: struct spec
 * копируется значением (стенды, сверка), и указатель в копии смотрел бы в оригинал. */
enum group_pick { PICK_ORDER = 0, PICK_LATENCY, PICK_MANUAL, PICK_BALANCE };
/* balance: чем ядро выбирает слот нового соединения (ключ `by`, docs/spec-v2.md). CONNECTION —
 * случайно, каждое соединение само по себе; SITE — хеш адреса назначения: один сайт — один член
 * (consistent-hashing у Clash); SITE_CLIENT — хеш пары «адрес клиента, адрес назначения»: сайт у
 * одного устройства — на одном члене (sticky-sessions). Порядок — как в спеке (group_by_name). */
enum group_by { BY_CONNECTION = 0, BY_SITE, BY_SITE_CLIENT };

struct group_cfg {
    enum group_pick pick;
    /* Арена спеки (group_members_alloc): members, weight, alive, lat_ms, lat4_ms, lat6_ms — все
     * на members_n записей. Номер члена < SPEC_ANON_BASE — именованный выход, иначе безымянный
     * (spec_out). */
    unsigned *members;
    size_t members_n;
    /* manual: номер члена по умолчанию — выбор до первой команды select; -1 — первый. */
    int def;
    /* latency: допуск и интервал замера. Допуск: -1 — не задан (умолчание GROUP_TOL_DEFAULT_MS),
     * 0..60000 — задан человеком, и ноль здесь настоящее значение — «без допуска, побеждает самый
     * быстрый» (прежде 0 читался как «не задан», и человек, поставивший 0, получал 50, —
     * group_tolerance_ms). Интервал: 0 — не задан (GROUP_INT_DEFAULT_S), у заданного нижний
     * предел 5, так что ноль занят однозначно (group_interval_s). Числа умолчаний взяты у
     * sing-box: интервал 3 минуты, допуск 50 мс. */
    int lat_tolerance_ms;
    int lat_interval_s;
    /* latency: адрес проверки urltest (пусто — GROUP_URL_DEFAULT, src/kinds/grpurl.h) и сколько
     * секунд без трафика через группу замер не делается (-1 — умолчание платформы, 0 — мерить
     * всегда). Строка в самой настройке, а не указатель: struct spec копируется значением. */
    char url[192];
    int idle_timeout_s;
    /* balance: вес члена (1..100; 0 — не задан, то есть 1) — доля новых соединений. */
    unsigned char *weight;
    /* balance: чем раздаются новые соединения (enum group_by); 0 — случайно. */
    int by;
    /* СОСТОЯНИЕ, а не настройка (как device и failed у выхода): что сторож выбрал в последнем
     * проходе. Заполняет outputs_adopt_active_st из памяти сторожа, разбор оставляет -1/нулями.
     * У группы с именованными членами cur и alive — решение подхвата по приговорам членов
     * (fog_pick_known): то же, что примет проход, поэтому есть и до первого прохода.
     * cur — номер выбранного члена (-1 — нет: отказ или сторож не проходил); alive — по байту на
     * члена, 1 — жив; sel — выбор человека у manual (-1 — нет, действует def); lat_ms — задержка,
     * по которой выбирает сторож (-1 — не измерен); lat4_ms, lat6_ms — замеры по IPv4 и IPv6,
     * когда группа мерилась по обоим (-2 — по семействам не мерили: lat_ms и есть замер IPv4). */
    int cur;
    unsigned char *alive;               /* по байту на члена: 1 — жив (раньше маска в 32 бита) */
    int sel;
    int *lat_ms;
    int *lat4_ms, *lat6_ms;
    /* Свойства группы — пересечение свойств её членов (group_seal в src/kinds/group.c): у пула
     * интерфейсов это ровно свойства интерфейса. Считаются один раз, когда члены известны, —
     * вопрос out_caps приходит без спеки, и спросить членов ему нечем. */
    unsigned caps;
    /* Вид, которым группа видна снаружи (status, `outputs --kind`, подписи сверки). Перевод v1
     * ставит сюда вид прежнего выхода — interface, — и всё видимое снаружи остаётся прежним до
     * контракта v2 (шаг 3). NULL — «group». */
    const struct kind_ops *shown;
};

/* Что спека написала в ключах видов — до того, как известен вид (ключ `kind` может стоять в
 * объекте последним). Заполняет их читатель формата — model/v1.c из JSON, model/v2.c из дерева
 * YAML, — вид получает готовые значения (kind_ops.parse) и решает, что они значат; общий разбор
 * по битам kind_ops.keys отказывает ключу чужого вида. */
struct out_keys {
    struct out_obfs obfs;       /* obfs.on — ключ задан и разобран */
    char sub_file[256];
    char conf[256];
    char opts_file[256];
    char domain[128];
    int stream, stream_port;
    int *nodes;                 /* арена спеки, nodes_n записей (NULL при 0) */
    size_t nodes_n, nodes_cap;  /* nodes_cap ведёт spec_push у читателя формата */
    /* Какой из двух форм записан выбор узлов: `node` (сокращение) или `nodes` (список). */
    int node_one, node_many;
    unsigned transports;        /* `transport:` спеки v2 (vless_cfg.transports) */
    int insecure;               /* `insecure:` спеки v2 (vless_cfg.insecure) */
    struct node_exclude excl;   /* `exclude:`, `exclude_name:` спеки v2 (vless_cfg.excl) */
    struct tun_pool pool;       /* `active`, `by`, `interval`, `silence` спеки v2 (struct tun_pool) */
    int by_set;                 /* `by` записан (у него ноль — значение connection) */
    /* `devices` спеки v1 — кандидаты в порядке предпочтения. В модели поля нет: пул устройств —
     * это группа (kind: group), её собирает перевод v1 (model/v1.c), а вид выхода только
     * решает, принимает ли он такой список вообще (KK_DEVICES — у interface). */
    char (*devices)[32];        /* арена спеки, devices_n записей */
    size_t devices_n, devices_cap;
    /* Ключи записаны спекой v2 (model/v2.c): отказ вида называет ключ именем v2 (out_key). */
    int v2;
    /* keys_of: устройство выхода — то, что parse вывел бы сам (из имени), писать его незачем. */
    int device_derived;
};
/* Имя ключа для отказа вида: у v1 и v2 оно местами разное (`opts_file`/`strategy`). */
static inline const char *out_key(const struct out_keys *k, const char *v1, const char *v2) {
    return k->v2 ? v2 : v1;
}

/* ---- IPv6 ОТ ХОСТА (шаг 8 выпуска 1.10; docs/spec-v2.md, «ipv6 у выхода») ---------------------
 *
 * ЗАЧЕМ. У роутера своего IPv6 от провайдера часто нет, а у сервера на том конце туннеля
 * WireGuard (хоста) он есть. Хост — «донор»: IPv6 клиентов уходит к нему внутри самого туннеля.
 * Сторону хоста человек настраивает сам (обычный сервер WireGuard с IPv6), раздачу IPv6 в
 * локальную сеть — тоже сам, в netifd и odhcpd (`ip6prefix` у интерфейса wg, `ip6assign` у LAN,
 * `ra_default`, `ula_prefix`): это чужие пакеты, и их настройка принадлежит человеку (раздел 2
 * docs/architecture.md). steer маршрутизирует и говорит в diag, чего не хватает.
 *
 * РЕЖИМЫ — ключ `ipv6` у выхода с устройством, который несёт IPv6 (interface, awg):
 *   routed — хост маршрутизует на пира ПРЕФИКС (или отвечает за адреса из него NDP proxy), и у
 *            клиентов LAN адреса из этого префикса. IPv6 клиентов с адресом из префикса идёт по
 *            правилам: правила в донора ведут его туда, у правил в другие выходы IPv6 отвергается
 *            (другой сервер отбросит чужой источник по AllowedIPs, провайдер — по BCP38), и имена
 *            под ними получают пустой AAAA; всё несовпавшее из префикса — в донора. Адрес из
 *            префикса не уходит ни в другой выход, ни в WAN никогда (fail-closed в forward_v6).
 *            Донор в спеке один.
 *   nat    — у пира один адрес, клиенты на ULA: steer сам ставит masquerade IPv6 на устройство
 *            выхода в своей таблице (исключение из «steer не трогает файрвол» — только по этому
 *            ключу), и IPv6 идёт по правилам, как IPv4.
 *   off    — выход IPv6 не несёт, хотя вид умеет: IPv6 его правил отвергается, AAAA пустой.
 * Ключа нет — поведение 1.9, до байта (снимок генератора). Спека v1 ключа не знает.
 *
 * ТЕЛЕФОН. Раздачей IPv6 там владеет модуль Tethering Android, и префикса хоста в раздачу steer
 * не отдаст. По правилу «выразить всё, неприменимое — предупредить» routed и nat на телефоне
 * разбираются и хранятся, но действуют как отсутствие ключа (out_ipv6_mode), а apply и diag
 * говорят об этом; off применим везде. */
enum out_ipv6 { OUT_V6_KIND = 0, OUT_V6_ROUTED, OUT_V6_NAT, OUT_V6_OFF };

/* Префикс IPv6: адрес в порядке сети и длина; len 0 — префикса нет. */
struct v6pfx {
    uint8_t a[16];
    unsigned char len;
};

struct output {
    /* Пусто — безымянный выход, член группы, рождённый переводом v1 из `devices` (лежит в
     * sp->out за именованными, см. struct spec). */
    char name[32];
    /* Вид — таблица функций своего модуля (src/kinds/kind.h). Указатель, а не номер в реестре:
     * общий код зовёт kind_of(o)->health и соседей прямо, без поиска, а новому виду не нужно
     * место в общем перечне номеров — только свой файл и строка в профиле. NULL (обнулённый
     * выход — так их собирают стенды) читается как direct: kind_of ниже, тот же смысл, что был
     * у нулевого значения прежнего перечня. */
    const struct kind_ops *kind;
    /* Устройство выхода. У группы — АКТИВНОЕ устройство, то, через которое трафик идёт сейчас
     * (выбор сторожа среди устройств членов); отдельно от членов, потому что сторож меняет его,
     * не трогая настройку. */
    char device[32];
    /* Сторож признал выход неработающим и применил on_fail: живых устройств нет (запись «-» в
     * `active`, см. outputs_adopt_active). Трафик через device при этом НЕ идёт, даже если
     * устройство поднято, — status и diag говорят об этом прямо (docs/contract-v1.md, `failed`).
     * У группы спеки v2 — решение подхвата по приговорам членов (живого, которого можно взять,
     * нет; у manual — не работает выбранный), и apply тогда ставит ей on_fail сразу.
     * Заполняет outputs_adopt_active, разбор спеки оставляет нулём. */
    int failed;
    /* Что делать с трафиком, когда выход не работает. Принадлежит группе и любому выходу с
     * устройством (docs/architecture.md, «Вид выхода»). */
    enum on_fail on_fail;
    /* ПОДЛОЖКА: через какой выход идёт собственный трафик туннеля этого выхода (`over` спеки
     * v2, `via` спеки v1). Пусто — напрямую, как всегда. Имя, а не номер: пустая строка
     * обнулённого выхода — «напрямую», а нулевой номер значил бы первый выход. Смысл, проверки
     * и метка — в блоке «подложка» ниже (out_over, out_underlay_mark). */
    char over[32];
    /* Настройка вида — ровно одна из этих, по kind. */
    union {
        struct iface_cfg iface;
        struct vless_cfg vless;
        struct hy2_cfg hy2;
        struct proxy_cfg proxy;
        struct xsteer_cfg xs;
        struct awg_cfg awg;
        struct zapret_cfg zp;
        struct tgws_cfg tg;
        struct group_cfg grp;
    };
    uint32_t mark;      /* 0 for direct: claiming a packet needs no mark */
    int table;
    /* IPv6 ОТ ХОСТА (ключ `ipv6` спеки v2, шаг 8 выпуска 1.10; устройство — у struct v6pfx ниже):
     * как написано в спеке. OUT_V6_KIND — ключа нет, поведение 1.9. Спросить, что действует на
     * этой платформе, — out_ipv6_mode. */
    enum out_ipv6 ipv6;
    /* routed: префикс хоста. v6pfx_given — записан в спеке (`prefix:`); иначе это СОСТОЯНИЕ, как
     * device: выведенный из адресов раздачи префикс (v6donor_derive, failover.c), который apply
     * вписывает в набор v6donor. len 0 — не известен. */
    struct v6pfx v6pfx;
    int v6pfx_given;
    /* IPv6 правил этого выхода не несётся: `ipv6: off` или рядом есть выход-донор (`ipv6: routed`),
     * а этот выход не донор и не `ipv6: nat`. Решает spec_v6_resolve один раз после разбора;
     * out_caps тогда снимает KC_IPV6, и всё, что спрашивает «несёт ли выход IPv6» (маршрут IPv6,
     * forward_v6, dom6_ok, свойства группы), видит один ответ. */
    int v6_denied;
};

/* ---- МОДЕЛЬ v2: кто → что → куда (docs/architecture.md, «4в») -------------------------------
 *
 * Правило связывает клиентов (кто), списки (что) и выход или группу (куда). Спека v2 пишет их
 * именованными и ссылается на имена; спека v1 (JSON, до 2.0.0) переводится в ту же модель
 * (model/v1.c): канал становится правилом с безымянными клиентом и списком. Движок внутри один —
 * компилятор, резолвер, сторож и status читают только эти сущности.
 *
 * Имена структур с приставкой spec_: `struct rule` занят правилом имени у резолвера
 * (dnsd_int.h), `struct list` — списком подсетей у `steer fit` (aggregate.c). */

/* КТО: клиенты правила. */
struct spec_client {
    char name[32];                  /* пусто — безымянный (перевод v1) */
    /* Адреса, подсети и MAC — как на роутере; на телефоне ещё «self» и «uid:N[-M]» (см.
     * from_is_local). Адреса и MAC в одном клиенте нельзя: nft не умеет «или» внутри правила. */
    char (*from)[64];               /* арена спеки, from_n записей (NULL при 0) */
    size_t from_n;
};

/* ЧТО: назначения правила. */
struct spec_list {
    char name[32];                  /* пусто — безымянный (перевод v1) */
    /* Пути — указатели на копии строк в арене спеки, а сами массивы указателей — тоже куски
     * арены ровно на *_n записей: число файлов в списке константой не ограничено. */
    const char **prefixes_files;
    size_t prefixes_n;
    const char **domains_files;
    size_t domains_n;
    /* Наборы правил sing-box (`.srs`): и имена, и подсети, и сужение в одном файле. Читает их
     * не разбор спеки, а те, кому нужно содержимое: компилятор (подсети и сужение — src/compile/
     * groups.c) и резолвер (имена — src/dnsd/table.c); общий читатель — src/model/srs.c. */
    const char **srs_files;
    size_t srs_n;
    /* Сужение по протоколу и портам назначения (схема 2 спеки v1, `proto`/`ports` у списка v2).
     * Пусто — сужения нет, и поведение прежнее до последнего байта текста правил. */
    struct l4match l4;
    /* Назначение — весь интернет, а не файлы (`all` спеки v2, `any` канала v1 без списков):
     * у правила с таким списком набора нет, правило безусловное — только «кто» и сужение l4. */
    int all;
};

/* КТО → ЧТО → КУДА. Порядок правил в спеке — приоритет: при пересечении побеждает то, что выше
 * (с поправкой на правила на устройство, dev_scope). */
struct spec_rule {
    /* Подпись, а не идентификатор: у канала v1 — его имя, и по-русски можно (label_ok). Уходит в
     * status, в журнал резолвера и в сообщения. */
    char name[32];
    /* Выход или группа — индекс в sp->out. */
    int out;
    /* Клиенты — индексы в sp->client; ни одного — клиенты по умолчанию (sp->lan). */
    unsigned *clients;              /* арена спеки, clients_n номеров */
    size_t clients_n;
    /* Списки — индексы в sp->list; ни одного — весь трафик клиентов (v1: `any`). */
    unsigned *lists;                /* арена спеки, lists_n номеров */
    size_t lists_n;
    /* fake-IP (default) or real-IP for a domain rule. See dnsd: fake-IP is
     * precise per domain but makes every traceroute hop show the fake address,
     * because the kernel rewrites ICMP errors to look like they came from the
     * address the client addressed. real-IP keeps hops legible and loses precision
     * only where two domains share one backend address. */
    int realip;
    /* ПРАВИЛО НА ОДНО УСТРОЙСТВО и потому старше любого глобального.
     *
     * ЗАЧЕМ ОТДЕЛЬНЫЙ ПРИЗНАК, если клиент и так умеет и адрес, и MAC. Порядок совпадения
     * читается со спеки: побеждает первое совпавшее правило, и правило на телефон работало
     * ровно до тех пор, пока человек держал его выше глобальных. Стоило добавить новое
     * правило «весь Instagram в туннель» и поставить его первым — и исключение для телефона
     * перестало действовать, молча. То есть приоритет был свойством ПОРЯДКА В СПИСКЕ, а не
     * свойством правила, и удержать его должен был человек.
     *
     * С этим признаком порядок обеспечивается построением: build_groups проходит правила
     * ДВАЖДЫ и кладёт правила на устройство первыми, как бы они ни лежали в спеке.
     *
     * ЧТО ТРЕБУЕТСЯ ОТ ТАКОГО ПРАВИЛА (проверяет разбор): непустые клиенты, и в них только
     * ОДИНОЧНЫЕ хозяева — адрес без маски (или /32) либо MAC. Подсеть в правиле «на устройство»
     * означала бы, что приоритет получил не телефон, а половина сети, — и получила бы его тихо.
     *
     * ПОБОЧНОЕ СЛЕДСТВИЕ: у такого правила «весь трафик» законен без согласия (`allow_all` в
     * v1). Общий запрет заведён против описки «весь трафик в туннель», у которой цена — все
     * клиенты без интернета и починка с провода; у правила на одного хозяина цена ошибки — один
     * хозяин, и он же её и заметит. */
    int dev_scope;
    /** Выключенное правило: лежит в спеке, но в правила не превращается.
     *
     *  Нужно потому, что «отключу на вечер» — самая частая просьба, а единственным способом
     *  было удалить правило вместе с выбранными списками и собрать его заново. Выключенное
     *  правило остаётся видимым движку — status и explain о нём знают.
     *
     *  Умолчание — включено: в спеке v1 поле называется `enabled` и проверяется на `false`, а
     *  внутри хранится обратное — так поле, которого нет, даёт нуль и означает «работает». */
    int disabled;
    /* Апстрим DNS правила (`dns` правила v2): номер в sp->dns.up плюс один; 0 — общий. */
    unsigned dns;
};

/* DNS спеки v2 (раздел `dns`, docs/spec-v2.md): кэш ответов, апстримы и путь запроса к ним.
 * Режим по умолчанию (`dns.mode`) в модель отдельным полем не идёт: он уже разложен в realip
 * каждого правила. Резолвер спеку не читает: эти поля демон кладёт в таблицу для резолвера
 * (src/dnsd/tabfmt.h), а тот разбирает адрес апстрима тем же dnsurl_parse.
 *
 * Апстрим — это ОДИН сервер и путь до него. Транспорт выводится из схемы адреса: udp://, tcp://,
 * tls:// (DoT), https:// (DoH), quic:// (DoQ, RFC 9250).
 * Имя сервера в tls:// и https:// разрешается не системным резолвером, а bootstrap: адресами
 * `ips` апстрима либо серверами `bootstrap` (свои у апстрима, иначе общие из `dns`). Запрос к
 * апстриму уходит напрямую (out == -1) или с меткой выхода out: это метка выхода-подложки, та же,
 * что у сокета туннеля `over` (out_underlay_mark), и та же цепочка postrouting_guard не даёт ему
 * уйти мимо устройства выхода. */
enum dns_proto { DNSP_NONE = 0, DNSP_UDP, DNSP_TCP, DNSP_DOT, DNSP_DOH, DNSP_QUIC };
struct spec_dns_up {
    char name[32];
    char url[256];
    int out;                        /* выход запроса — номер в sp->out; -1 — напрямую */
    /* Разбор url (dnsurl_parse): протокол, имя или адрес сервера, порт, путь DoH. */
    unsigned char proto;
    unsigned short port;
    char host[128];
    char path[128];
    /* Адреса сервера, записанные в спеке (минуют bootstrap), и серверы bootstrap апстрима. */
    char (*ips)[46];                /* арена спеки, ips_n записей */
    size_t ips_n;
    char (*boot)[46];               /* арена спеки, boot_n записей */
    size_t boot_n;
    /* `fragment: true` (только DoT и DoH): ClientHello уходит двумя записями TLS с разрезом внутри
     * имени сервера (SNI) и паузой между двумя отправками — против DPI, ищущего SNI в одной записи. */
    unsigned char frag;
    unsigned char inl;             /* задан в самом правиле (`dns: { url: … }`), а не в dns.upstreams */
    /* ГРУППА СЕРВЕРОВ (`{ servers: [имя, …], mode: race | failover }`): несколько апстримов как
     * один. grp — DNSG_RACE или DNSG_FAILOVER, 0 — это сервер, а не группа. У группы url, out, ips
     * и boot пусты (proto DNSP_NONE, out -1); mem — номера членов в sp->dns.up (с нуля), в порядке
     * спеки; члены — только серверы (группа в группе — отказ разбора). Число членов не
     * ограничено. Как группа отвечает — src/dnsd/dupgrp.c. */
    unsigned char grp;
    unsigned *mem;                  /* арена спеки, mem_n записей */
    size_t mem_n;
};
enum { DNSG_NONE = 0, DNSG_RACE = 1, DNSG_FAILOVER = 2 };
struct spec_dns {
    long cache;                     /* записей кэша; 0 — кэша нет */
    /* Пределы срока жизни записи кэша, секунд: ответ живёт не меньше ttl_min и не дольше
     * ttl_max, отрицательный (NXDOMAIN, пустой ответ) — ttl_neg. Умолчания ставит разбор. */
    long ttl_min, ttl_max, ttl_neg;
    struct spec_dns_up *up;         /* куча, растёт по числу апстримов (spec_grow) */
    size_t up_n, up_cap;
    /* Общий апстрим доменных правил без своего: номер в up плюс один; 0 — нет (имена спрашивают
     * прежним путём: dnsmasq на роутере, исходный сервер запроса на телефоне). */
    unsigned general;
    /* Сервер (или группа) для имён вне правил (`dns.other`): номер в up плюс один; 0 — нет (их
     * спрашивают прежним путём, как раньше). Недоступен — резолвер отвечает прежним путём. */
    unsigned other;
    char (*boot)[46];               /* общие серверы bootstrap, арена спеки */
    size_t boot_n;
    /* ИМЕНА ПРАВИЛ — ТОЛЬКО IPv4: на AAAA имени под доменным правилом резолвер отвечает пустым
     * ответом, какой бы ни был выход. Ставит перевод v1 (spec_parse_v1, src/model/v1.c) и больше
     * никто; у спеки v2 поле нулевое.
     *
     * Зачем. До 1.9 резолвер гасил AAAA всех имён под правилом, и спеки v1 написаны при этом
     * поведении. С 1.9 правило в выход с IPv6 получало на AAAA поддельный или настоящий IPv6
     * (dom6_ok ниже) — и у спеки v1 это поведение новое, о котором её автор не просил: если
     * туннель на той стороне IPv6 не везёт, клиент с двумя стеками сперва тратит время на попытку
     * по IPv6 и лишь потом переходит на IPv4 (замечания проверки 1.9). В
     * спеке v2 IPv6 — явная часть модели (раздел «4б»), и там ответы AAAA остаются.
     *
     * Почему поле, а не проверка версии спеки в резолвере. Резолвер спеку не видит вовсе: в
     * режиме --table-fd он получает от демона готовую таблицу каналов (src/dnsd/tabfmt.h), и
     * решение про AAAA едет в ней полем семейства — «4» вместо «46». Читает поле сборка таблицы
     * (dch_fam, src/dnsd/table.c) — та же, что у демона, у `steer dnsd-table` и у резолвера со
     * --spec, поэтому решение одно на всех. Слой модели говорит, что значит спека, слой
     * резолвера — что с этим делать; номер формата дальше перевода не уходит.
     *
     * Компилятор поле НЕ читает (build_groups ставит dom6 по dom6_ok, как раньше): набор правил
     * спеки v1 остаётся тем же до байта, что давал 1.9 (снимок tests/snapshot.sh), — с набором
     * «<группа>6», v6-двойником и картой fakeip6. Они стоят пустыми: резолвер туда ничего не
     * кладёт. Такое расхождение безопасно в эту сторону — правило без адресов ничего не забирает;
     * опасное обратное (адрес без правила, которое его заберёт) не возникает: поле только
     * снимает IPv6, а не добавляет. Строки IPv6 в списках (парный набор и двойник) от поля не
     * зависят — речь только об ответах на AAAA. */
    int names_v4;
};

/* Пользуется ли резолвер апстримом номер u (с нуля): он общий (`dns.upstream`), для имён вне
 * правил (`dns.other`), назначен включённому правилу — сам или членом группы, которая назначена.
 * Метку выхода апстрима «через выход» компилятор ставит в страж только таким (generate.c). */
int spec_dns_up_used(const struct spec *sp, size_t u);

/* Разобрать адрес апстрима в u (proto, host, port, path). 0 — разобрано; -1 — нет, why — причина
 * человеческими словами. Один разбор на спеку и на резолвер (src/model/parse.c). */
int dnsurl_parse(const char *url, struct spec_dns_up *u, char *why, size_t why_n);

/* СПЕКА — ЗНАЧЕНИЕ, А НЕ ГЛОБАЛЫ (docs/architecture.md, раздел 2, правило 6).
 *
 * Раньше разобранная спека жила в пяти глобальных массивах (g_out, g_ch, g_from_default,
 * g_lan_dev, g_traceroute_hops): один экземпляр на процесс, доступный отовсюду без
 * объявления. Решение владельца — отказаться от этого в пользу явной передачи параметром:
 * struct spec собирает те же пять групп полей в одно значение, load_spec заполняет его, а
 * каждая функция, которой нужна спека, получает указатель на него параметром.
 *
 * ПОЧЕМУ НЕ ОДИН ОБЩИЙ ЭКЗЕМПЛЯР ВМЕСТО ПЯТИ ГЛОБАЛОВ. Это был бы тот же порок под другим
 * именем: g_spec вместо g_out теряет ту же информацию — кто читает спеку, а кто нет, — и
 * даёт любой функции доступ к ней без спроса. Стенд, собирающий failover.c без парсера
 * (failovermatch), или два процесса с разными спеками в одном тесте оказались бы вынуждены
 * либо делить один экземпляр, либо снова заводить глобал под другим именем. Явный параметр
 * делает то же самое видимым в сигнатуре: функция, которая спеку не получает, спеку не
 * читает — это проверяет компилятор, а не память того, кто её писал.
 *
 * ГДЕ ЖИВЁТ ЭКЗЕМПЛЯР. Сам struct spec теперь маленький (указатели и счётчики; замер bss — в
 * отчёте к выпуску), а всё, что растёт с числом правил, лежит в куче: каждая точка входа
 * (cmd_* в daemon/, dnsd, tgws, vless-команды, awg-команды) заводит свой `static struct spec`
 * и передаёт указатель вниз по вызовам. Один процесс — один экземпляр за время своей жизни,
 * но эти экземпляры не делят состояние между собой, и это и есть разница со старыми глобалами:
 * явную, а не подразумеваемую.
 *
 * ВЛАДЕНИЕ. Два рода памяти.
 *   - Выходы (out, anon) — обычные кучи с удвоением (spec_grow): их правит сторож
 *     (device, приговоры, состояние групп), и у каждого экземпляра они свои.
 *   - Всё остальное — правила, списки, клиенты, апстримы DNS и всё, что висит на элементах
 *     (адреса клиента, файлы списка, члены группы…) — арена sp->mem (spec_alloc), которая
 *     ЧИТАЕТСЯ и не меняется после разбора. Арена с счётчиком ссылок (struct spec_mem): копия
 *     для прохода сторожа (spec_clone) берёт ту же арену, а не переписывает её, и загрузка новой
 *     спеки посреди прохода (spec_release старой) её не освобождает, пока проход не кончился.
 *     Раньше сторож копировал struct spec целиком memcpy (под 250 КБ на проход) — теперь
 *     копируются только выходы, ради которых копия и нужна.
 * spec_release() отдаёт своё и снимает ссылку с арены; load_spec зовёт её сам перед разбором,
 * поэтому повторная загрузка в тот же экземпляр (цикл демона) не течёт. Указатель на элемент
 * растущего массива живёт до следующего роста того же массива: кто добавляет запись, держит
 * индекс, а не указатель. */
struct spec_mem;
struct spec {
    /* Именованные выходы: [0, out_n), в порядке спеки. Их число ограничено раскладкой метки
     * (spec_outputs_max), больше ничем. */
    struct output *out;
    size_t out_n, out_cap;
    /* Безымянные члены групп, которых рождает перевод v1 из `devices`; номер в
     * group_cfg.members — SPEC_ANON_BASE + позиция здесь. Обращаться — spec_out(). */
    struct output *anon;
    size_t anon_n, anon_cap;
    struct spec_rule *rule;
    size_t rule_n, rule_cap;
    struct spec_list *list;
    size_t list_n, list_cap;
    struct spec_client *client;
    size_t client_n, client_cap;
    struct spec_mem *mem;           /* арена (spec_alloc), с счётчиком ссылок */
    void *own;                      /* личные массивы копии (spec_clone): состояние групп */
    /* Клиенты по умолчанию (`lan` спеки v2): у правила без своих клиентов «кто» — это они.
     * Адреса — `from_default` спеки v1; пусто — клиенты узнаются по устройству (lan_dev ниже). */
    struct spec_client lan;
    /* Локальные устройства — устройства клиентов по умолчанию: те, с которых движок забирает
     * трафик клиентов.
     *
     * СПИСОК, А НЕ СТРОКА, потому что роутер бывает выходной точкой не только для своего
     * моста: у splify2 просили маршрутизировать ещё и хостов из Tailscale/ZeroTier, для
     * которых он шлюз (splify2#16). В спеке v1 это `lan_devices`; прежнее `lan_device` осталось
     * сокращением для списка из одного элемента.
     *
     * ПОЧЕМУ ВЫБОР ПО УСТРОЙСТВУ, А НЕ ПО ПОДСЕТИ. Раньше движок выводил подсеть клиентов из
     * адреса единственного устройства. Для Tailscale это не работает в принципе: у
     * tailscale0 на роутере адрес обычно /32, и выведенная из него «подсеть» — сам роутер.
     * Имя устройства отвечает на тот же вопрос точнее и там, где адрес не отвечает вовсе:
     * заодно в правило попадают клиенты за вторым роутером в LAN, у которых адреса чужой
     * подсети, а интерфейс тот же. Умолчание — один "br-lan", выставляется в load_spec. */
    char (*lan_dev)[64];            /* арена спеки, lan_dev_n записей */
    size_t lan_dev_n;
    int traceroute_hops;
    struct spec_dns dns;
};

/* ---- память спеки --------------------------------------------------------------------------
 *
 * ЗАЧЕМ АРЕНА. Внутренние массивы (адреса клиента, файлы списка, члены группы…) знают свою длину
 * в момент разбора и живут ровно столько же, сколько спека. Отдельный malloc под каждый значил
 * бы отдельный free под каждый и путь очистки по всем видам записей; арена — это цепочка
 * кусков, освобождаемая одним обходом (spec_release), и кусок в 4 КБ вмещает спеку роутера
 * целиком (три правила — это сотни байт). Записи выдаются обнулёнными (calloc куска).
 *
 * ПОЧЕМУ УКАЗАТЕЛИ В ЭЛЕМЕНТАХ, А НЕ ВСТРОЕННЫЕ МАССИВЫ. Встроенный массив на предел — это
 * память под предел у КАЖДОЙ записи: 32 адреса по 64 байта — 2 КБ на клиента, 64 файла — по
 * 512 байт на вид списка, и пустое правило стоило столько же, сколько правило на пределе.
 * Указатель на кусок ровно нужной длины стоит восемь байт плюс то, что реально записано.
 *
 * НЕХВАТКА ПАМЯТИ. spec_alloc и spec_grow возвращают NULL/-1, а не рвут процесс: разбор
 * отдаёт человеку «недостаточно памяти для спеки (что растили и до скольких)», и это
 * настоящая причина отказа — предела в коде, который можно было бы упомянуть, у спеки нет. */
struct spec_chunk {
    struct spec_chunk *next;
    size_t used, cap;
};
/* Арена: цепочка кусков и счётчик ссылок (spec_clone берёт ссылку, spec_release снимает). */
struct spec_mem {
    size_t refs;
    struct spec_chunk *head;
};

static inline void *spec_alloc(struct spec *s, size_t n) {
    if (!n) return NULL;
    n = (n + 7u) & ~(size_t)7u;
    if (!s->mem) {
        s->mem = (struct spec_mem *)calloc(1, sizeof(*s->mem));
        if (!s->mem) return NULL;
        s->mem->refs = 1;
    }
    struct spec_chunk *c = s->mem->head;
    if (!c || c->cap - c->used < n) {
        size_t cap = n > 4096 ? n : 4096;
        struct spec_chunk *nc = (struct spec_chunk *)calloc(1, sizeof(*nc) + cap);
        if (!nc) return NULL;
        nc->cap = cap;
        if (n > 4096 && c) {            /* большой кусок — за головой: голова ещё принимает мелочь */
            nc->next = c->next;
            c->next = nc;
            nc->used = n;
            return nc + 1;
        }
        nc->next = s->mem->head;
        s->mem->head = nc;
        c = nc;
    }
    void *p = (unsigned char *)(c + 1) + c->used;
    c->used += n;
    return p;
}

/* Копия строки/массива в арене; NULL при нехватке памяти (и при n == 0 для массива). */
static inline char *spec_strdup(struct spec *s, const char *str) {
    size_t n = strlen(str) + 1;
    char *p = (char *)spec_alloc(s, n);
    if (p) memcpy(p, str, n);
    return p;
}
static inline void *spec_memdup(struct spec *s, const void *src, size_t n) {
    void *p = spec_alloc(s, n);
    if (p) memcpy(p, src, n);
    return p;
}

/* Дописать запись в массив из арены, длину которого заранее не знаешь: место под запись номер n
 * (cap — ёмкость, ведёт вызывающий; начальный ноль — «массива ещё нет»). Полный массив
 * переезжает в арену вдвое больше, прежний остаётся в ней мёртвым куском — это не утечка
 * (арена отдаётся целиком) и не больше удвоения от нужного. NULL — нехватка памяти. */
static inline void *spec_push(struct spec *s, void **arr, size_t n, size_t *cap, size_t esz) {
    if (n >= *cap) {
        size_t nc = *cap ? *cap * 2 : 4;
        void *p = spec_alloc(s, nc * esz);
        if (!p) return NULL;
        if (n) memcpy(p, *arr, n * esz);
        *arr = p;
        *cap = nc;
    }
    return (unsigned char *)*arr + n * esz;
}

/* Дать верхнему массиву место на need записей: realloc с удвоением, новый хвост — нули. 0 — есть
 * место; -1 — нехватка памяти (массив цел). Прежние указатели на элементы после успеха
 * недействительны. */
static inline int spec_grow(void **arr, size_t *cap, size_t need, size_t esz) {
    if (need <= *cap) return 0;
    size_t nc = *cap ? *cap : 4;
    while (nc < need) nc *= 2;
    void *p = realloc(*arr, nc * esz);
    if (!p) return -1;
    memset((unsigned char *)p + *cap * esz, 0, (nc - *cap) * esz);
    *arr = p;
    *cap = nc;
    return 0;
}

/* То же для массива из арены (правила, списки, клиенты, апстримы): читаемая часть спеки живёт в
 * общей арене, а не в realloc-куче. Прежний кусок остаётся в арене мёртвым — не больше удвоения. */
static inline int spec_grow_a(struct spec *s, void **arr, size_t *cap, size_t need, size_t esz) {
    if (need <= *cap) return 0;
    size_t nc = *cap ? *cap : 4;
    while (nc < need) nc *= 2;
    void *p = spec_alloc(s, nc * esz);
    if (!p) return -1;
    if (*cap) memcpy(p, *arr, *cap * esz);
    *arr = p;
    *cap = nc;
    return 0;
}

/* Отдать всё, что держит спека, и обнулить её. Безопасно на нулевой и на уже отданной. Арену
 * отпускает по счётчику ссылок: копия для прохода (spec_clone) может ещё читать её. */
static inline void spec_release(struct spec *s) {
    if (s->mem && --s->mem->refs == 0) {
        for (struct spec_chunk *c = s->mem->head, *n; c; c = n) { n = c->next; free(c); }
        free(s->mem);
    }
    free(s->out);
    free(s->anon);
    free(s->own);
    memset(s, 0, sizeof(*s));
}

/* Выход по номеру, каким его хранит group_cfg.members и о каком говорит rule.out: меньше
 * SPEC_ANON_BASE — именованный (sp->out), иначе безымянный член (sp->anon). */
static inline struct output *spec_out(const struct spec *s, size_t idx) {
    return idx >= SPEC_ANON_BASE ? &s->anon[idx - SPEC_ANON_BASE] : &s->out[idx];
}
static inline int spec_is_named(size_t idx) { return idx < SPEC_ANON_BASE; }
/* Номер именованного выхода по указателю; (size_t)-1 — указатель не в sp->out (безымянный член
 * пула, копия на стеке). Вычитание указателей из разных массивов было бы неопределённым, поэтому
 * сравнение идёт по адресам. */
static inline size_t spec_out_idx(const struct spec *s, const struct output *o) {
    uintptr_t a = (uintptr_t)o, b = (uintptr_t)s->out;
    if (!s->out || a < b || a >= b + s->out_n * sizeof(*s->out)) return (size_t)-1;
    return (size_t)(o - s->out);
}

/* Стенды, собирающие спеку руками, и парсеры: место на n именованных выходов / правил / списков /
 * клиентов вперёд. 0 — есть; -1 — нехватка памяти. */
static inline int spec_reserve_out(struct spec *s, size_t n) {
    return spec_grow((void **)&s->out, &s->out_cap, n, sizeof(*s->out));
}
static inline int spec_reserve_rule(struct spec *s, size_t n) {
    return spec_grow_a(s, (void **)&s->rule, &s->rule_cap, n, sizeof(*s->rule));
}
static inline int spec_reserve_list(struct spec *s, size_t n) {
    return spec_grow_a(s, (void **)&s->list, &s->list_cap, n, sizeof(*s->list));
}
static inline int spec_reserve_client(struct spec *s, size_t n) {
    return spec_grow_a(s, (void **)&s->client, &s->client_cap, n, sizeof(*s->client));
}
static inline int spec_reserve_up(struct spec *s, size_t n) {
    return spec_grow_a(s, (void **)&s->dns.up, &s->dns.up_cap, n, sizeof(*s->dns.up));
}

/* Копия спеки для того, кто её меняет (проход сторожа). Общее и читаемое — правила, списки,
 * клиенты, апстримы, всё в арене — берётся по ссылке; выходы копируются, а состояние групп
 * (alive, замеры) получает свои массивы: проход пишет в них, и демон должен видеть свою спеку
 * нетронутой. d обязана быть нулевой или ранее отданной. 0 — готово; -1 — нехватка памяти
 * (d пуста). */
static inline int spec_clone(struct spec *d, const struct spec *s) {
    spec_release(d);
    *d = *s;
    if (d->mem) d->mem->refs++;
    d->out = d->anon = NULL;
    d->out_cap = d->anon_cap = 0;
    d->own = NULL;
    size_t members = 0;
    for (size_t i = 0; i < s->out_n; i++)
        if (out_group(&s->out[i])) members += s->out[i].grp.members_n;
    for (size_t i = 0; i < s->anon_n; i++)
        if (out_group(&s->anon[i])) members += s->anon[i].grp.members_n;
    if (s->out_n) {
        d->out = (struct output *)malloc(s->out_n * sizeof(*d->out));
        if (!d->out) goto fail;
        memcpy(d->out, s->out, s->out_n * sizeof(*d->out));
        d->out_cap = s->out_n;
    }
    if (s->anon_n) {
        d->anon = (struct output *)malloc(s->anon_n * sizeof(*d->anon));
        if (!d->anon) goto fail;
        memcpy(d->anon, s->anon, s->anon_n * sizeof(*d->anon));
        d->anon_cap = s->anon_n;
    }
    if (members) {
        /* alive (байт) и три массива int на члена — одним куском. */
        size_t per = 1 + 3 * sizeof(int);
        unsigned char *blk = (unsigned char *)malloc(members * per + 3 * sizeof(int));
        if (!blk) goto fail;
        d->own = blk;
        int *iv = (int *)blk;               /* выровнено: сначала int-массивы */
        unsigned char *bv = (unsigned char *)(iv + 3 * members);
        for (int pass = 0; pass < 2; pass++) {
            size_t n = pass ? d->anon_n : d->out_n;
            struct output *arr = pass ? d->anon : d->out;
            for (size_t i = 0; i < n; i++) {
                if (!out_group(&arr[i])) continue;
                struct group_cfg *g = &arr[i].grp;
                size_t m = g->members_n;
                if (!m) continue;
                memcpy(iv, g->lat_ms, m * sizeof(int));
                g->lat_ms = iv; iv += m;
                memcpy(iv, g->lat4_ms, m * sizeof(int));
                g->lat4_ms = iv; iv += m;
                memcpy(iv, g->lat6_ms, m * sizeof(int));
                g->lat6_ms = iv; iv += m;
                memcpy(bv, g->alive, m);
                g->alive = bv; bv += m;
            }
        }
    }
    return 0;
fail:
    spec_release(d);
    return -1;
}
/* Каталог состояния (steer_state_dir) и каталог имён таблиц iproute2 (steer_rt_tables_dir) —
 * пути платформы со швом переопределения: src/platform/platform.h. */

/* ---- вопросы к правилу ---------------------------------------------------------------------
 *
 * Правило ссылается на клиентов и списки номерами; прочесть их — здесь, одним способом на всех
 * читателей (компилятор, резолвер, раскладка наборов .srs, имена наборов). Перевод v1 даёт у
 * правила ровно одного клиента (или ни одного) и ровно один список; несколько — это спека v2
 * (шаг 2 из 1.9), и тогда правило раскладывается компилятором на пары «клиент × список». */

/* Свой клиент правила или NULL — у правила без своих клиентов «кто» по умолчанию (sp->lan). */
static inline const struct spec_client *rule_client(const struct spec *sp,
                                                     const struct spec_rule *r) {
    return r->clients_n ? &sp->client[r->clients[0]] : NULL;
}

/* «Кто» правила, каким его видит компилятор: свой клиент, а если его нет или в нём не осталось
 * ни одной записи — клиенты по умолчанию. Правило то же, что у канала v1 («свой from, а если
 * его нет — from_default»), и записано один раз здесь. */
static inline const struct spec_client *rule_who(const struct spec *sp, const struct spec_rule *r) {
    const struct spec_client *c = rule_client(sp, r);
    return c && c->from_n ? c : &sp->lan;
}

/* Список правила. У правила без списков (весь трафик) — общий пустой список с all=1. */
extern const struct spec_list spec_list_all;
static inline const struct spec_list *rule_list(const struct spec *sp, const struct spec_rule *r) {
    return r->lists_n ? &sp->list[r->lists[0]] : &spec_list_all;
}

/* Выход правила (или группа). */
static inline const struct output *rule_out(const struct spec *sp, const struct spec_rule *r) {
    return &sp->out[r->out];
}

/* The port `steer dnsd` listens on and the redirect points at. One constant, so
 * the two halves cannot disagree about where DNS is being steered. */
#define DNS_PORT 5300

/* Вид выхода и его свойства. kind_of — единственное место, где читается поле kind: обнулённый
 * выход (kind == NULL) — это direct, как было у нулевого значения прежнего перечня видов. */
static inline const struct kind_ops *kind_of(const struct output *o) {
    return o->kind ? o->kind : KIND_ZERO;
}
static inline unsigned out_caps(const struct output *o) {
    const struct kind_ops *k = kind_of(o);
    unsigned c = k->caps | (k->caps_of ? k->caps_of(o) : 0);
    /* IPv6 выхода снят (`ipv6: off` или выход рядом с донором — spec_v6_resolve): вид умеет, но
     * этот выход IPv6 не несёт. Одним местом здесь, чтобы все вопросы «несёт ли IPv6» (маршрут
     * IPv6, forward_v6, dom6_ok, свойства группы в group_seal) получили один ответ. */
    if (o->v6_denied) c &= ~(unsigned)KC_IPV6;
    return c;
}
static inline int out_has_cap(const struct output *o, unsigned cap) { return (out_caps(o) & cap) != 0; }

/* Выход, у которого есть устройство и своя таблица маршрутизации. vless сюда входит:
 * его TUN — такое же устройство, и вся логика меток, маршрутов и проверок к нему
 * применима без изменений. Одна функция вместо повторения условия в пяти местах —
 * иначе добавление нового вида требовало бы найти их все, а забытое место означало бы
 * выход, который настроен, но не маршрутизируется. */
static inline int out_has_device(const struct output *o) { return out_has_cap(o, KC_DEVICE); }

/* Выход, которому нужна СВОЯ МЕТКА, чтобы его трафик можно было узнать в ядре.
 *
 * Не то же самое, что out_has_device, и разошлись они на kind=zapret: у того устройства нет
 * и таблицы маршрутизации нет (пакет уходит обычным маршрутом), а метка есть — по ней
 * цепочка postrouting отдаёт пакет нужному экземпляру nfqws. Пока условие было одно на две
 * надобности, добавление такого вида означало бы выход, помеченный ничем: правило канала
 * встало бы, а трафик в очередь не попал бы, и понять это было бы нечем — правила выглядят
 * применёнными.
 *
 * direct метки не получает по-прежнему: заявлять пакет ничем не нужно, он и так идёт туда. */
static inline int out_needs_mark(const struct output *o) { return out_has_cap(o, KC_MARK); }

/* Выход, которому нужна метка СОЕДИНЕНИЯ, а не только метка пакета.
 *
 * Отдельно от out_needs_mark, потому что метка соединения живёт НЕ В НАШЕМ ФАЙЛЕ И НЕ В
 * НАШЕЙ ТАБЛИЦЕ. Она лежит в записи conntrack ядра и переживает и перезапуск службы, и
 * `nft delete table`, и удаление пакета целиком — снять её оттуда нечем, кроме как выждав
 * срок жизни записи. Значит ставить её можно только тем выходам, которым она ДЕЙСТВИТЕЛЬНО
 * нужна, а не всем подряд «на всякий случай».
 *
 * Кому нужна. Выходу kind=zapret — по ней цепочка postrouting узнаёт соединение после
 * хука forward, где метку пакета переписывают чужие (Tailscale). Выходам с устройством —
 * из-за выгрузки потоков: после установления соединения наша цепочка видит единицы пакетов
 * вместо тысяч, и пересмотреть маршрут (или применить запрет on_fail=drop) можно только по
 * метке соединения.
 *
 * Кому НЕ нужна — kind=tgws, и это не экономия, а починенная поломка. Перехват стоит в nat
 * prerouting и решает по метке ПАКЕТА, которую ставит наша же цепочка на десять приоритетов
 * раньше; ни таблицы маршрутизации, ни очереди у такого выхода нет, а соединение
 * заканчивается на самом роутере — то есть в forward не попадает и выгружено быть не может.
 * Метка соединения ему не нужна была никогда, а вреда приносила много: к нашему биту
 * добавляется ZAPRET_SKIP_MARK (см. out_skips_zapret), и он означает «этот трафик не твой»
 * для системного обхода. После удаления микропакета tgws правила исчезают, а записи
 * conntrack с этим битом остаются — и подхватившие Telegram podkop или splify2 получают
 * трафик, уже помеченный «мимо обхода». Снаружи это ровно то, о чём сказал владелец:
 * «удалил stgws — другие сервисы не могут нормально маршрутизировать Telegram». */
static inline int out_needs_ctmark(const struct output *o) { return out_has_cap(o, KC_CTMARK); }

/* Выход, устройство которого создаёт и обслуживает НАШ процесс, а не netifd.
 *
 * Отдельно от out_has_device, потому что из этого следуют другие вещи: ждать устройство
 * снаружи нельзя (его ещё нет), ifdown/ifup бесполезны (netifd про него не знает —
 * «Interface … not found», и на живом роутере это вечный холостой цикл в журнале), а
 * поднимает замену procd. */
static inline int out_engine_managed(const struct output *o) { return out_has_cap(o, KC_ENGINE_OWNED); }

/* Выход, которому masquerade не нужен: наружу он ходит от своего имени.
 *
 * Причины у vless и xsteer РАЗНЫЕ, и объединять их формулировкой нельзя — только
 * следствием. У vless адреса клиентов границу не переходят вовсе: клиент завершает TCP у
 * себя и соединяется с сервером обычным сокетом. У xsteer они переходят, но переходят к
 * хабу внутри туннеля, где транслировать их нечем и не нужно; более того, NAT там ВРЕДЕН
 * — он скрывает, от какой пира пришёл пакет, и ломает обратный поиск по AllowedIPs.
 * Отсюда одна функция для решения и разные тексты в сообщениях. */
static inline int out_self_natting(const struct output *o) { return out_has_cap(o, KC_SELF_NAT); }

/* Выход, трафик которого общий обход DPI трогать НЕ должен.
 *
 * Это все виды, кроме kind=direct, и исключение здесь ровно одно — оно же и есть смысл
 * прямого канала: там общий обход обязан работать, для этого канал и заводят.
 *
 * ПОЧЕМУ ОСТАЛЬНЫМ ОБХОД ВРЕДЕН, а не просто бесполезен. Пакет, уходящий в туннель, DPI
 * видит снаружи как сам туннель: разбирать его полезную нагрузку невозможно, и стратегия
 * обхода работает не с тем, для чего написана. Но nfqws при этом рассинхронизирует и режет
 * ВНЕШНИЕ пакеты — то есть трогает транспорт туннеля, и рукопожатие может не сойтись. Плюс
 * лишний проход через очередь на каждый пакет.
 *
 * Мост Telegram (kind=tgws) здесь по той же причине: его трафик разбирает наш собственный
 * обработчик, и второй разбиратель поверх — это два обхода на один пакет, то есть не то,
 * что выбрал человек, ни в одном из двух смыслов.
 *
 * ОДНОЙ ФУНКЦИЕЙ, а не `case` по kind на месте: спрашивают об этом генератор правил и
 * (со временем) диагностика, а две копии перечня разошлись бы при появлении следующего
 * вида выхода — и разошлись бы молча, потому что правила у обоих выглядят исправно. */
static inline int out_skips_zapret(const struct output *o) {
    /* На телефоне zapret нет (решение владельца: «zapret не надо», .zapret = 0 в
     * src/platform/android.c) — ни системного, которому бит говорит «не твоё», ни своего
     * kind=zapret (спека его отвергает, см. src/kinds/zapret.c). Бит ставить некому читать, а
     * стоит он в бите 30 — там, где netd отдаёт производителю два бита метки (Fwmark.h:
     * vendor, 29-30). Ноль здесь снимает и бит в правилах разметки, и цепочку failopen,
     * которая существует только ради него (out_failopen_capable ниже). */
    if (!plat()->zapret) return 0;
    return out_has_cap(o, KC_SKIP_ZAPRET);
}

/* ВЫХОД УПАЛ, ТРАФИК ПУЩЕН НАПРЯМУЮ — И ОН СНОВА ОБЫЧНЫЙ ТРАФИК РОУТЕРА.
 *
 * Бит ZAPRET_SKIP_MARK ставит правило разметки в prerouting_mark, и ставит БЕЗУСЛОВНО: оно
 * ничего не знает о том, жив ли туннель. Пока выход работает, так и надо (см. out_skips_zapret
 * выше). Но при отказе с on_fail=direct или on_fail=zapret сторож снимает правило fwmark, и
 * помеченный пакет уходит по таблице main — через WAN, открытым путём, — а бит на нём
 * остаётся. Общий обход видит «не мой» и такой пакет не трогает. То есть «напрямую» на деле
 * значило «напрямую и мимо zapret»: сайты, которые без обхода не открываются, у человека с
 * упавшим туннелем не открывались и там, где весь остальной роутер их открывает. А у
 * on_fail=zapret, который ровно обходом и обещает, это было прямое расхождение с обещанием.
 *
 * Выбранное решение: СОСТОЯНИЕ «УПАЛ И ПУЩЕН НАПРЯМУЮ» ЛЕЖИТ В ЯДРЕ, в наборе FAILOPEN_SET
 * нашей таблицы (метки выходов), а отдельная цепочка prerouting_failopen сразу после
 * разметки (mangle + 2) снимает бит с пакетов, чья метка в наборе. Метку в набор кладёт и
 * вынимает тот, кто и так меняет маршрут выхода: сторож в apply_failed (кладёт при
 * direct/zapret, вынимает при drop) и в bind_device (вынимает при привязке к живому
 * устройству), apply — когда устройства для выхода нет вовсе (apply_routing в daemon/apply.c). Сверка
 * сторожа это же и чинит: apply пересоздаёт таблицу с пустым набором, но заодно возвращает
 * правило fwmark, и первый же проход видит у упавшего выхода расхождение и зовёт apply_failed.
 *
 * Почему не «ставить бит только при живом выходе» прямо в правиле разметки: правило одно на
 * группу каналов и знает о выходе только его метку, а переписывать правила на каждом отказе
 * значило бы пересобирать цепочку из сторожа. Почему не по устройству в postrouting («бит —
 * только тем, кто уходит в туннель»): список устройств у выхода меняется, у vless и xsteer
 * устройство заводит наш же процесс, и промах в перечне означал бы тихо вернувшийся обход
 * внешних пакетов туннеля. Набор же отвечает ровно на вопрос «пущен ли выход напрямую», и
 * ответ на него уже есть у сторожа.
 *
 * Только выходы с устройством (interface, vless, xsteer): у kind=zapret on_fail выражает
 * флаг bypass очереди (см. generate), у tgws on_fail бывает только drop. Цепочка и набор
 * ставятся, лишь если в спеке есть такой выход с on_fail не drop, — остальным на каждый
 * пакет лишний поиск ни к чему. */
#define FAILOPEN_SET "failopen"
/* ВЫХОД, КОТОРЫЙ ВООБЩЕ БЫВАЕТ «ПУЩЕН НАПРЯМУЮ»: с устройством и с on_fail не drop. Отдельно от
 * out_failopen_capable, потому что у набора FAILOPEN_SET после проверки на QEMU 04664a5
 * (docs/architecture.md, раздел 2, «Набор правил») два читателя, а не один:
 *   - цепочка prerouting_failopen — снять бит «не для zapret»; ей нужен ещё и сам бит
 *     (out_failopen_capable ниже), то есть на телефоне её нет;
 *   - цепочка postrouting_guard (generate.c, «ПОМЕЧЕННЫЙ ПАКЕТ НЕ ТУДА — НИКУДА») — пропустить
 *     мимо устройств выхода помеченный пакет выхода, который сторож законно отпустил напрямую.
 *     Этой отметка нужна на любой платформе: на телефоне выход с on_fail=direct, упав, тоже уводит
 *     свой трафик в сеть телефона, и без отметки цепочка сочла бы это утечкой и отбросила.
 * Поэтому набор заводится по этому вопросу и отметку ставит и снимает failopen_mark по нему же, а
 * цепочка снятия бита — по out_failopen_capable. */
static inline int out_releasable(const struct output *o) {
    return out_has_device(o) && o->on_fail != FAIL_DROP;
}
static inline int out_failopen_capable(const struct output *o) {
    return out_releasable(o) && out_skips_zapret(o);
}

