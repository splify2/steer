static int g_trace;
#define TR(...) do { if (g_trace) fprintf(stderr, "tun: " __VA_ARGS__); } while (0)

/* ---- пул установщиков ------------------------------------------------------
 *
 * Рукопожатие вынесено из цикла в отдельные потоки. Пул, а не поток на соединение, по двум
 * причинам: поток на каждое соединение это сотни потоков на пачке запросов страницы, и —
 * важнее — адрес узла, сработавший в прошлый раз, кэшируется в транспорте как __thread
 * (proto/transport/trdial.c). Живя
 * в потоке-однодневке, этот кэш терялся бы на каждом соединении, и перебор мёртвых адресов
 * начинался бы заново.
 *
 * Очередь без предела, потоки — по нагрузке (I-529).
 *
 * Прежде очередь была в 32 заявки при четырёх установщиках, и лишний SYN получал RST: «столько
 * рукопожатий роутер не переварит». На компьютере браузер открывает сотню соединений разом, и отказ
 * на четвёртой десятке был ложным: узким местом были четыре потока, ждущих сеть, а не процессор.
 * Теперь заявка принимается всегда (каждая принадлежит соединению, а число соединений ограничено
 * таблицей), а потоков столько, сколько ждёт: нет свободного установщика — заводится ещё, до
 * CONNECTORS_MAX; лишние уходят после CONNECTOR_IDLE_S простоя. Постоянные CONNECTORS остаются: у
 * них живёт кэш адреса узла (см. выше).
 *
 * Четыре постоянных — по замеру: восемь не дали ничего, двенадцатое соединение приходило за 1798 мс
 * против 1693 при четырёх, то есть упор в X25519 и AEAD рукопожатия, а не в ожидание сети. Сверх них
 * потоки нужны только когда рукопожатия ЖДУТ (медленный или мёртвый узел, 8 с на заявку), — там и
 * заводятся. Потолок потоков настоящий: каждый держит стек и дескрипторы. STEER_TUN_CONNECTORS
 * задаёт его вручную. */
#define CONNECTORS 4
#define CONNECTORS_MAX 64
#define CONNECTOR_IDLE_S 20
/* Сколько установщик ждёт связи с узлом. Восемь секунд — прежнее число: его же берёт проверка
 * узла при подъёме, и соединение, которое проверка сочла бы живым, не должно отваливаться здесь
 * по более короткому сроку. */
#define CONNECT_TIMEOUT_S 8

/* ---- запасные сессии -------------------------------------------------------
 *
 * Рукопожатие с узлом — 100-400 мс, и при заявке «на каждый SYN» оно целиком лежит на
 * критическом пути первого запроса. У nft-маршрутизации этого шага нет вовсе — SYN сразу
 * уезжает в туннель. Уравнять пути можно только одним способом: сделать рукопожатие
 * ЗАРАНЕЕ. Это возможно, потому что адрес назначения в VLESS едет не при установлении, а
 * в заголовке запроса — вместе с первыми данными (см. upstream_send): TLS-сессия к узлу
 * до этого момента ничья, и её можно приготовить впрок. Для стека это свойство дайлера —
 * DC_PRECONNECT (dialer.h): у протокола, где адрес нужен уже при установлении, пула нет.
 *
 * Пул пополняется ТОЛЬКО по приходу SYN — на тихом роутере фоновых рукопожатий нет
 * совсем — и только когда SYN идут потоком: первое соединение после затишья
 * (SPARE_TTL_MS) идёт обычным путём и запасных не заводит, второе, пришедшее раньше, чем
 * протухла бы запасная, пополнение заводит. Браузер открывает соединения пачками, и
 * остальные соединения пачки достаются из пула готовыми; одиночная проверка отклика
 * стоит узлу одно соединение, а не пять. Отказ узла (запасной или живого соединения)
 * отодвигает пополнение на 5, 10, 20, 40 с и дальше на минуту; удачное установление
 * паузу снимает.
 *
 * Срок годности короткий не по нашей воле: Xray закрывает соединение, не приславшее
 * запрос VLESS, по таймауту рукопожатия — по умолчанию 4 секунды. Запас старше считаем
 * мёртвым сами, не проверяя: проверка стоила бы круга до сервера, а протухшую сессию
 * дешевле выбросить и открыть новую.
 *
 * Память: жилая часть связи — это ~19 КБ буферов TLS; при четырёх запасных — до
 * 76 КБ, и то лишь у выхода, через который реально ходят. Плата сопоставима с одним
 * лишним живым соединением. */
#define SPARE_MAX 8
#define SPARE_TTL_MS 2500
#define SPARE_EMPTY   0
#define SPARE_FILLING 1
#define SPARE_READY   2
/* Запасная — это целая сессия дайлера, а берётся из неё только связь (dialer_ops.take).
 * Сессии лежат одним блоком в куче (stack_run), по SPARE_MAX штук шагом g_sess_stride: прежде
 * это был статический массив внутри таблицы, но размер сессии теперь называет дайлер. */
struct spare {
    void *sess;
    uint64_t born_ns;
    uint8_t state;
};
static struct spare g_spares[SPARE_MAX];
static pthread_mutex_t g_spare_mu = PTHREAD_MUTEX_INITIALIZER;
/* Сколько держать. Задаётся STEER_TUN_SPARES (0 выключает), читается один раз в
 * stack_run — до запуска потоков, поэтому дальше поле только читают. Ноль и у дайлера без
 * DC_PRECONNECT: связь, которой нужен адрес назначения, впрок не приготовить. */
static int g_spare_want;
/* Последний отказ установления запасной: пока узел не отвечает, пополнять пул — значит
 * занимать установщиков заведомо мёртвыми попытками наперегонки с живыми заявками. */
static uint64_t g_spare_fail_ns;
/* Отказов подряд (запасных и живых соединений вместе) — от него растёт пауза до следующего
 * пополнения: SPARE_PAUSE_MS << (n-1), не больше SPARE_PAUSE_MAX_MS. Любое удачное установление
 * обнуляет счёт. Прежде пауза была одна, пять секунд: узел, который не отвечает минутами, получал
 * по четыре лишних соединения каждые пять секунд, пока человек (или проверка в интерфейсе)
 * продолжал открывать соединения. */
static unsigned g_spare_fail_n;
#define SPARE_PAUSE_MS 5000
#define SPARE_PAUSE_MAX_MS 60000
/* Когда в последний раз приходило соединение: запасные копятся только под поток соединений.
 * Одиночное (проверка отклика, замер страны выхода) — это одно соединение к узлу, а не пять:
 * пять разом похожи на перебор для сервера с ограничением соединений с адреса, и тот начинает
 * отвечать на ClientHello молчанием. */
static uint64_t g_spare_syn_ns;
/* Часы запасных. Ноль — настоящие; стенд (tests/tunnelmatch.c) ставит своё время, чтобы считать
 * соединения за минуты без ожидания. */
static uint64_t g_spare_clock_ns;

/* Сессия передаётся указателем, а не считается установщиком по индексу: g_sess у каждого
 * потока своя, и SESS() в чужом потоке адресовал бы чужую таблицу. Ошибка была бы из тех,
 * что проявляются перепутанными кусками чужого соединения раз в сутки.
 *
 * c == NULL означает пополнение пула запасных: sp — слот g_spares, sess — его сессия, и
 * результат останется там же — забирать его некому, его найдёт следующий SYN. efd — eventfd
 * потока-заказчика: по готовности установщик будит его цикл, чтобы SYN-ACK... уже не
 * SYN-ACK (он ушёл сразу), а ранние данные не ждали до 20 мс опроса. Узла в заявке нет: он
 * один на процесс и лежит в дайлере (g_dl). */
struct connjob { struct conn *c; void *sess; struct spare *sp; int efd; };
/* Очередь заявок — кольцо, растущее вдвое: q[head .. head+n) по модулю cap. */
static struct {
    struct connjob *q;
    unsigned cap, head, n;
    unsigned nthreads, idle, max;   /* потоков всего, ждущих заявку, потолок */
    pthread_mutex_t mu;
    pthread_cond_t cv;
    int started;
} g_cq = { .mu = PTHREAD_MUTEX_INITIALIZER, .cv = PTHREAD_COND_INITIALIZER };

static uint64_t spare_now(void) { return g_spare_clock_ns ? g_spare_clock_ns : now_ns(); }

/* Исход установления соединения к узлу: отказ удлиняет паузу пополнения, успех её снимает. */
static void spare_note(int ok) {
    pthread_mutex_lock(&g_spare_mu);
    if (ok) {
        g_spare_fail_n = 0;
        g_spare_fail_ns = 0;
    } else {
        if (g_spare_fail_n < 32) g_spare_fail_n++;
        g_spare_fail_ns = spare_now();
    }
    pthread_mutex_unlock(&g_spare_mu);
}

static void *connector(void *arg) {
    int extra = arg != NULL;        /* сверх постоянных: уходит после простоя */
    for (;;) {
        pthread_mutex_lock(&g_cq.mu);
        while (g_cq.n == 0) {
            g_cq.idle++;
            if (extra) {
                struct timespec ts;
                clock_gettime(CLOCK_REALTIME, &ts);
                ts.tv_sec += CONNECTOR_IDLE_S;
                int er = pthread_cond_timedwait(&g_cq.cv, &g_cq.mu, &ts);
                g_cq.idle--;
                if (er == ETIMEDOUT && g_cq.n == 0) {
                    g_cq.nthreads--;
                    pthread_mutex_unlock(&g_cq.mu);
                    return NULL;
                }
            } else {
                pthread_cond_wait(&g_cq.cv, &g_cq.mu);
                g_cq.idle--;
            }
        }
        struct connjob j = g_cq.q[g_cq.head];
        g_cq.head = (g_cq.head + 1) % g_cq.cap;
        g_cq.n--;
        pthread_mutex_unlock(&g_cq.mu);

        if (!j.c) {
            /* Пополнение пула: сессия остаётся в своём слоте g_spares, будить некого —
             * её заберёт следующий SYN. Слот наш (FILLING), пока не отдадим. Исход слежке
             * за узлом докладывает сам дайлер — внутри connect. */
            struct spare *sp = j.sp;
            int rc = g_dl->ops->connect(g_dl->ctx, j.sess, CONNECT_TIMEOUT_S);
            pthread_mutex_lock(&g_spare_mu);
            if (rc == 0) {
                sp->born_ns = spare_now();
                sp->state = SPARE_READY;
            } else {
                sp->state = SPARE_EMPTY;
            }
            pthread_mutex_unlock(&g_spare_mu);
            spare_note(rc == 0);
            continue;
        }

        /* Исход — и слежке за узлом (под демоном): серия отказов зовёт её проверку раньше
         * срока. Докладывает дайлер, потому что мера «жив ли узел» — его. */
        int rc = g_dl->ops->connect(g_dl->ctx, j.sess, CONNECT_TIMEOUT_S);
        spare_note(rc == 0);
        j.c->rc = rc;
        /* RELEASE: цикл читает done с ACQUIRE, и всё, что записано в сессию выше, обязано
         * быть видно ему к этому моменту. Без барьера это ровно та ошибка, которая
         * проявляется раз в сутки на другой архитектуре. */
        __atomic_store_n(&j.c->done, 1, __ATOMIC_RELEASE);
        /* Разбудить цикл заказчика: без этого готовое рукопожатие ждало опроса — до
         * 20 мс сверху на каждое соединение. Дескриптор жив, пока жив цикл: перед
         * выходом тот дожидается своих заявок (connq_release) и лишь потом закрывает
         * eventfd, поэтому писать в чужой переиспользованный номер мы не можем. */
        if (j.efd >= 0) {
            uint64_t one = 1;
            ssize_t wr = write(j.efd, &one, sizeof(one));
            (void)wr;   /* переполнение счётчика eventfd — это и так «уже разбужен» */
        }
    }
    return NULL;
}

/* Завести установщика; 0 — встал. Под g_cq.mu. */
static int connector_spawn(int extra) {
    pthread_attr_t a;
    pthread_attr_init(&a);
    /* Стек скромный: рукопожатие держит крупные буферы в __thread, а не на стеке. TLS сверх него —
     * thread_stack (у glibc она берётся из стека, и 128 КБ без неё — EINVAL). */
    pthread_attr_setstacksize(&a, thread_stack(128 * 1024));
    pthread_attr_setdetachstate(&a, PTHREAD_CREATE_DETACHED);
    pthread_t t;
    int err = pthread_create(&t, &a, connector, extra ? (void *)&g_cq : NULL);
    pthread_attr_destroy(&a);
    if (err != 0) return err;
    g_cq.nthreads++;
    return 0;
}

/* Поставить заявку в очередь; заводит потоки-установщики при первом вызове и по нагрузке.
 * 0 — принята, -2 — установщиков нет ни одного, -1 — нет памяти под очередь (предела «очередь полна»
 * больше нет: очередь растёт).
 *
 * Запущенной очередь считается, только если создался хотя бы один установщик (I-322).
 * Прежде started ставился до pthread_create, и при отказе всех созданий заявки копились в
 * очереди, которую никто не разбирает: клиент получал SYN-ACK, а дальше ни данных, ни RST,
 * и повторной попытки завести потоки не было уже никогда. Теперь отказ говорит в журнал,
 * заявка отклоняется, а следующая заявка пробует завести установщиков снова. */
static int connq_push(const struct connjob *j) {
    pthread_mutex_lock(&g_cq.mu);
    if (!g_cq.started) {
        if (!g_cq.max) {
            const char *e = getenv("STEER_TUN_CONNECTORS");
            int v = e ? atoi(e) : 0;
            g_cq.max = v >= 1 ? (unsigned)v : CONNECTORS_MAX;
        }
        int err = 0;
        for (unsigned i = 0; i < CONNECTORS && i < g_cq.max; i++) {
            err = connector_spawn(0);
            if (err != 0) break;
        }
        if (!g_cq.nthreads) {
            static time_t said;
            if (g_now_s - said >= 5) {
                said = g_now_s;
                fprintf(stderr, LOG_W "потоки установки соединений не создаются (%s) — "
                                "новые соединения через туннель отклоняются\n", strerror(err));
            }
            pthread_mutex_unlock(&g_cq.mu);
            return -2;
        }
        g_cq.started = 1;
    }
    if (g_cq.n == g_cq.cap) {
        unsigned nc = g_cq.cap ? g_cq.cap * 2 : 64;
        struct connjob *nq = malloc((size_t)nc * sizeof(*nq));
        if (!nq) { pthread_mutex_unlock(&g_cq.mu); return -1; }
        for (unsigned i = 0; i < g_cq.n; i++) nq[i] = g_cq.q[(g_cq.head + i) % g_cq.cap];
        free(g_cq.q);
        g_cq.q = nq;
        g_cq.cap = nc;
        g_cq.head = 0;
    }
    g_cq.q[(g_cq.head + g_cq.n) % g_cq.cap] = *j;
    g_cq.n++;
    /* Ждущих меньше, чем заявок, — нужен ещё один установщик (отказ создания не страшен: прежние
     * разберут очередь, только дольше). */
    if (g_cq.n > g_cq.idle && g_cq.nthreads < g_cq.max) connector_spawn(1);
    pthread_cond_signal(&g_cq.cv);
    pthread_mutex_unlock(&g_cq.mu);
    return 0;
}

/* Взять готовую запасную сессию. 0 — out заполнен и сессия наша, -1 — пусто.
 *
 * Берётся САМАЯ СТАРАЯ из годных: свежие переживут ещё один SYN, а старую иначе всё
 * равно выбросил бы срок. Протухшие закрываются прямо здесь — это не горячий путь,
 * SYN приходят десятками в секунду, не тысячами. */
static int spare_checkout(void *out) {
    const struct dialer_ops *d = g_dl->ops;
    uint64_t now = spare_now();
    struct spare *best = NULL;
    pthread_mutex_lock(&g_spare_mu);
    for (int i = 0; i < SPARE_MAX; i++) {
        struct spare *sp = &g_spares[i];
        if (sp->state != SPARE_READY) continue;
        if ((now - sp->born_ns) / 1000000 >= SPARE_TTL_MS) {
            d->close(sp->sess);
            sp->state = SPARE_EMPTY;
            continue;
        }
        /* Сервер мог успеть закрыть парковку — это видно без чтения. POLLIN сам по
         * себе не приговор: там может лежать NewSessionTicket, чтение его пропустит. */
        struct pollfd pd = { .fd = d->fd(sp->sess), .events = POLLIN | POLLRDHUP };
        if (poll(&pd, 1, 0) > 0 && (pd.revents & (POLLERR | POLLHUP | POLLRDHUP))) {
            d->close(sp->sess);
            sp->state = SPARE_EMPTY;
            continue;
        }
        /* Узлов несколько (пул, pool.c): запасная связь — к своему узлу, и годится не всякому
         * соединению; связь к узлу, который больше не активен, — выбросить. */
        int m = d->match ? d->match(g_dl->ctx, out, sp->sess) : 1;
        if (m < 0) {
            d->close(sp->sess);
            sp->state = SPARE_EMPTY;
            continue;
        }
        if (!m) continue;
        if (!best || sp->born_ns < best->born_ns) best = sp;
    }
    /* Переселение связи — у дайлера: что в сессии связь, а что состояние потока, и какие в
     * связи указатели на саму себя (у HTTP/2 их два, см. xhttp_moved в trxhttp.c), знает он, а
     * не стек. Под замком, как прежде копия: слот станет пустым только после неё. */
    if (best) {
        d->take(out, best->sess);
        best->state = SPARE_EMPTY;
    }
    pthread_mutex_unlock(&g_spare_mu);
    return best ? 0 : -1;
}

/* Закрыть протухшие запасные сессии.
 *
 * Нужно потому, что spare_checkout вызывается только на SYN: перестань клиент открывать
 * соединения — и пул остаётся набитым НАВСЕГДА. Сервер такую парковку закрывает через
 * несколько секунд сам, но с нашей стороны это по-прежнему открытый дескриптор и ~19 КБ
 * буферов TLS на каждый; на роутере с 15 МБ держать их сутками ради соединений, которых
 * никто не открывает, незачем.
 *
 * Зовётся из прохода по срокам, раз в секунду на поток: восемь слотов под уже взятым
 * мьютексом — это дешевле, чем одна проверка одного соединения рядом. */
static void spare_sweep(void) {
    if (g_spare_want <= 0) return;
    uint64_t now = spare_now();
    pthread_mutex_lock(&g_spare_mu);
    for (int i = 0; i < SPARE_MAX; i++) {
        struct spare *sp = &g_spares[i];
        if (sp->state != SPARE_READY) continue;
        if ((now - sp->born_ns) / 1000000 < SPARE_TTL_MS) continue;
        g_dl->ops->close(sp->sess);
        sp->state = SPARE_EMPTY;
    }
    pthread_mutex_unlock(&g_spare_mu);
}

/* Пополнить пул до want. Вызывается на каждый SYN — то есть ровно тогда, когда
 * соединения действительно открывают. Слоты резервируются под замком, заявки уходят
 * без него: connq_push берёт свой мьютекс, и держать два вложенными незачем. */
static void spare_refill(void) {
    if (g_spare_want <= 0) return;
    int fill[SPARE_MAX];
    int nfill = 0;
    pthread_mutex_lock(&g_spare_mu);
    uint64_t now = spare_now();
    uint64_t prev = g_spare_syn_ns;
    g_spare_syn_ns = now;
    /* Первое соединение после затишья — без запасных: копить их есть под что, только когда
     * соединения идут потоком (следующее придёт раньше, чем протухнет запасная). */
    if (!prev || (now - prev) / 1000000 >= SPARE_TTL_MS) {
        pthread_mutex_unlock(&g_spare_mu);
        return;
    }
    if (g_spare_fail_ns) {
        uint64_t pause = g_spare_fail_n > 5 ? SPARE_PAUSE_MAX_MS
                       : (uint64_t)SPARE_PAUSE_MS << (g_spare_fail_n > 1 ? g_spare_fail_n - 1 : 0);
        if (pause > SPARE_PAUSE_MAX_MS) pause = SPARE_PAUSE_MAX_MS;
        if ((now - g_spare_fail_ns) / 1000000 < pause) {
            pthread_mutex_unlock(&g_spare_mu);
            return;
        }
    }
    int have = 0;
    for (int i = 0; i < SPARE_MAX; i++)
        if (g_spares[i].state != SPARE_EMPTY) have++;
    for (int i = 0; i < SPARE_MAX && have + nfill < g_spare_want; i++) {
        if (g_spares[i].state != SPARE_EMPTY) continue;
        g_spares[i].state = SPARE_FILLING;
        fill[nfill++] = i;
    }
    pthread_mutex_unlock(&g_spare_mu);

    for (int k = 0; k < nfill; k++) {
        struct connjob j = { .c = NULL, .sess = g_spares[fill[k]].sess, .sp = &g_spares[fill[k]],
                             .efd = -1 };
        if (connq_push(&j) != 0) {
            /* Очередь полна — живые заявки важнее. Вернуть ВСЕ оставшиеся резервы:
             * слот в состоянии FILLING без заявки не заполнит никто и никогда. */
            pthread_mutex_lock(&g_spare_mu);
            for (; k < nfill; k++) g_spares[fill[k]].state = SPARE_EMPTY;
            pthread_mutex_unlock(&g_spare_mu);
            return;
        }
    }
}

/* Снять из очереди заявки этого потока и дождаться тех, что уже в работе.
 *
 * Нужно на выходе из цикла — а он выходит, если epoll вернул ошибку. Без этого слив таблицы
 * закрывал сессию, с которой в тот момент работает установщик, и дальше происходили сразу две
 * разные беды:
 *
 *   - закрытие сессии отдавало ядру дескриптор, которым установщик ещё пользуется. Номер тут
 *     же достаётся другому потоку, и куски чужого соединения уезжают не туда — ровно тот класс
 *     ошибок, ради которого заявка и несёт указатель на сессию, а не индекс;
 *   - таблицы и сессии принадлежат потоку-владельцу. Он возвращается из worker_loop и
 *     освобождает их (прежде — вместе с TLS, теперь — munmap), а установщик продолжает писать
 *     по прежнему адресу.
 *
 * Необслуженные заявки просто выбрасываем: установщик их ещё не брал, ждать нечего. Ждать
 * приходится только взятых, их не больше числа установщиков, и каждая ограничена таймаутом connect.
 *
 * Возвращает 0, если отпустили всех, и -1, если кто-то так и не доложил. По -1 таблицу
 * сливать НЕЛЬЗЯ — освобождать её под работающим установщиком это и есть то, от чего мы тут
 * защищаемся. Тогда честнее утечь: путь и так предсмертный, а процесс перезапустит procd. */
static int connq_release(struct conn *base) {
    if (g_inloop) return 0;     /* установщиков нет: заявок в очереди и в работе не бывает */
    pthread_mutex_lock(&g_cq.mu);
    unsigned kept = 0;
    for (unsigned i = 0; i < g_cq.n; i++) {
        struct connjob j = g_cq.q[(g_cq.head + i) % g_cq.cap];
        if (j.c >= base && j.c < base + g_nslots) {
            j.c->pending = 0;            /* нашу запись больше никто не тронет */
            continue;
        }
        g_cq.q[(g_cq.head + kept++) % g_cq.cap] = j;
    }
    g_cq.n = kept;
    pthread_mutex_unlock(&g_cq.mu);

    /* Взятые в работу: ждём доклада. Предел щедрый — таймаут установления восемь секунд, и
     * пережидать его дешевле, чем разбираться в порче памяти на живом роутере.
     *
     * Проверка стоит и ПОСЛЕ последнего сна: прежде она шла только перед каждым, и доклад,
     * пришедший за последние 10 мс, не спрашивался вовсе — приговор «не доложил» ставился
     * по счётчику кругов, и таблица утекала там, где освобождать было уже можно (I-193). */
    for (int spin = 0;; spin++) {
        int busy = 0;
        for (size_t i = 0; i < g_nslots; i++)
            if (base[i].used && base[i].pending &&
                !__atomic_load_n(&base[i].done, __ATOMIC_ACQUIRE)) busy++;
        if (!busy) return 0;
        if (spin == 1500) break;
        struct timespec ts = { .tv_sec = 0, .tv_nsec = 10 * 1000 * 1000 };
        nanosleep(&ts, NULL);
    }
    fprintf(stderr, LOG_W "установщик не доложил за 15 с, таблица не освобождается\n");
    return -1;
}

/* eventfd цикла этого потока: установщик пишет в него по готовности заявки. Живёт от
 * входа в worker_loop до выхода; -1, если ядро eventfd не дало, — тогда работает
 * прежний опрос раз в 20 мс. */
static __thread int g_conn_efd = -1;

/* Поставить заявку. 0 — принята, иначе отказ connq_push (нет памяти или установщиков). */
static int conn_submit(struct conn *c) {
    if (g_inloop) {
        /* Без установщика: открытие начинает сам дайлер, здесь же, и не ждёт ответа узла. Исход — через
         * stack_sess_ready (когда придёт, не раньше), а отказ на месте — кодом. Заявка при этом такая же:
         * pending до тех пор, пока done не поднят, — разбирает её тот же проход цикла. */
        c->done = 0;
        int rc = g_dl->ops->connect(g_dl->ctx, SESS(c), CONNECT_TIMEOUT_S);
        if (rc) {
            c->rc = rc;
            __atomic_store_n(&c->done, 1, __ATOMIC_RELEASE);
        }
        return 0;
    }
    struct connjob j = { .c = c, .sess = SESS(c), .sp = NULL, .efd = g_conn_efd };
    return connq_push(&j);
}

/* Таблица заводится один раз на поток: слотов пока нет, корзины пусты. 0 — готово, -1 — памяти под
 * неё нет.
 *
 * Одно отображение (mmap) на всё, и резерв, а не выделение: PROT_NONE ничего не стоит, и память
 * (mprotect на чтение-запись, свежие нулевые страницы от ядра) берётся кусками по CONN_CHUNK слотов в
 * conn_slot_grow. Четыре массива лежат в резерве один за другим, каждый от границы страницы: горячая
 * таблица, список живых, свободные и — после них — сессии дайлера шагом g_sess_stride. Резерв не
 * получился — берём вдвое меньше, пока не получится (потолок объяснён у CONN_CHUNK). */
static int conn_table_init(void) {
    if (!g_conns) {
        size_t pg = (size_t)sysconf(_SC_PAGESIZE);
        size_t cap = g_slots_want;
        if (!cap) cap = sizeof(void *) >= 8 ? (size_t)1 << 20 : (size_t)1 << 13;
        if (cap > SLOTS_IDX_MAX) cap = SLOTS_IDX_MAX;
        void *m = MAP_FAILED;
        size_t len = 0, off_live = 0, off_free = 0, off_sess = 0;
        for (;; cap /= 2) {
#define PGUP(x) (((x) + pg - 1) & ~(pg - 1))
            off_live = PGUP(cap * sizeof(struct conn));
            off_free = off_live + PGUP(cap * sizeof(uint32_t));
            off_sess = off_free + PGUP(cap * sizeof(uint32_t));
            len = off_sess + PGUP(cap * g_sess_stride);
            m = mmap(NULL, len, PROT_NONE, MAP_PRIVATE | MAP_ANONYMOUS | MAP_NORESERVE, -1, 0);
            if (m != MAP_FAILED || cap <= CONN_CHUNK) break;
        }
        if (m == MAP_FAILED) return -1;
        g_conns = m;
        g_tab_base = m;
        g_tab_page = pg;
        g_tab_off_live = off_live;
        g_tab_off_free = off_free;
        g_tab_off_sess = off_sess;
        g_live = (uint32_t *)(g_tab_base + off_live);
        g_freelist = (uint32_t *)(g_tab_base + off_free);
        g_sess = g_tab_base + off_sess;
        g_tables_len = len;
        g_slots_cap = cap;
        g_slots_commit = g_nslots = 0;
        g_bucket_mask = CONN_BUCKETS - 1;
        g_bucket = malloc(CONN_BUCKETS * sizeof(*g_bucket));
        if (!g_bucket) { munmap(m, len); g_conns = NULL; g_tables_len = 0; return -1; }
    }
    g_live_n = 0;
    g_free_n = 0;
    for (size_t i = 0; i <= g_bucket_mask; i++) g_bucket[i] = -1;
    /* Перезапуск таблицы (стенд): уже выданные слоты возвращаются в свободные целиком. */
    for (size_t i = g_nslots; i-- > 0;) {
        g_conns[i].livepos = -1;
        g_conns[i].hnext = -1;
        g_conns[i].fd = -1;
        g_conns[i].aux = -1;
        g_freelist[g_free_n++] = (uint32_t)i;
    }
    return 0;
}

/* Вернуть таблицы потока системе. Только когда установщики отпущены (connq_release вернул 0):
 * иначе они писали бы в снятое отображение. */
static void conn_table_free(void) {
    if (!g_conns) return;
    munmap(g_tab_base, g_tables_len);
    free(g_bucket);
    g_conns = NULL;
    g_tab_base = NULL;
    g_live = g_freelist = NULL;
    g_bucket = NULL;
    g_sess = NULL;
    g_tables_len = 0;
    g_slots_cap = g_slots_commit = g_nslots = 0;
}

/* Взять в работу страницы [from, to) элементов массива с шагом elem от base: страницы целиком, от
 * границы вниз до границы вверх — соседний массив лежит с границы страницы, и перекрытия нет. */
static int tab_commit(unsigned char *base, size_t elem, size_t from, size_t to) {
    size_t pg = g_tab_page;
    size_t lo = (from * elem) & ~(pg - 1);
    size_t hi = (to * elem + pg - 1) & ~(pg - 1);
    return mprotect(base + lo, hi - lo, PROT_READ | PROT_WRITE);
}

/* Дать таблице ещё CONN_CHUNK слотов памяти. 0 — дано, -1 — резерв кончился или ядро отказало. */
static int conn_slots_grow(void) {
    size_t to = g_slots_commit + CONN_CHUNK;
    if (to > g_slots_cap) to = g_slots_cap;
    if (to == g_slots_commit) return -1;
    size_t from = g_slots_commit;
    if (tab_commit((unsigned char *)g_conns, sizeof(struct conn), from, to) != 0 ||
        tab_commit(g_tab_base + g_tab_off_live, sizeof(uint32_t), from, to) != 0 ||
        tab_commit(g_tab_base + g_tab_off_free, sizeof(uint32_t), from, to) != 0 ||
        tab_commit(g_sess, g_sess_stride, from, to) != 0)
        return -1;
    g_slots_commit = to;
    return 0;
}

/* Слот под новое соединение: свободный из списка, а если его нет — следующий не выдававшийся (память
 * под него берётся здесь же). NULL — слотов больше нет (резерв или память). Слот выдаётся обнулённым
 * ядром, кроме признаков «пусто», которые не нули. */
static struct conn *conn_slot(void) {
    if (g_free_n) return &g_conns[g_freelist[--g_free_n]];
    if (g_nslots == g_slots_commit && conn_slots_grow() != 0) return NULL;
    struct conn *c = &g_conns[g_nslots++];
    c->livepos = -1;
    c->hnext = -1;
    c->fd = -1;
    c->aux = -1;
    g_dl->ops->clear(SESS(c));
    return c;
}

/* Один ли адрес у двух ключей: семейство и сами адреса (четыре байта у IPv4, шестнадцать у IPv6). */
static inline int flow_same_addr(const struct flow_key *a, const struct flow_key *b) {
    if (a->v6 != b->v6) return 0;
    if (a->v6) return !memcmp(a->src6, b->src6, 16) && !memcmp(a->dst6, b->dst6, 16);
    return a->src == b->src && a->dst == b->dst;
}

static struct conn *conn_find(const struct flow_key *k) {
    for (int32_t i = g_bucket[flow_hash(k) & g_bucket_mask]; i >= 0; i = g_conns[i].hnext) {
        struct conn *c = &g_conns[i];
        if (flow_same_addr(&c->key, k) &&
            c->key.sport == k->sport && c->key.dport == k->dport &&
            c->key.proto == k->proto)
            return c;
    }
    return NULL;
}

/* Корзин стало меньше, чем живых: вдвое больше, цепочки пересобираются обходом живых. Не вышло с
 * памятью — цепочки просто длиннее, поиск не ломается. */
static void conn_buckets_grow(void) {
    size_t nb = ((size_t)g_bucket_mask + 1) * 2;
    int32_t *nbk = malloc(nb * sizeof(*nbk));
    if (!nbk) return;
    for (size_t i = 0; i < nb; i++) nbk[i] = -1;
    uint32_t nmask = (uint32_t)nb - 1;
    for (int li = 0; li < g_live_n; li++) {
        struct conn *c = &g_conns[g_live[li]];
        unsigned b = flow_hash(&c->key) & nmask;
        c->hnext = nbk[b];
        nbk[b] = (int32_t)g_live[li];
    }
    free(g_bucket);
    g_bucket = nbk;
    g_bucket_mask = nmask;
}

/* Внести слот в список живых и в хэш. Вызывается одним местом — рождением соединения. */
static void conn_link(struct conn *c) {
    int32_t idx = (int32_t)(c - g_conns);
    if ((size_t)g_live_n > g_bucket_mask) conn_buckets_grow();
    c->livepos = g_live_n;
    g_live[g_live_n++] = (uint32_t)idx;
    unsigned b = flow_hash(&c->key) & g_bucket_mask;
    c->hnext = g_bucket[b];
    g_bucket[b] = idx;
}

/* Убрать из списка живых и из хэша. Дыра в g_live закрывается последним элементом: порядок
 * обхода никому не важен, а сдвиг хвоста стоил бы тем дороже, чем больше соединений. */
static void conn_unlink(struct conn *c) {
    int32_t idx = (int32_t)(c - g_conns);
    if (c->livepos >= 0) {
        int last = --g_live_n;
        uint32_t moved = g_live[last];
        g_live[c->livepos] = moved;
        g_conns[moved].livepos = c->livepos;
        c->livepos = -1;
    }
    unsigned b = flow_hash(&c->key) & g_bucket_mask;
    int32_t *slot = &g_bucket[b];
    while (*slot >= 0) {
        if (*slot == idx) { *slot = c->hnext; break; }
        slot = &g_conns[*slot].hnext;
    }
    c->hnext = -1;
}

static void conn_drop(struct conn *c);

/* Порция данных клиента на одну отправку узлу, если дайлер не называет большей: место дайлера под
 * заголовок и кадр Vision. */
#define UP_MAX (TUNNEL_BUF - 2048)

/* Слот под новое соединение: свободный, а если таблица дошла до потолка (см. CONN_CHUNK) — освободить
 * простаивающее.
 *
 * Таблица растёт (conn_slot), поэтому вытеснение — крайняя мера у потолка адресного пространства или
 * памяти, а не обычный путь при сотне вкладок, как было при жёстких 320. Вытесняется ТОЛЬКО то, что
 * уже ничего не принесёт: закрытое сервером, поток DNS, сделавший своё, и простой дольше
 * IDLE_EVICT_S. Живое соединение не вытесняется никогда — при отказе клиент повторит SYN, а
 * вытеснение живого ломало HTTP/2 залпом ERR_CONNECTION_CLOSED.
 *
 * Возвращает NULL, если вытеснять нечего: все слоты (названное в журнале число) заняты и активны. */
static struct conn *conn_new(const struct tun_dev *tun) {
    (void)tun;
    struct conn *fresh = conn_slot();
    if (fresh) return fresh;

    time_t now = g_now_s;
    struct conn *old = NULL;
    for (int li = 0; li < g_live_n; li++) {
        struct conn *c = &g_conns[g_live[li]];
        /* Закрытые сервером — первые кандидаты в любом возрасте: они уже ничего не принесут,
         * а живут только чтобы додать клиенту остаток. */
        if (c->pending) continue;        /* установщик пишет в эту запись — не трогать */
        int cheap = c->srv_closed != 0;
        /* Остальные — только если ДЕЙСТВИТЕЛЬНО простаивают. Порог не осторожность, а
         * исправление: без него вытеснялось самое давнее из ЖИВЫХ, и это оказалось хуже
         * прежнего молчаливого отказа. Каждый новый SYN стоит блокирующего рукопожатия
         * (100-400 мс), и приняв его ценой ещё работающего соединения, мы на одном ядре
         * получаем молотилку: цикл занят рукопожатиями, обслуживать существующие некогда,
         * клиенты повторяют, SYN'ов больше. На роутере это выглядело как «вообще ничего не
         * открывается», и в логе шла ровно эта строка по десять раз в секунду.
         *
         * Если простаивающих нет, честный ответ — отказать. Отказ дёшев: клиент повторит
         * SYN через секунду, и к тому времени место, скорее всего, освободится. */
        /* Поток DNS (UDP на порт 53) — исключение из порога. Резолвер берёт новый исходный
         * порт на каждый запрос, поэтому такой поток — один запрос и один ответ, и через
         * DNS_IDLE_S молчания он своё сделал: ответ либо пришёл, либо клиент уже спросил
         * заново с другого порта. По общему порогу он выглядел активным все 120 с, и таблица,
         * забитая ими, отказывала новым соединениям, включая обычный TCP (I-055). Срок
         * простоя при этом НЕ меняется: исключение действует только здесь, когда свободных
         * мест нет и иначе пришлось бы отказать. */
        int dns_done = c->is_udp && c->key.dport == 53 && now - c->last >= DNS_IDLE_S;
        if (!cheap && !dns_done && now - c->last < IDLE_EVICT_S) continue;
        if (!old || cheap > (old->srv_closed != 0) ||
            (cheap == (old->srv_closed != 0) && c->last < old->last))
            old = c;
    }
    if (!old) {
        /* Молчать нельзя — именно за это пришлось искать причину полдня, — но и писать на
         * каждый пакет тоже: одна строка в две секунды. */
        static __thread time_t said;
        if (now != said && now - said >= 2) {
            said = now;
            fprintf(stderr, LOG_W "все %zu соединений потока заняты и активны, новые "
                            "отклоняются — потолок слотов (адресное пространство или память)\n", g_nslots);
        }
        return NULL;
    }

    /* RST — только вытесняемому TCP: он ждёт ответа по открытому соединению и без отказа
     * досиживал бы до своего таймаута. У потока UDP такого ожидания нет вовсе, а RST на
     * датаграмму — пакет, которого клиентский стек не поймёт. */
    if (old->cfd1) {
        struct linger lg = { 1, 0 };     /* вытеснение — RST клиенту: закрытие с SO_LINGER 0 */
        setsockopt(conn_cfd(old), SOL_SOCKET, SO_LINGER, &lg, sizeof(lg));
    }
    /* В лог — не чаще раза в десять секунд. Вытеснение мёртвого соединения это уборка, а не
     * событие: на живом роутере таких строк набегало по тридцать шесть за сорок секунд, и все
     * они сообщали «всё хорошо» тревожным тоном. Лог, который кричит в норме, перестают
     * читать — и тогда он молчит и в настоящей беде. */
    static __thread time_t said_evict;
    if (now - said_evict >= 10) {
        said_evict = now;
        fprintf(stderr, LOG_W "таблица на потолке (%zu слотов), убираю простаивающее "
                        "(молчало %lu с)\n", g_nslots, (unsigned long)(now - old->last));
    }
    conn_drop(old);
    /* conn_drop вернул слот в список свободных — забираем его оттуда же, а не по прежнему
     * указателю. Иначе слот остался бы и у нас, и в списке, и следующий SYN получил бы
     * ЗАНЯТУЮ запись: одно соединение под двумя потоками, перепутанные данные, и найти это
     * можно только по симптому «иногда приходит чужая страница». */
    return &g_conns[g_freelist[--g_free_n]];
}

/* Освободить слот. Из epoll дескриптор уходит сам при close — отдельного epoll_ctl не
 * нужно, и делать его после close значило бы ходить в ядро с закрытым номером. */
static void conn_drop(struct conn *c) {
    TR("закрываю conn#%ld fd=%d\n", (long)(c - g_conns), c->fd);
    if (c->used) {
        g_dl->ops->close(SESS(c));
        conn_unlink(c);
        g_freelist[g_free_n++] = (uint32_t)(c - g_conns);
    }
    rtx_done(&c->rtx);
    free(c->early);
    /* Сокет клиента: обычное закрытие — ядро допишет отданное и пошлёт FIN; RST — если conn_reset
     * поставил SO_LINGER 0. Из epoll его снимает само закрытие. */
    if (c->cfd1) close(conn_cfd(c));
    /* Толстую половину НЕ трём целиком: десятки килобайт memset на каждое закрытие — это
     * десятки килобайт, прогнанных через кэш ради нулей, которые всё равно перепишет открытие
     * связи. Сессию к новому соединению готовит дайлер (clear), трогая только её начало. */
    memset(c, 0, sizeof(*c));
    c->fd = -1;
    c->aux = -1;
    c->livepos = -1;
    c->hnext = -1;
    g_dl->ops->clear(SESS(c));
}

/* Сколько клиент может прислать сейчас, не вылезая за то, что мы способны принять. Пока установщик
 * ещё работает (pending), принять можно только то, что влезет в буфер ранних данных (EARLY_CAP):
 * остальное handle_packet не подтверждает, и клиенту, который уже отправил окно из десяти сегментов,
 * дыра стоит таймаута повторной передачи, а следом ещё одного и ещё: Linux без SACK после первого
 * таймаута уходит в состояние потери, где дубликаты ACK быстрый повтор не запускают, а мы сегменты
 * за дырой выбрасываем, и таймаут удваивается на каждом круге (выгрузка стоит дольше десяти секунд).
 * Окно, которое не обещает лишнего, дыры не создаёт вовсе.
 *
 * Для готового соединения — dialer_ops.room; -1 — предела нет или он не применим (UDP). */
static long conn_room(const struct conn *c) {
    if (c->is_udp) return -1;
    if (c->pending) return c->early_n >= EARLY_CAP ? 0 : (long)(EARLY_CAP - c->early_n);
    if (c->fd < 0 || !g_dl->ops->room) return -1;
    return g_dl->ops->room(g_dl->ctx, SESS(c));
}

/* Связь соединения отдана циклу: запись узлу больше не ждёт сокета (dialer_ops.live, I-534). */
static void conn_live(struct conn *c) {
    if (g_dl->ops->live) g_dl->ops->live(SESS(c));
}

/* Сколько байт связь ещё не отправила узлу (dialer_ops.out_pending). */
static size_t conn_out_pending(const struct conn *c) {
    if (c->fd < 0 || !g_dl->ops->out_pending) return 0;
    return g_dl->ops->out_pending(g_dl->ctx, SESS(c));
}

/* Сколько байт клиента соединения c собирается в одну отправку (см. dialer_ops.up_max). Пока
 * соединение не готово или дайлер не называет большего — UP_MAX: место дайлера под заголовок и
 * кадр Vision. */
static size_t conn_up_max(const struct conn *c) {
    if (c->is_udp || c->pending || c->fd < 0 || !g_dl->ops->up_max) return UP_MAX;
    size_t m = g_dl->ops->up_max(g_dl->ctx, SESS(c));
    if (m < UP_MAX) return UP_MAX;
    return m > SOCK_READ_MAX ? SOCK_READ_MAX : m;
}

/* Отправить узлу данные клиента. Форма — заголовок запроса, обёртки, упаковка транспорта —
 * дело дайлера (dialer_ops.send); итог — SEND_* (dialer.h). */
static int upstream_send(struct conn *c, const unsigned char *data, size_t n) {
    int sr = g_dl->ops->send(g_dl->ctx, SESS(c), &c->key, c->is_udp, data, n);
    if (sr == SEND_OK) c->sent_any = 1;
    return sr;
}

/* RST клиенту и освобождение записи: закрытие сокета с SO_LINGER 0.
 *
 * У потока UDP отвечать нечем: сбрасывать нечего, соединения в понимании клиента нет
 * вовсе. Молча закрываем — клиент узнает об этом отсутствием ответа, как узнаёт о любой
 * потерянной датаграмме. */
static void conn_reset(struct conn *c, const struct tun_dev *tun) {
    (void)tun;
    if (c->cfd1) {
        struct linger lg = { 1, 0 };
        setsockopt(conn_cfd(c), SOL_SOCKET, SO_LINGER, &lg, sizeof(lg));
    }
    conn_drop(c);
}

/* Связь соединения с узлом кончилась ошибкой: если она оборвана (node_sock_aborted), сказать дайлеру
 * — у слежки за узлом это повод проверить его сейчас. 1 — оборвана. */
static int conn_node_lost(struct conn *c) {
    if (!(g_inloop ? g_dl->ops->aborted(SESS(c)) : node_sock_aborted(c->fd))) return 0;
    if (g_dl->ops->lost) g_dl->ops->lost(g_dl->ctx, SESS(c));
    return 1;
}

/* Отдать серверу ранние данные. 0 — буфер пуст и освобождён; 1 — остался хвост (окно
 * h2 закрыто, дошлём позже); -1 — поток сломан, соединению конец. Пока хвост не ушёл,
 * никакие свежие данные клиента серверу не отправляются — иначе байты поменяются
 * местами, а TCP-поток этого не прощает. */
static int early_flush(struct conn *c) {
    while (c->early_off < c->early_n) {
        if (c->is_udp) {
            /* Датаграммы — по одной, каждая своим вызовом (длина впереди — своя, см. udp_send_dgram):
             * дайлер вправе слать датаграмму отдельным сообщением (hysteria2 — датаграммой QUIC), и
             * склейка превратила бы их в одну. Хвост остаётся с границы датаграммы. */
            uint32_t dl;
            memcpy(&dl, c->early + c->early_off, sizeof(dl));
            if (dl > c->early_n - c->early_off - sizeof(dl)) return -1;
            int sr = upstream_send(c, c->early + c->early_off + sizeof(dl), dl);
            if (sr == SEND_AGAIN) return 1;
            if (sr != SEND_OK) return -1;
            c->early_off += (uint32_t)sizeof(dl) + dl;
            continue;
        }
        size_t chunk = c->early_n - c->early_off;
        /* Запас под заголовок запроса и обёртку (у VLESS — кадр Vision): дайлер клеит их в один буфер
         * TUNNEL_BUF. У сокета клиента — порция под одну запись TLS (SOCK_SEND_CHUNK, см. sock_read). */
        size_t lim = c->cfd1 ? SOCK_SEND_CHUNK : TUNNEL_BUF - 2048;
        if (chunk > lim) chunk = lim;
        int sr = upstream_send(c, c->early + c->early_off, chunk);
        if (sr == SEND_AGAIN) return 1;
        if (sr != SEND_OK) return -1;
        c->early_off += (uint32_t)chunk;
    }
    free(c->early);
    c->early = NULL;
    c->early_n = c->early_off = c->early_cap = 0;
    return 0;
}

/* Придержать данные до готовности потока. 0 — взяли, -1 — не поместилось или нет памяти.
 *
 * Одна функция на TCP и UDP, потому что придерживается в обоих случаях РОВНО ТО, что уйдёт
 * серверу: у TCP это поток байт как есть, у UDP — уже обрамлённые дайлером датаграммы
 * (dgram_frame), каждая со своей длиной впереди (udp_send_dgram): обрамление границ не несёт у
 * всех — у hysteria2 датаграмма уходит как есть, и склеенные они приходили серверу одной. */
static int early_hold(struct conn *c, const unsigned char *d, size_t n) {
    uint32_t cap = c->early_cap ? c->early_cap : EARLY_CAP;
    if (n > cap - c->early_n) return -1;
    if (!c->early) {
        c->early = malloc(cap);
        if (!c->early) return -1;
    }
    memcpy(c->early + c->early_n, d, n);
    c->early_n += (uint32_t)n;
    return 0;
}

/* Место под датаграмму UDP, которая крупнее EARLY_CAP, пока поток к узлу ещё открывается.
 *
 * Без этого первая датаграмма потока крупнее 8 КиБ терялась БЕЗ повтора: у UDP нет
 * подтверждений, а клиент, отправивший её один раз (DNS по UDP с большим ответом, обмен
 * WireGuard внутри туннеля, игра), ждёт ответа, которого не будет. Буфер растёт до размера
 * ЭТОЙ датаграммы и только когда он пуст: придерживается не больше одной крупной. Цена —
 * не больше UDP_DGRAM_ABS + 66 байт на соединение, и только у соединения, чья первая
 * датаграмма крупная, пока длится рукопожатие; при предельных 320 соединениях и все с
 * максимальной датаграммой это ~20 МиБ на секунды, чего обычная работа не даёт.
 * 0 — место есть (или готово), -1 — нет. */
static int early_reserve(struct conn *c, size_t need) {
    uint32_t cap = c->early_cap ? c->early_cap : EARLY_CAP;
    if (need <= cap - c->early_n) return 0;
    if (c->early_n || need > UDP_DGRAM_ABS + 66) return -1;
    free(c->early);
    c->early = malloc(need);
    if (!c->early) { c->early_cap = 0; return -1; }
    c->early_cap = (uint32_t)need;
    return 0;
}

/* ---- UDP -------------------------------------------------------------------- */
/* Номер IP-пакета для датаграмм, отдаваемых клиенту. Осмыслен только при нарезке: по нему
 * клиент склеивает фрагменты одной датаграммы и не путает их с чужими.
 *
 * ОДИН НА ПРОЦЕСС, а не на поток, и это изменено ради нескольких рабочих потоков (R-146). Сборка
 * у клиента идёт по тройке «адрес источника, адрес назначения, номер» — а источник у всех потоков
 * один и тот же (адрес, который клиент считает адресом сервера), и клиент один. Два рабочих с
 * независимыми счётчиками рано или поздно выдавали ОДИН номер двум разным датаграммам для одного
 * клиента, и тот склеивал куски чужих: молча испорченная датаграмма. Счётчик общий; атомарный
 * инкремент без порядка стоит одной команды и берётся только при нарезке (датаграмма крупнее
 * MTU — редкость), так что борьбы за строку кэша нет. */
static uint16_t g_ip_id;
static uint16_t ip_id_next(void) { return __atomic_add_fetch(&g_ip_id, 1, __ATOMIC_RELAXED); }
/* Номер заголовка фрагментации IPv6 — 32 бита, свой счётчик (RFC 8200: один на пару адресов за срок сборки). */
static uint32_t g_ip6_id;
static uint32_t ip6_id_next(void) { return __atomic_add_fetch(&g_ip6_id, 1, __ATOMIC_RELAXED); }

/* Сколько датаграмм клиента отброшено за размер (больше dgram_max дайлера); читает журнал udp_packet. */
static unsigned long long g_udp_toobig;

/* Самая большая датаграмма, которую несёт текущий дайлер (dialer_ops.dgram_max). */
static size_t dgram_limit(void) {
    size_t m = g_dl->ops->dgram_max;
    return !m ? UDP_DGRAM_MAX : m < UDP_DGRAM_ABS ? m : UDP_DGRAM_ABS;
}

/* Датаграмма серверу: обрамление дайлера и данные ОДНИМ куском.
 *
 * Одним обязательно: h2_write отправляет либо всё, либо ничего, и датаграмма, разрезанная
 * на два вызова, при закрытом окне уехала бы половиной — сервер прочитал бы длину и стал
 * ждать хвост, которого нет, а следующая датаграмма приехала бы внутрь предыдущей.
 *
 * Запас в 64 байта под обрамление: у VLESS оно два байта длины, но буфер стека не должен
 * знать, чьё именно. */
static int udp_send_dgram(struct conn *c, const unsigned char *p, size_t n) {
    static __thread unsigned char fr[UDP_DGRAM_ABS + 64];
    if (n > dgram_limit()) return SEND_FATAL;
    size_t fn = g_dl->ops->dgram_frame(p, n, fr, sizeof(fr));
    if (!fn) return SEND_FATAL;
    /* Сессия ещё устанавливается: писать в неё нельзя — в ней работает установщик, — а
     * датаграмму придержать можно. Проверка стоит ЗДЕСЬ, в единственном месте, которое
     * знает про обрамление: разложенная по вызывающим, она была бы вторым правилом «кто
     * имеет право трогать сессию», и второе однажды разошлось бы с первым. */
    if (c->pending) {
        uint32_t dl = (uint32_t)fn;
        if (early_reserve(c, sizeof(dl) + fn) != 0) return SEND_AGAIN;
        if (early_hold(c, (const unsigned char *)&dl, sizeof(dl)) != 0) return SEND_AGAIN;
        return early_hold(c, fr, fn) == 0 ? SEND_OK : SEND_AGAIN;
    }
    return upstream_send(c, fr, fn);
}

/* Куда дайлер отдаёт нагрузку (dialer_ops.deliver): соединение и его устройство, плюс счёт
 * отданного — ради строки трассировки после разбора. */
struct emit_ctx {
    struct conn *c;
    const struct tun_dev *tun;
    size_t total;
};

/* Целая датаграмма от узла — клиенту. */
static int emit_dgram(void *arg, const unsigned char *p, size_t n) {
    struct emit_ctx *e = arg;
    struct conn *c = e->c;
    int wr = c->key.v6 ? udp_write_to_client6(e->tun, c->key.dst6, c->key.src6, c->key.dport, c->key.sport,
                                              p, n, ip6_id_next())
                       : udp_write_to_client(e->tun, c->key.dst, c->key.src, c->key.dport, c->key.sport,
                                             p, n, ip_id_next());
    if (wr != 0) return -1;
    TR("клиенту датаграмма %zu байт\n", n);
    /* Метка времени двигается на КАЖДОЙ датаграмме, а не только на пакетах клиента:
     * поток, по которому идёт только приём (а таких у UDP полно — те же обновления от
     * игрового сервера), иначе убрали бы по простою прямо во время работы. */
    c->last = g_now_s;
    c->udp_replied = 1;
    return 0;
}

/* Дописать клиенту в сокет то, что лежит в кольце: одной записью writev, кольцо может переходить через край —
 * тогда двумя кусками. Сокет полон — остаток ждёт EPOLLOUT (CWR снят). */
/* Дописать клиенту в сокет то, что лежит в кольце (R-152). Сокет полон — остаток ждёт EPOLLOUT; сокет
 * клиента умер — client_gone, закроет проход сроков (здесь соединение не закрывается: зовут из прохода
 * чтения, который ещё держит его). -1 — сокет умер. */
static int sock_flush(struct conn *c) {
    while (c->rtx.len) {
        uint32_t first = c->rtx.cap - c->rtx.head;
        if (first > c->rtx.len) first = c->rtx.len;
        struct iovec iov[2] = { { c->rtx.buf + c->rtx.head, first }, { c->rtx.buf, c->rtx.len - first } };
        ssize_t w = writev(conn_cfd(c), iov, iov[1].iov_len ? 2 : 1);
        if (w > 0) { rtx_drop(&c->rtx, (uint32_t)w); c->last = g_now_s; continue; }
        if (w < 0 && errno == EINTR) continue;
        if (w < 0 && (errno == EAGAIN || errno == EWOULDBLOCK)) { c->carmed &= (uint8_t)~CWR; return 0; }
        c->client_gone = 1;
        return -1;
    }
    return 0;
}

/* Отдать клиенту кусок потока (R-152: сторона клиента — всегда сокет). В кольцо недописанного, в сокет —
 * одной записью в конце прохода (sock_flush из drain_conn_reads). Не сразу каждой записью TLS: замер
 * (vision, вн1) — запись по 16 КБ отдельным send стоила 2,34 с/ГиБ против 1,67 у склейки за проход: вызов
 * и отправка TCP на каждые 16 КБ дороже копии в кольцо. Место проверено заранее (client_can_take_record);
 * кольцо заводится при первых данных и растёт по надобности. */
static int emit_to_client(struct conn *c, const unsigned char *p, size_t n) {
    if (!c->rtx.cap && rtx_init(&c->rtx, RTX_START) != 0) return -1;
    if (rtx_room(&c->rtx) < n && c->rtx.cap < RTX_CAP) rtx_grow(&c->rtx, RTX_CAP);
    if (rtx_room(&c->rtx) < n) return -1;
    rtx_push(&c->rtx, p, (uint32_t)n);
    return 0;
}

/* Кусок потока от узла — клиенту. */
static int emit_stream(void *arg, const unsigned char *p, size_t n) {
    struct emit_ctx *e = arg;
    if (emit_to_client(e->c, p, n) != 0) return -1;
    e->total += n;
    return 0;
}

/* Сколько раз дайлер отдал за проход больше запаса (см. downstream_pump). Счётчик ради стенда и журнала. */
static __thread unsigned g_overemit;

/* Прочитать у сервера и отдать клиенту как TCP-пакет (или датаграммы UDP).
 *
 * Два шага дайлера, а не один: чтение (read) и разбор (deliver). Между ними стек считает то,
 * что считал всегда, — сколько байт пришло от узла за порцию (DRAIN_MAX_BYTES) и сколько
 * времени ушло на само чтение (STEER_TUN_STATS), — и эти числа не должны зависеть от того,
 * сколько стоит разбор протокола. */
static int downstream_pump(struct conn *c, const struct tun_dev *tun, size_t *rx_n) {
    /* Статический, а не на стеке: буфер размером с запись TLS — это шестнадцать килобайт
     * стека на каждый вызов, а поток обработки здесь один. */
    static __thread unsigned char buf[DOWN_BUF];
    size_t got = 0;
    *rx_n = 0;
    void *s = SESS(c);
    TR("чтение conn#%ld fd=%d\n", (long)(c - g_conns), c->fd);
    uint64_t r0 = g_stats ? now_ns() : 0;
    const unsigned char *rx = buf;
    int rc = g_dl->ops->read(s, buf, sizeof(buf), &rx, &got);
    *rx_n = got;
    if (g_stats) g_st.recv_ns += now_ns() - r0;
    g_rx_total += got;
    if (g_stats && got) { g_st.recs++; g_st.rec_bytes += got; }
    if (rc) { TR("чтение от сервера: rc=%d\n", rc); return rc; }
    /* Ноль байт — законно: приехал служебный кадр HTTP/2, данных пока нет. Принять это за
     * конец потока значило бы разрывать соединение на первом же SETTINGS. */
    if (!got) { TR("служебный кадр, данных нет\n"); return 0; }
    TR("от сервера %zu байт\n", got);

    /* Разбор — заголовок ответа, обёртки, сборка датаграмм — у дайлера. Нагрузку он отдаёт
     * сразу, кусок за куском, а не складывает в общий буфер: складывать было незачем — всё
     * равно потом нарезали, — а стоило это копии всего трафика и предела «не влезло». */
    struct emit_ctx e = { .c = c, .tun = tun, .total = 0 };
    if (g_dl->ops->deliver(g_dl->ctx, s, c->is_udp, rx, got,
                           c->is_udp ? emit_dgram : emit_stream, &e) != 0) {
        /* Прочитанное от узла клиенту не легло (кольцо полно — нарушен договор deliver — или
         * поток не разобрался). Вернуть его некуда: поток уже обрезан, и закрыть его FIN значило
         * бы выдать обрубок за штатный конец (I-520). Клиенту — RST из общего прохода. */
        if (!c->is_udp) {
            static __thread time_t said;
            c->aborted = 1;
            if (g_now_s - said >= 10) {
                said = g_now_s;
                fprintf(stderr, LOG_W "conn#%ld: данные узла не переданы клиенту (дайлер %s) — "
                        "соединение сброшено\n", (long)(c - g_conns), g_dl->ops->name);
            }
        }
        return -1;
    }
    if (c->is_udp) return 0;

    /* Договор дайлера (dialer.h, deliver): за проход — не больше, чем стек проверил в кольце повтора
     * (CLIENT_ROOM_RESERVE). Сверх этого emit может отказать на полном кольце, и исправное соединение рвётся
     * (так умирали ss и vmess: накопитель отдавал acc_n + прочитанное). Само нарушение — не отказ, а запись в
     * журнал, чтобы следующий такой дайлер нашёлся по строке, а не по оборванным загрузкам. */
    if (e.total > CLIENT_ROOM_RESERVE) {
        static __thread time_t said;
        g_overemit++;
        if (g_now_s - said >= 10) {
            said = g_now_s;
            fprintf(stderr, LOG_W "дайлер %s отдал за проход %zu байт при запасе %d — нарушен договор "
                    "dialer.h (deliver), кольцо повтора может не вместить\n",
                    g_dl->ops->name, e.total, (int)CLIENT_ROOM_RESERVE);
        }
    }
    if (!e.total) { TR("после разбора данных нет\n"); return 0; }
    TR("клиенту %zu байт\n", e.total);
    return 0;
}

/* ---- сборка фрагментированной датаграммы клиента ---------------------------
 *
 * Клиент, которому понадобилось отправить датаграмму больше MTU, режет её сам — на выходе
 * из его стека это уже несколько IP-фрагментов. Нести их по отдельности нельзя: заголовок
 * UDP есть только в первом, а серверу нужна ЦЕЛАЯ датаграмма. Значит собирать.
 *
 * Собираем в любом порядке. Прежняя версия держала один слот и принимала куски строго
 * подряд, и обоснование («фрагменты одной датаграммы идут подряд») верно лишь пока в
 * сети один отправитель: два клиента LAN, пишущие крупное одновременно, или один клиент с
 * двумя потоками перемешивают куски, и первый фрагмент второй датаграммы сбрасывал сборку
 * первой. Не по порядку куски приходят и при нескольких очередях TUN.
 *
 * Ключ сборки — (источник, получатель, номер) для UDP: RFC 791 добавляет протокол, но
 * сюда попадает только UDP. У IPv6 — тот же ключ с 32-битным номером заголовка
 * фрагментации (RFC 8200, 4.5); правило «наложение — отбросить всё» то же (RFC 5722).
 *
 * Пределы и их причины:
 *  - DEFRAG_SLOTS = 16 одновременных сборок на поток обработки. Каждая держит до
 *    8 + UDP_DGRAM_ABS (65515) байт плюс три битовые карты по 1 КиБ, то есть 16 сборок —
 *    ~1 МиБ в худшем случае, и куча освобождается по готовности сборки. Больше одновременно незавершённых
 *    датаграмм у LAN роутера не бывает: сборка живёт доли секунды, а потерянный хвост
 *    держится до срока. Когда все слоты заняты, вытесняется САМАЯ СТАРАЯ — новая
 *    датаграмма живее брошенной, — и это считается и попадает в журнал.
 *  - DEFRAG_TTL_NS = 30 с: RFC 791 советует держать сборку по сроку жизни пакета (не менее
 *    15 с), Linux держит 30 с (net.ipv4.ipfrag_time), RFC 8200 — 60 с для IPv6. Берём
 *    значение Linux: клиент за этим роутером — обычно Linux-стек, и его повторная
 *    отправка укладывается в тот же срок.
 *  - Датаграмма не больше 8 + UDP_DGRAM_ABS = 65515: больше по IPv4 не бывает. Что из собранного
 *    возьмёт дайлер, решает он сам (dgram_max), а сборка от этого не зависит.
 *
 * Наложение и повтор. Точный повтор уже принятого фрагмента (те же смещение и длина)
 * молча пропускается: сеть иногда дублирует пакеты, и датаграмма от этого не портится.
 * Любое другое наложение — признак порчи или атаки (классический приём обхода фильтров и
 * основа ряда CVE в стеках IP), и вся датаграмма отбрасывается, как велит RFC 5722 для
 * IPv6 и как делает Linux для IPv4 в режиме без перекрытий. Для UDP потеря датаграммы —
 * штатный исход.
 *
 * Несколько рабочих потоков: таблица сборки своя у каждого. Читатель TUN раздаёт фрагменты по
 * хэшу адресов и протокола БЕЗ портов (stack_owner) — у первого куска порты есть, у остальных
 * нет, и хэш по портам развёл бы куски одной датаграммы. Поэтому все куски приходят одному
 * рабочему, он собирает, а готовую датаграмму отдаёт владельцу её пятёрки (xmail, см. g_rw).
 * Проверяется стендом tests/tunnelmatch.c (t_owner, t_owner_mail). */
#define DEFRAG_SLOTS  16
#define DEFRAG_TTL_NS 30000000000ull
#define DEFRAG_MAXLEN (8 + UDP_DGRAM_ABS)           /* UDP-датаграмма целиком, с заголовком */
#define DEFRAG_BLOCKS ((DEFRAG_MAXLEN + 7) / 8)

struct frag_slot {
    /* Ключ сборки: семейство, адреса (IPv4 — первые четыре байта, остальные нули) и номер (IPv4 — 16 бит,
     * заголовок фрагментации IPv6 — 32). */
    uint8_t v6;
    uint8_t src[16], dst[16];
    uint32_t id;
    uint64_t at;                                     /* когда пришёл первый кусок */
    uint32_t total;                                  /* длина целиком; 0 — последний ещё не пришёл */
    uint32_t got;                                    /* сколько байт уже лежит */
    /* Карты по восьмибайтовым блокам: занят блок, с него начинается кусок, на нём кончается.
     * Две последние нужны, чтобы отличить точный повтор от накрывшего два прежних. */
    uint8_t have[DEFRAG_BLOCKS], start[DEFRAG_BLOCKS], end[DEFRAG_BLOCKS];
    unsigned char buf[DEFRAG_MAXLEN];
};

/* Счётчики за жизнь потока: что собрано и сколько потеряно, по причинам. Печатаются в
 * журнал не чаще раза в 10 с, и только когда есть потери. */
struct defrag_stat {
    unsigned long done, overlap, bad, expired, evicted;
};
static __thread struct frag_slot *g_frag[DEFRAG_SLOTS];
static __thread struct defrag_stat g_dfs;

static void defrag_say(const char *why) {
    static __thread uint64_t said;
    if (g_now_ns - said < 10000000000ull && said) return;
    said = g_now_ns ? g_now_ns : 1;
    fprintf(stderr, LOG_W "фрагменты UDP: датаграмма потеряна (%s); всего потеряно: наложение %lu, "
            "брак %lu, срок %lu, вытеснено %lu, собрано %lu\n", why, g_dfs.overlap, g_dfs.bad,
            g_dfs.expired, g_dfs.evicted, g_dfs.done);
}

static void frag_free(int i) { free(g_frag[i]); g_frag[i] = NULL; }

/* Собрать датаграмму из фрагментов. Возвращает длину готового пакета в out (то есть
 * собранная датаграмма выглядит как обычный нефрагментированный пакет и разбирается тем же
 * ip_parse), 0 — ждём следующий фрагмент, и 0 же при отказе: для UDP это одно и то же —
 * датаграммы не будет. IPv6 — заголовок фрагментации сразу за фиксированным (ip_parse другого не
 * принимает): расширения до него в собранный пакет не переходят, они относятся к «нефрагментируемой»
 * части и стеку не нужны. */
static size_t udp_defrag(const unsigned char *pkt, size_t n, unsigned char *out,
                         size_t out_cap) {
    int v6 = (pkt[0] >> 4) == 6;
    size_t ihl, len, off;
    int more;
    uint32_t id;
    uint8_t src[16] = { 0 }, dst[16] = { 0 };
    if (v6) {
        if (n < 48 || pkt[6] != 44 || pkt[40] != 17) return 0;
        size_t plen = ((size_t)pkt[4] << 8) | pkt[5];
        if (plen + 40 > n || plen < 8) return 0;
        ihl = 48;
        len = plen - 8;
        unsigned fo = (unsigned)((pkt[42] << 8) | pkt[43]);
        off = fo & 0xFFF8;
        more = fo & 1;
        id = ((uint32_t)pkt[44] << 24) | ((uint32_t)pkt[45] << 16) | ((uint32_t)pkt[46] << 8) | pkt[47];
        memcpy(src, pkt + 8, 16);
        memcpy(dst, pkt + 24, 16);
    } else {
        ihl = (size_t)(pkt[0] & 0x0F) * 4;
        if (ihl < 20 || n < ihl) return 0;
        size_t total = (size_t)((pkt[2] << 8) | pkt[3]);
        if (total > n || total < ihl) return 0;           /* заявленная длина больше пришедшей */
        len = total - ihl;
        unsigned frag = (unsigned)((pkt[6] << 8) | pkt[7]);
        off = (size_t)(frag & 0x1FFF) * 8;
        more = (frag & 0x2000) != 0;
        id = (uint16_t)((pkt[4] << 8) | pkt[5]);
        memcpy(src, pkt + 12, 4);
        memcpy(dst, pkt + 16, 4);
    }

    /* Просроченные сборки — прочь. Каждый приём: слотов шестнадцать, обход дешёвый. */
    for (int i = 0; i < DEFRAG_SLOTS; i++)
        if (g_frag[i] && g_now_ns - g_frag[i]->at > DEFRAG_TTL_NS) {
            frag_free(i);
            g_dfs.expired++;
            defrag_say("срок сборки 30 с вышел");
        }

    int si = -1;
    for (int i = 0; i < DEFRAG_SLOTS; i++)
        if (g_frag[i] && g_frag[i]->v6 == v6 && g_frag[i]->id == id &&
            !memcmp(g_frag[i]->src, src, 16) && !memcmp(g_frag[i]->dst, dst, 16)) {
            si = i;
            break;
        }

    /* Куски, которые собрать нельзя при любом раскладе: пустой, не кратный восьми (кроме
     * последнего) и выходящий за предел. Сборку своего ключа они ломают: с такими данными
     * датаграмма не склеится, и держать остальные куски до срока незачем. */
    if (!len || (more && (len & 7)) || off + len > DEFRAG_MAXLEN ||
        (!more && off + len < 8)) {
        if (si >= 0) frag_free(si);
        g_dfs.bad++;
        defrag_say("фрагмент неправильной длины или за пределом");
        return 0;
    }

    if (si < 0) {
        for (int i = 0; i < DEFRAG_SLOTS; i++)
            if (!g_frag[i]) { si = i; break; }
        if (si < 0) {                                /* все заняты: вытесняем самую старую */
            si = 0;
            for (int i = 1; i < DEFRAG_SLOTS; i++)
                if (g_frag[i]->at < g_frag[si]->at) si = i;
            frag_free(si);
            g_dfs.evicted++;
            defrag_say("все 16 слотов сборки заняты, вытеснена самая старая");
        }
        g_frag[si] = calloc(1, sizeof(struct frag_slot));
        if (!g_frag[si]) return 0;                   /* памяти нет — датаграммы нет */
        g_frag[si]->v6 = (uint8_t)v6;
        memcpy(g_frag[si]->src, src, 16);
        memcpy(g_frag[si]->dst, dst, 16);
        g_frag[si]->id = id;
        g_frag[si]->at = g_now_ns;
    }
    struct frag_slot *s = g_frag[si];

    size_t b0 = off / 8, b1 = (off + len - 1) / 8;   /* блоки [b0, b1] */
    /* Конец последнего куска задаёт длину всей датаграммы; два последних разной длины —
     * наложение. Уже известная длина меньше конца этого куска — тоже брак. */
    if (!more) {
        if (s->total && s->total != off + len) goto overlap;
        s->total = (uint32_t)(off + len);
    }
    if (s->total && off + len > s->total) goto overlap;

    unsigned have = 0, starts = 0, ends = 0;
    for (size_t b = b0; b <= b1; b++) {
        have += s->have[b];
        if (b > b0) starts += s->start[b];
        if (b < b1) ends += s->end[b];
    }
    if (have) {
        /* Точный повтор: ровно такой же кусок уже принят — занят весь диапазон, на краях
         * стоят начало и конец, а внутри ни одного чужого. */
        if (have == b1 - b0 + 1 && s->start[b0] && s->end[b1] && !starts && !ends)
            return 0;
        goto overlap;
    }
    memcpy(s->buf + off, pkt + ihl, len);
    for (size_t b = b0; b <= b1; b++) s->have[b] = 1;
    s->start[b0] = 1;
    s->end[b1] = 1;
    s->got += (uint32_t)len;
    if (!s->total || s->got < s->total) return 0;    /* ждём остальное */

    /* Собрали. Отдаём как обычный пакет: заголовок IP на 20 байт, длина по факту, флагов
     * фрагментации нет — дальше его разбирает тот же путь, что и всё остальное. */
    size_t iph = v6 ? 40 : 20;
    size_t asm_total = iph + s->total;
    /* Длина в заголовке UDP обязана совпасть с собранной: сервер читает именно её, и
     * фрагмент, потерянный ядром клиента, дал бы здесь короткую датаграмму с чужой длиной. */
    size_t udp_len = (size_t)((s->buf[4] << 8) | s->buf[5]);
    if (udp_len != s->total || asm_total > out_cap) {
        frag_free(si);
        g_dfs.bad++;
        defrag_say("длина в заголовке UDP не равна собранной");
        return 0;
    }
    memset(out, 0, iph);
    if (v6) {
        out[0] = 0x60;
        out[4] = (unsigned char)(s->total >> 8);
        out[5] = (unsigned char)s->total;
        out[6] = 17;
        out[7] = 64;
        memcpy(out + 8, src, 16);
        memcpy(out + 24, dst, 16);
    } else {
        out[0] = 0x45;
        out[2] = (unsigned char)(asm_total >> 8);
        out[3] = (unsigned char)asm_total;
        out[4] = (unsigned char)(id >> 8);
        out[5] = (unsigned char)id;
        out[8] = 64;
        out[9] = 17;
        memcpy(out + 12, src, 4);
        memcpy(out + 16, dst, 4);
    }
    memcpy(out + iph, s->buf, s->total);
    frag_free(si);
    g_dfs.done++;
    return asm_total;

overlap:
    frag_free(si);
    g_dfs.overlap++;
    defrag_say("фрагменты накладываются");
    return 0;
}

/* Датаграмма из TUN: своя сессия на каждый поток «адрес-порт → адрес-порт».
 *
 * Почему сессия на поток, а не одна на всё. Адрес назначения в VLESS едет в заголовке
 * запроса, то есть задаётся ОДИН РАЗ и на весь поток. Нести в одном потоке нескольких
 * адресатов умеет XUDP (это Mux.Cool поверх VLESS, со своим кадрированием и своими
 * идентификаторами), и выигрывает он там, где адресатов много и каждому по одной
 * датаграмме — то есть на DNS. Для того, ради чего UDP здесь и нужен — QUIC, WireGuard,
 * игры, — адресат один, поток живёт минутами, и XUDP не даёт ничего, кроме своего формата,
 * в котором можно ошибиться.
 *
 * Рукопожатие на поток теперь недорого: первая датаграмма ждёт его в буфере ранних данных,
 * а пул запасных сессий отдаёт готовый поток сразу — то же, что и у SYN. Ровно поэтому
 * поддержка UDP появилась именно после той работы, а не до: без неё каждая новая
 * QUIC-сессия стоила бы 100-400 мс на пустом месте.
 *
 * Правило «сессия на поток» — стека, а не только VLESS: дайлер получает поток целиком и один,
 * поэтому протокол с мультиплексированием понадобился бы стеку как другая модель, а не как
 * ещё одна таблица (см. «чего здесь нет» в dialer.h). */
static void udp_packet(const struct tun_dev *tun, struct conn *c, const struct flow_key *k,
                       const unsigned char *pkt, size_t n, size_t off) {
    size_t dn = n - off;
    /* Сюда попадают только целые датаграммы: фрагменты собирает udp_defrag ещё до разбора
     * заголовка, и неполной датаграммы здесь быть не может. Проверка всё равно стоит —
     * отправить серверу обрубок под видом целой датаграммы хуже, чем потерять её. */
    if (k->frag || !dn) return;
    if (dn > dgram_limit()) {
        /* Крупнее, чем несёт дайлер, — потеря, и молчать о ней нельзя: снаружи это «QUIC/DNS через туннель
         * иногда не работает». Счётчик общий (потоков цикла несколько), сообщение — раз в десять секунд. */
        unsigned long long tot = __atomic_add_fetch(&g_udp_toobig, 1, __ATOMIC_RELAXED);
        static __thread time_t said_big;
        if (g_now_s - said_big >= 10) {
            said_big = g_now_s;
            fprintf(stderr, LOG_W "датаграмма UDP %zu байт больше предела протокола %s (%zu) — отброшена; "
                            "всего отброшено %llu\n", dn, g_dl->ops->name, dgram_limit(), tot);
        }
        return;
    }

    if (!c) {
        if (flow_rejected(k, 1)) {
            unsigned char un[128];
            size_t ul = icmp_unreach_build(un, sizeof(un), pkt, n);
            if (ul) tun_write_ctl(tun, un, ul);
            TR("поток UDP отвергнут политикой хоста\n");
            return;
        }
        c = conn_new(tun);
        if (!c) return;                             /* все потоки свежие — клиент повторит */
        memset(c, 0, sizeof(*c));
        c->used = 1;
        c->born_turn = g_turn;
        c->is_udp = 1;
        c->key = *k;
        c->fd = -1;
        c->aux = -1;
        conn_link(c);                               /* после ключа: хэш считается по нему */
        c->last = g_now_s;
        /* Отказ дайлер называет сам (у VLESS — негодный UUID узла, I-097). */
        if (g_dl->ops->flow_open(g_dl->ctx, SESS(c), k, 1) != 0) {
            conn_drop(c);
            return;
        }

        int qr;
        /* DC_UDP_OWN: у потока UDP своя связь — сокет UDP, а запасная сессия несёт поток TCP
         * (dialer.h). */
        if (g_spare_want > 0 && !(g_dl->ops->caps & DC_UDP_OWN) && spare_checkout(SESS(c)) == 0) {
            c->fd = g_dl->ops->fd(SESS(c));
            conn_live(c);
            node_sock_silence(c->fd);
            TR("UDP: взята запасная сессия\n");
        } else if ((qr = conn_submit(c)) == 0) {
            c->pending = 1;
            TR("UDP: заявка установщику\n");
        } else {
            /* Заявка не встала в очередь (нет памяти). Сказать об этом надо: снаружи это выглядит как
             * «QUIC не работает через туннель». Отказ -2 (нет установщиков) connq_push назвал сам. */
            static __thread time_t said_q;
            if (qr == -1 && g_now_s - said_q >= 5) {
                said_q = g_now_s;
                fprintf(stderr, LOG_W "нет памяти под очередь установки соединений, "
                                "датаграмма отброшена\n");
            }
            conn_drop(c);
            return;
        }
        spare_refill();
    }

    c->last = g_now_s;

    /* Хвост ранних датаграмм, не уместившийся в окно h2 при готовности потока, обязан уйти
     * ПЕРВЫМ. Свежая датаграмма вперёд него — это не «переставленные датаграммы», с чем
     * QUIC живёт, а разрезанный пополам кадр: в потоке к узлу датаграммы идут одним
     * байтовым потоком, и вставка между двумя половинами ломает разбор у сервера
     * НАВСЕГДА. На голом tcp такого не бывает (там отправка либо целиком, либо ошибка), а
     * на grpc и xhttp окно закрывается штатно. */
    if (!c->pending && c->early) {
        int fr = early_flush(c);
        if (fr < 0) { conn_drop(c); return; }
        if (fr > 0) {
            if (g_stats) g_st.udp_drops++;
            TR("хвост ранних датаграмм не ушёл — свежую теряем\n");
            return;
        }
    }

    int sr = udp_send_dgram(c, pkt + off, dn);
    if (sr == SEND_OK) {
        TR("датаграмма клиента %zu байт -> серверу\n", dn);
        return;
    }
    if (sr == SEND_AGAIN) {
        /* Окно h2 закрыто или буфер ранних данных полон. У TCP на этом месте пакет просто
         * не подтверждается и клиент повторяет его сам; у UDP подтверждений нет, и
         * придержать датаграмму негде — значит теряем её. Это не поблажка: потеря
         * датаграммы — штатное событие для любого протокола поверх UDP, и все они умеют
         * её пережить, а вот отправка НЕ ПО ПОРЯДКУ сломала бы, например, QUIC. */
        if (g_stats) g_st.udp_drops++;
        TR("датаграмма отброшена: отправить сейчас нельзя\n");
        return;
    }
    TR("поток UDP сломан, закрываю\n");
    conn_drop(c);
}

/* Один пакет из TUN. */
static void drain_conn(struct conn *c, const struct tun_dev *tun);

static void handle_packet_one(const struct tun_dev *tun, const unsigned char *pkt, size_t n) {
    struct flow_key k;

    size_t off = 0;

    /* Пакет обязан принадлежать этому рабочему по тому же хэшу, которым его раздал читатель (R-146).
     * Не принадлежит — ошибка раздачи: половина соединения не у владельца, и подтверждения до него не
     * дойдут (то самое зависание, ради которого потоки были выключены). Пакет всё равно
     * разбирается, как прежде, а ошибка считается и называется в журнале. */
    if (g_rw && stack_owner(pkt, n, g_nwork) != (unsigned)g_worker) {
        g_not_owner++;
        static __thread time_t said_no;
        if (g_now_s - said_no >= 5) {
            said_no = g_now_s;
            fprintf(stderr, LOG_W "пакет пришёл рабочему %d, которому он не принадлежит "
                            "(всего %llu) — ошибка раздачи по потокам\n", g_worker, g_not_owner);
        }
    }

    /* Фрагменты UDP собираем ДО разбора: у продолжения нет заголовка UDP, и разбирать в нём
     * нечего — ip_parse такой пакет и не примет. Собранное выглядит обычным пакетом и идёт
     * дальше общим путём, поэтому знать про фрагменты больше никому не нужно. */
    if ((n >= 20 && (pkt[0] >> 4) == 4 && pkt[9] == 17 && (((pkt[6] << 8) | pkt[7]) & 0x3FFF)) ||
        (ip6_frag_off(pkt, n) && pkt[40] == 17)) {
        static __thread unsigned char asm_pkt[40 + 8 + UDP_DGRAM_ABS];
        size_t an = udp_defrag(pkt, n, asm_pkt, sizeof(asm_pkt));
        if (!an) { TR("фрагмент UDP: %s\n", "ждём продолжения или отказ"); return; }
        TR("датаграмма собрана из фрагментов: %zu байт\n", an);
        pkt = asm_pkt;
        n = an;
        /* Собрана у того, кому достались куски, а владелец сессии — по хэшу пятёрки, и это может быть
         * другой рабочий (см. «что хэш не ловит» у g_rw). Отдаём ему целиком; сюда же она вернётся
         * уже без признаков фрагмента, и тот же хэш назовёт его самого. */
        if (g_rw) {
            unsigned o = stack_owner(pkt, n, g_nwork);
            if (o != (unsigned)g_worker) { xmail_put(o, pkt, n); return; }
        }
    }

    if (ip_parse(pkt, n, &k, &off) != 0) { TR("пакет не разобран (%zu байт)\n", n); return; }
    if (g_trace) {
        char sa[INET6_ADDRSTRLEN], da[INET6_ADDRSTRLEN];
        inet_ntop(k.v6 ? AF_INET6 : AF_INET, flow_src_bytes(&k), sa, sizeof(sa));
        inet_ntop(k.v6 ? AF_INET6 : AF_INET, flow_dst_bytes(&k), da, sizeof(da));
        TR("%s:%u -> %s:%u proto=%u flags=0x%02x len=%zu\n", sa, k.sport, da, k.dport,
           k.proto, k.tcp_flags, n - off);
    }

    /* Всё, что не TCP и не UDP, туннель нести не умеет: это ICMP, ESP и прочее, для чего
     * у VLESS (и у любого дайлера потоков) команды нет вовсе.
     *
     * И НЕ МОЛЧИМ. Прежде такой пакет просто выбрасывался, и это стоило целых сайтов —
     * тогда в этой ветке был ещё и UDP: браузер идёт к Cloudflare по QUIC, то есть UDP на
     * 443, и тишину понимает как «ещё не ответили», а не «нельзя». Он ждёт и повторяет, и
     * на сайтах, настойчиво предпочитающих QUIC, страница не открывалась вовсе. ICMP-отказ
     * превращал ожидание в мгновенный переход на TCP.
     *
     * Теперь UDP несётся честно (ветка ниже), и отказ остался только тому, чему помочь
     * по-прежнему нечем. Для ICMP это правильный ответ и по существу: эмуляция ping через
     * прокси вводит в заблуждение — успешный ping не означает рабочий путь. */
    if (k.proto != 6 && k.proto != 17) {
        unsigned char un[128];
        size_t ul = icmp_unreach_build(un, sizeof(un), pkt, n);
        if (ul) tun_write_ctl(tun, un, ul);
        TR("ни TCP, ни UDP (proto=%u), отказ\n", k.proto);
        return;
    }

    struct conn *c = conn_find(&k);

    if (k.proto == 17) { udp_packet(tun, c, &k, pkt, n, off); return; }

    /* TCP через TUN не несём (R-152): соединения клиентов перенаправляет к слушателю модуля правило nat
     * steer, и в устройство TCP попадает, только когда перенаправления нет — карта не успела получить
     * элемент выхода (миг между up модуля и привязкой) или раскладка старого ядра, где его не ставят
     * (Linux 4.9, решение владельца 2026-10-12 — пропускаем). Ответ — сброс, а не тишина: приложение
     * сразу узнаёт, что соединения нет, и повторит, а не ждёт своего срока. */
    (void)c;
    if (!(k.tcp_flags & TCP_RST)) {
        size_t data_n = n - off;
        uint32_t ack = k.seq + (uint32_t)data_n + ((k.tcp_flags & TCP_SYN) ? 1u : 0u) +
                       ((k.tcp_flags & TCP_FIN) ? 1u : 0u);
        unsigned char rp[64];
        size_t rl = k.v6 ? tcp_build6(rp, sizeof(rp), k.dst6, k.src6, k.dport, k.sport,
                                      (k.tcp_flags & TCP_ACK) ? k.ack : 0, ack, TCP_RST | TCP_ACK, NULL, 0, 0, 0, -1)
                         : tcp_build(rp, sizeof(rp), k.dst, k.src, k.dport, k.sport,
                                     (k.tcp_flags & TCP_ACK) ? k.ack : 0, ack, TCP_RST | TCP_ACK, NULL, 0, 0, 0, -1);
        if (rl) tun_write_ctl(tun, rp, rl);
        g_tcp_tun_rst++;
        static __thread time_t said;
        if (g_now_s - said >= 10) {
            said = g_now_s;
            fprintf(stderr, LOG_W "TCP пришёл в устройство (перенаправления к слушателю нет) — сброс "
                            "(всего %llu)\n", g_tcp_tun_rst);
        }
    }
}

static void handle_packet(const struct tun_dev *tun, const unsigned char *pkt, size_t n) {
    handle_packet_one(tun, pkt, n);
}

/* Поднять устройство и дать ему адрес.
 *
 * Делает это движок, а не управляющий слой, потому что устройство создаёт тоже движок:
 * между «TUN появился» и «TUN готов нести трафик» нет никого, кому это можно было бы
 * поручить. Без этого apply не находит рабочего устройства, ставит blackhole (при
 * on_fail=drop) и трафик стоит — притом что процесс запущен, узел выбран и в логе всё
 * выглядит успешным. Ровно тот случай, когда «настроено» и «работает» расходятся молча.
 *
 * Адрес нужен не нам: наш клиент читает из TUN пакеты и открывает по ним потоки, source
 * в них не участвует вовсе. Нужен он ядру и фаерволу — маршрут на устройство без адреса
 * ядро считает непригодным для локально порождённых пакетов.
 *
 * 198.51.100.0/24 — это TEST-NET-2 из RFC 5737: диапазон, отведённый под документацию и
 * НЕ маршрутизируемый в интернете. Поэтому он не может столкнуться ни с чужим сервисом,
 * ни с локальной сетью, которую кто-то себе выбрал. Пул fake-IP (198.18.0.0/15) здесь
 * брать нельзя — он занят под другую задачу, и пересечение перепутало бы одно с другим.
 *
 * Номер адреса берётся из таблицы маршрутизации выхода: она уже уникальна и уже лежит в
 * реестре, то есть переживает перезагрузку. Выдумывать для этого второй счётчик значило
 * бы завести второе место, где номера могут разъехаться. */
void tun_bring_up(const char *dev, int table) {
    char addr[40];
    /* Без знака: таблица приходит из файла реестра, и отрицательное число оттуда давало
     * адрес 198.51.100.-N, который ip не примет (I-322). */
    snprintf(addr, sizeof(addr), "198.51.100.%u/32", 1u + ((unsigned)table % 200u));
    const char *a[] = { "ip", "addr", "replace", addr, "dev", dev, NULL };
    /* Отказы называются по одному, и тон у них разный, потому что разная и цена.
     *
     * Дотуда, где это заметно, движок доходит успешным: очереди открыты, узел выбран, в
     * журнале стоит штатное «<dev> -> <узел>». Поэтому немой отказ здесь — это не
     * недостающая строка, а расхождение «настроено» и «работает» без единого следа, тот же
     * класс, за который этот путь правили дважды (имя устройства и привязка таблицы). */
    if (run_quiet(a) != 0)
        fprintf(stderr, LOG_W "%s: адрес %s не встал — ядро сочтёт маршрут на это "
                        "устройство непригодным для локально порождённых пакетов\n",
                dev, addr);
    /* Адрес IPv6 (ULA, один на таблицу): без него у локально порождённых пакетов IPv6 через устройство нет
     * адреса источника (пробы выхода, подложка `over`), как без адреса IPv4 выше. Тон осведомляющий: IPv6 на
     * машине может быть выключен вовсе, а клиенты LAN ходят через устройство со своими адресами. */
    char addr6[48];
    snprintf(addr6, sizeof(addr6), "fd73:7465:6572::%x/128", 1u + ((unsigned)table % 200u));
    const char *a6[] = { "ip", "-6", "addr", "replace", addr6, "dev", dev, NULL };
    if (run_quiet(a6) != 0)
        fprintf(stderr, LOG_I "%s: адрес IPv6 %s не встал — IPv6 локальных пакетов через это устройство "
                        "не пойдёт (IPv6 выключен?)\n", dev, addr6);
    const char *u[] = { "ip", "link", "set", "dev", dev, "up", NULL };
    if (run_quiet(u) != 0)
        fprintf(stderr, LOG_W "%s: устройство не поднялось — через него не пойдёт "
                        "ничего\n", dev);
    /* Очередь устройства — 500 пакетов по умолчанию, и она про направление ЯДРО → МЫ, а не
     * про наши записи. Прежнее объяснение здесь («полная очередь означает EAGAIN и ожидание
     * на каждой записи») замера не выдержало: 200 000 неблокирующих записей в TUN на ядре
     * 6.8 дали НОЛЬ EAGAIN и ноль rx_dropped — запись в устройство в txqueuelen не упирается
     * вовсе. А вот пакеты, которые ядро отдаёт нам, лежат в этой очереди ровно txqueuelen
     * штук: из 20 000 отправленных при 500 до нас доехали 500 (остальные 19 501 сосчитаны
     * как tx_dropped устройства), при 4096 — 4096.
     *
     * То есть выигрыш настоящий, но он про другое: сколько пакетов уцелеет, пока цикл занят
     * предыдущим витком (криптографией, записью в сокеты, разбором). Вчетверо с лишним
     * больший запас — вчетверо реже потери на пиках. Памяти это не стоит заранее: очередь
     * занимает столько, сколько в ней реально лежит.
     *
     * Почему это важно назвать точно, а не «работает и так»: по этому объяснению уже
     * сверялись. В реализации на Go тот же механизм пересказан в комментарии к Write
     * («EAGAIN на записи означает переполненную очередь устройства»), а txqueuelen там не
     * поднимается ни клиентом, ни хабом — I-115. */
    const char *q[] = { "ip", "link", "set", "dev", dev, "txqueuelen", "4096", NULL };
    /* Тон здесь ОСВЕДОМЛЯЮЩИЙ, а не тревожный: трафик пойдёт и с ядерной очередью, потеряна
     * будет скорость. Предупреждать об этом значило бы на системах, где txqueuelen не
     * принимают вовсе, встречать каждый штатный запуск красной строкой — и научить не
     * смотреть в журнал вообще. */
    if (run_quiet(q) != 0)
        fprintf(stderr, LOG_I "%s: очередь передачи осталась ядерной — просили 4096 "
                        "пакетов, не приняли; ждать чтения их сможет 500, остальные ядро "
                        "на пиках отбросит\n", dev);
}

/* ВЫЧЕРПАТЬ сокет соединения, а не прочитать по одной записи за виток цикла.
 *
 * Разница принципиальная. Пока мы не читаем, у сервера закрывается окно, и заново открыть
 * его стоит круга до сервера — десятки миллисекунд. Читая по одной записи на итерацию, мы
 * получаем скорость «запись за круг», то есть задержку вместо полосы: замерено 3 Мбит/с там,
 * где криптография держит 800.
 *
 * Пределов три: место в кольце недописанного клиенту (client_can_take_record), объём и число чтений за виток —
 * чтобы одно активное соединение не заморозило остальные.
 *
 * Отдельной функцией, потому что вызывается из двух мест: по событию epoll и по флагу
 * rx_ready. Копия этой логики в двух местах означала бы, что предел порции соблюдается в
 * одном из них и не соблюдается в другом. */

/* Вторая связь дайлера (dialer_ops.aux_fd; у xhttp — ответы на выгрузку): её событие — повод пересчитать
 * место сразу, а не когда проснётся клиент, которому отказано в окне и который молчит до своего таймера.
 * aux_sync зовётся на каждом проходе по соединениям — сессия могла переехать из запасной, и дескриптор
 * стал другим, — а epoll_ctl только на изменение. */
static void aux_sync(int ep, struct conn *c) {
    if (!g_dl->ops->aux_fd || c->aux == -2) return;
    int af = g_dl->ops->aux_fd(SESS(c));
    if (af != c->aux) {
        if (c->aux >= 0) epoll_ctl(ep, EPOLL_CTL_DEL, c->aux, NULL);
        c->aux = -1;
        c->aux_out = 0;
        if (af < 0) return;
        struct epoll_event e = { .events = EPOLLIN, .data = { .u32 = AUX_BIT | (uint32_t)(c - g_conns) } };
        if (epoll_ctl(ep, EPOLL_CTL_ADD, af, &e) == 0) c->aux = af;
    }
    /* Живая запись второй связи (I-534): что сокет не принял, лежит в её очереди, и сервер, ждущий остаток, ничего
     * не пришлёт, пока он не уйдёт, — без EPOLLOUT остаток ждал бы ответа, которого не будет. Событие записи (по
     * уровню) будит aux_event, и aux_drain досылает очередь; опустела — EPOLLOUT снимается. */
    if (c->aux >= 0 && g_dl->ops->aux_pending) {
        int want = g_dl->ops->aux_pending(SESS(c)) > 0;
        if (want != c->aux_out) {
            struct epoll_event e = { .events = EPOLLIN | (want ? (uint32_t)EPOLLOUT : 0u),
                                     .data = { .u32 = AUX_BIT | (uint32_t)(c - g_conns) } };
            if (epoll_ctl(ep, EPOLL_CTL_MOD, c->aux, &e) == 0) c->aux_out = (uint8_t)want;
        }
    }
}

/* Событие второй связи: слить пришедшее (место у дайлера могло вырасти — недочитанное у клиента дочитает
 * проход сроков, sock_want_read). Связь, которую
 * дайлер больше слушать не просит, снимается с epoll навсегда: закрытая, она читалась бы на каждом витке. */
static void aux_event(int ep, struct conn *c) {
    if (!c->used || c->pending || c->born_turn == g_turn || c->aux < 0) return;
    if (g_dl->ops->aux_drain(SESS(c)) != 0) {
        epoll_ctl(ep, EPOLL_CTL_DEL, c->aux, NULL);
        c->aux = -2;
    }
}

static void drain_conn_reads(struct conn *c, const struct tun_dev *tun);

static void drain_conn(struct conn *c, const struct tun_dev *tun) {
    drain_conn_reads(c, tun);
    if (c->cfd1 && c->rtx.len) sock_flush(c);
}

static void drain_conn_reads(struct conn *c, const struct tun_dev *tun) {
    const struct dialer_ops *d = g_dl->ops;
    void *s = SESS(c);
    int reads = 0;
    uint64_t drained_from = g_rx_total;
    c->rx_ready = 0;
    for (;;) {
        size_t rx_n = 0;
        if (downstream_pump(c, tun, &rx_n) != 0) {
            /* Сервер закрыл. Соединение НЕ закрываем, пока клиент не подтвердит всё
             * отправленное: пока в кольце есть неподтверждённое, его надо повторять, а
             * закрыв соединение, мы уничтожим и кольцо. FIN уйдёт из общего прохода. */
            c->srv_closed = 1;
            c->closed_at = g_now_ns;
            /* Оборвана, а не закрыта — клиенту RST из общего прохода (поле aborted). */
            if (conn_node_lost(c) && !c->is_udp) c->aborted = 1;
            TR("сервер закрыл conn#%ld, ждём подтверждения %u байт\n",
               (long)(c - g_conns), c->rtx.len);
            return;
        }
        if (++reads >= DRAIN_MAX_READS || g_rx_total - drained_from >= DRAIN_MAX_BYTES) {
            if (g_stats) g_st.drain_full++;
            /* Прервались на своём пределе, а данные, может быть, ещё в буфере: отметим, что
             * ждать события на сокете для них не нужно. */
            c->rx_ready = 1;
            return;
        }
        if (!c->is_udp && !client_can_take_record(c)) {
            c->rx_ready = 1;
            return;
        }
        /* Целая запись уже прочитана у сокета — спрашивать ядро незачем. */
        if (d->has_data(s)) continue;
        /* Есть ли ещё что читать — спрашиваем само чтение, а не poll перед ним: read дайлера не ждёт (нет
         * данных — rx_n == 0 и код 0, см. dialer_ops.read), так что poll перед КАЖДЫМ чтением стоил системного
         * вызова на чтение (замер: ~2 % цикла, 36-116 вызовов на МБ). Пустое чтение даёт один poll на конец
         * порции, а не на каждое чтение: пустым оно бывает по двум причинам, и различить их снаружи нельзя —
         * сокет пуст (EAGAIN) либо у связи съеден служебный кадр (запись TLS без данных: билет сессии;
         * WINDOW_UPDATE, PING, SETTINGS у HTTP/2), а за ним в сокете ещё лежит. Под фронтом (EPOLLET) новое
         * событие на это не придёт, и соединение встало бы до следующих данных (так вставало на gRPC: две
         * загрузки из пяти). Поэтому пустое чтение проверяется poll'ом: готов сокет — читаем дальше. */
        if (!rx_n) {
            if (g_inloop) return;       /* дескриптора нет, а всё пришедшее лежит в сессии (has_data выше) */
            struct pollfd sp = { .fd = c->fd, .events = POLLIN, .revents = 0 };
            if (poll(&sp, 1, 0) <= 0 || !(sp.revents & (POLLIN | POLLHUP | POLLERR))) return;
        }
    }
}

/* Установщик доложил по соединению c (done): связь готова или нет. Зовёт проход цикла по заявкам
 * (worker_loop); отдельной функцией — ради стенда (tests/poolmatch.c). 1 — соединение закрыто (его
 * место в g_live занял другой), 0 — поток готов. */
static int conn_ready(struct conn *c, const struct tun_dev *tun) {
    const struct dialer_ops *d = g_dl->ops;
    c->pending = 0;
    c->fd = d->fd(SESS(c));
    if (c->rc == 0) node_sock_silence(c->fd);
    if (c->client_gone) {
        /* Клиент передумал, пока шло рукопожатие. Отвечать некому — просто
         * закрываем и поток к узлу, и запись. */
        conn_drop(c);
        return 1;
    }
    if (c->rc != 0) {
        /* С причиной, а не «не открылся»: код различает «TCP не соединился»,
         * «сервер не признал ключ» и «сервер не согласился на HTTP/2». */
        fprintf(stderr, LOG_W "поток к %s не открылся: %s (rc=%d)\n",
                d->peer_of ? d->peer_of(g_dl->ctx, SESS(c)) : d->peer(g_dl->ctx),
                d->strerror(c->rc), c->rc);
        /* RST, а не молчание: клиент иначе ждёт до таймаута. Молчать я пробовал —
         * страница с видео перестала открываться вовсе, потому что браузер
         * использует быстрый отказ лучше, чем ожидание. */
        conn_reset(c, tun);
        return 1;
    }
    conn_live(c);
    /* Пока шло рукопожатие, узел соединения перестал быть активным (заменён): нести через
     * него нечего, клиент переподключится к живому. */
    if (d->stale && d->stale(g_dl->ctx, SESS(c))) {
        conn_reset(c, tun);
        return 1;
    }
    /* Ранние данные, которые клиент успел прислать за время рукопожатия, —
     * серверу, первым делом и до любых свежих пакетов. */
    if (c->early && early_flush(c) < 0) {
        conn_reset(c, tun);
        return 1;
    }
    c->last = g_now_s;
    /* Клиент слышал окно по месту в буфере ранних данных (conn_room): теперь буфера нет, окно —
     * полное, и сказать об этом надо сразу, иначе клиент с окном в несколько сотен байт ждёт
     * пробы нулевого окна. room_seen заводится заново — сравнивать теперь не с чем. */
    TR("поток готов (conn#%ld), ранние данные ушли\n", (long)(c - g_conns));
    return 0;
}

/* Набор узлов сменился (stack_nodes_changed): соединения через узел, который больше не активен, — в
 * сброс ближайшим проходом сроков (aborted: RST, а не FIN). Приложение переподключится сразу и
 * попадёт на живой узел, а не будет ждать своего таймаута на повисшем. seen — счёт перемен, уже
 * разобранных этим потоком цикла. */
static void nodes_sweep(unsigned *seen, uint64_t now) {
    unsigned ep_now = __atomic_load_n(&g_nodes_epoch, __ATOMIC_ACQUIRE);
    if (ep_now == *seen) return;
    *seen = ep_now;
    const struct dialer_ops *d = g_dl->ops;
    for (int li = 0; d->stale && li < g_live_n; li++) {
        struct conn *c = &g_conns[g_live[li]];
        if (c->pending || c->aborted || !d->stale(g_dl->ctx, SESS(c))) continue;
        c->srv_closed = 1;
        c->aborted = 1;
        c->closed_at = now;
    }
}

/* Сроки одного соединения — повтор, хвост ранних данных, закрытие после сервера или обрыва, уборка
 * задержавшихся. Один проход цикла на все соединения зовёт это по живым (worker_loop); отдельной
 * функцией — ради стенда (tests/poolmatch.c): сроки видны снаружи только пакетами в устройство. 1 —
 * соединение закрыто (его место в g_live занял другой), 0 — живо. */
static void sock_read(struct conn *c, const struct tun_dev *tun);
static inline int sock_want_read(const struct conn *c);

static int conn_deadlines(struct conn *c, const struct tun_dev *tun, uint64_t now) {
    /* Хвост ранних данных, не поместившийся в окно h2 на готовности потока:
     * дослать. Новых данных клиента может и не быть — досылать больше некому. */
    if (c->early && early_flush(c) < 0) {
        conn_reset(c, tun);
        return 1;
    }

    /* Клиент молчит с самого рукопожатия: открыть поток без его данных, чтобы мог заговорить
     * сервер, говорящий первым (dialer.h, send с n == 0). Клиента, который говорил, обслуживает
     * путь ранних данных выше. */
    if (!c->is_udp && !c->sent_any && !c->early && !c->srv_closed && c->estab_ns &&
        now - c->estab_ns >= SERVER_FIRST_MS * 1000000ull) {
        int sr = upstream_send(c, NULL, 0);
        if (sr == SEND_FATAL) {
            conn_reset(c, tun);
            return 1;
        }
    }

    if (c->cfd1) {
        /* Сокет клиента умер (запись или чтение отказали) — закрыть, узлу больше некому отдавать. */
        if (c->client_gone) { conn_drop(c); return 1; }
        /* Недочитанное у клиента (предел за вызов, место у узла вернулось, ранние данные ушли). */
        if (sock_want_read(c)) {
            sock_read(c, tun);
            if (!c->used) return 1;
            if (c->client_gone) { conn_drop(c); return 1; }
        }
    }

    /* Оборванная связь или узел, который больше не активен: RST клиенту сразу, без
     * дожидания подтверждений — данных за обрывом всё равно не будет (у UDP — просто
     * закрытие). */
    if (c->srv_closed && c->aborted) {
        TR("conn#%ld: связь с узлом оборвана — RST клиенту\n", (long)(c - g_conns));
        conn_reset(c, tun);
        return 1;
    }

    /* Поток UDP, закрытый узлом: ждать нечего и прощаться нечем — ни кольца
     * неподтверждённого, ни FIN у датаграмм не бывает. Освобождаем сразу; если
     * клиент пришлёт ещё датаграмму, откроется новый поток. */
    if (c->srv_closed && c->is_udp) {
        TR("узел закрыл поток UDP conn#%ld\n", (long)(c - g_conns));
        conn_drop(c);
        return 1;
    }

    /* Клиент закрыл свою половину и замолчал, а сервер своей не закрывает (узнать
     * о FIN клиента ему неоткуда): дальше ждать нечего — закрываем тем же путём,
     * что и после сервера. */
    if (c->client_fin && !c->srv_closed && g_now_s - c->last > CLOSE_DRAIN_MS / 1000) {
        c->srv_closed = 1;
        c->closed_at = now;
    }

    /* Закрытые сервером: как только клиенту дописано всё — закрываем (FIN). Если сокет не принял
     * остаток за отведённое время, закрываем всё равно: клиент мог уйти совсем. */
    if (c->srv_closed) {
        if (c->cfd1 && c->rtx.len && sock_flush(c) < 0) { conn_drop(c); return 1; }
        int drained = c->rtx.len == 0;
        if (!drained && (now - c->closed_at) / 1000000 < CLOSE_DRAIN_MS) return 0;
        if (!drained)
            TR("conn#%ld: клиенту не дописано %u байт за %d мс, закрываю\n",
               (long)(c - g_conns), c->rtx.len, CLOSE_DRAIN_MS);
        conn_drop(c);                       /* FIN клиенту посылает само закрытие сокета */
        return 1;
    }

    /* Пустое кольцо отдаём обратно системе. Соединение при этом полностью рабочее:
     * при следующих данных кольцо появится снова. Именно после простоя, а не сразу по
     * опустошении, — иначе на каждом залпе подтверждений шли бы malloc и free. */
    if (c->rtx.cap && !c->rtx.len && g_now_s - c->last > 5) rtx_done(&c->rtx);

    /* Уборка задержавшихся: без неё таблица заполняется соединениями, которые клиент
     * бросил без FIN, и новые перестают открываться.
     *
     * Порог — тот же IDLE_EVICT_S, что и у вытеснения: «мёртвое соединение» должно
     * означать одно и то же в обоих местах. Пробовал шестьдесят, рассчитывая
     * освобождать слоты раньше, — и получил RST по живым соединениям HTTP/2, которые
     * браузер переиспользует после минуты простоя.
     *
     * RST обязателен. Прежде здесь было молчаливое conn_drop, и клиент оставался с
     * соединением, которое считает открытым: следующий запрос по нему уходил в
     * пустоту и ждал таймаута — то есть наша уборка выглядела как зависший сайт. */
    if (c->is_udp && !c->udp_replied && g_now_s - c->last > UDP_UNREPLIED_S) {
        conn_reset(c, tun);                 /* у UDP это просто закрытие */
        return 1;
    }
    if (g_now_s - c->last > IDLE_EVICT_S) {
        /* Порог тот же, что у TCP, и это не экономия на константе. Простаивающий
         * поток UDP — это, как правило, QUIC между запросами: у него свой таймаут
         * простоя, и он короче нашего, то есть клиент бросит соединение первым.
         * Убрав поток раньше него, мы поменяли бы у следующей датаграммы исходный
         * порт НА СТОРОНЕ УЗЛА — для получателя это новый путь, и QUIC пришлось бы
         * заново подтверждать его. Столько же держит и conntrack ядра. */
        conn_reset(c, tun);                 /* у UDP это просто закрытие, без RST */
        return 1;
    }
    return 0;
}

/* Что нужно потоку, чтобы работать: своя очередь устройства и свой номер. Больше ничего —
 * дайлер общий (g_dl), а остальное состояние у потока собственное (__thread и его таблицы). */
/* ---- TCP через слушатель модуля (R-152) -----------------------------------------------------------
 *
 * ЗАЧЕМ. TCP клиента завершает ядро: правило steer в nat (prerouting и output) по метке выхода делает
 * redirect на порт модуля, и соединение приходит сюда обычным сокетом. Прототип на одном стенде
 * (без VLESS): 21-27 Гбит/с при 0,22-0,27 с процессора на ГиБ против 0,59 вниз и 1,04 вверх у
 * собственного приёмника TCP в TUN — и SACK, переупорядочивание, контроль перегрузки ядро даёт
 * само (I-512 был ровно про это). Решение владельца 2026-10-11, R-152 в хабе.
 *
 * Соединение — та же struct conn рабочего, с пулом, запасными и установщиками; сторона клиента —
 * сокет (cfd1). Из сокета — крупными чтениями прямо дайлеру; узел не принял (SEND_AGAIN) — остаток в
 * early, и сокет не читается, пока early не ушёл: окно клиенту держит ядро само. Из дайлера — в кольцо
 * rtx и одной записью в сокет в конце прохода; сокет полон — EPOLLOUT, и у узла не читаем.
 *
 * ПРИНИМАЕТСЯ ТОЛЬКО ПЕРЕНАПРАВЛЕННОЕ. Порт слушателя открыт на всех адресах; подключение прямо к нему
 * (назначение — сам этот адрес и порт) закрывается сразу, иначе любой в сети получил бы прокси.
 * Перенаправленное ядро помнит в conntrack, и SO_ORIGINAL_DST отдаёт исходное назначение.
 *
 * ПОДДЕЛЬНЫЙ АДРЕС. Правило redirect стоит раньше dnat fake-IP (у соединения одна привязка NAT), поэтому
 * сюда приходит поддельный адрес. Настоящий — из карты @fakeip набора правил (fake_real_kernel): её
 * резолвер ставит синхронно, ДО ответа клиенту, так что к первому соединению она всегда готова.
 * Файл состояния резолвера (fakeip.state: «домен\tподдельный\tнастоящий») — только запасной путь:
 * резолвер пишет его в фоне через секунду после изменения (FAKEIP_STATE_DEBOUNCE_S), и самое первое
 * соединение к новому домену может его ещё не застать (стенд QEMU 2026-10-13: «поддельный адрес …
 * без настоящего в fakeip.state» на свежем выходе, когда запись была раз в минуту). */
#define FAKE4_BASE 0xC6120000u              /* 198.18.0.0/15 — пул резолвера (dnsd_int.h) */
#define FAKE4_SIZE 0x00020000u
/* Пул IPv6 — fdfe:dcba:9876::/96, поддельный IPv6 = префикс и поддельный IPv4 той же записи в младших 32
 * битах (fakeip6_of в spec.h, резолвер): по IPv6 находится запись IPv4, а у неё — настоящий IPv6. */
static const uint8_t FAKE6_PREFIX[12] = { 0xfd, 0xfe, 0xdc, 0xba, 0x98, 0x76, 0, 0, 0, 0, 0, 0 };
struct fake_pair {
    uint32_t fake, real;        /* хостовый порядок у fake, сетевой у real (0 — настоящего IPv4 нет) */
    uint8_t has6;               /* настоящий IPv6 записи известен (четвёртое поле файла) */
    uint8_t real6[16];
};
static __thread struct fake_pair *g_fp;
static __thread size_t g_fp_n;
static __thread time_t g_fp_mtime;

static int fp_cmp(const void *a, const void *b) {
    uint32_t x = ((const struct fake_pair *)a)->fake, y = ((const struct fake_pair *)b)->fake;
    return x < y ? -1 : x > y;
}

static char *g_fakeip_path;   /* задан помощником плагина из {conf}; живёт до конца процесса */

void stack_set_fakeip_path(const char *path) {
    free(g_fakeip_path);
    g_fakeip_path = path && *path ? strdup(path) : NULL;
}

static void fake_load(void) {
    char path[4096];
    if (g_fakeip_path) snprintf(path, sizeof(path), "%s", g_fakeip_path);
    else if (snprintf(path, sizeof(path), "%s/fakeip.state", steer_state_dir()) >= (int)sizeof(path)) return;
    struct stat st;
    if (stat(path, &st) != 0 || st.st_mtime == g_fp_mtime) return;
    FILE *f = fopen(path, "r");
    if (!f) return;
    g_fp_mtime = st.st_mtime;
    size_t cap = 256, n = 0;
    struct fake_pair *a = malloc(cap * sizeof(*a));
    char line[512];
    while (a && fgets(line, sizeof(line), f)) {
        /* «домен \t поддельный \t настоящий IPv4 или - [\t настоящий IPv6]» */
        char *t1 = strchr(line, '\t');
        if (!t1) continue;
        char *t2 = strchr(t1 + 1, '\t');
        if (!t2) continue;
        *t2 = 0;
        char *r4 = t2 + 1, *r6 = NULL;
        char *t3 = strpbrk(r4, "\t\n");
        if (t3) {
            char c3 = *t3;
            *t3 = 0;
            if (c3 == '\t') {
                r6 = t3 + 1;
                char *e6 = strpbrk(r6, "\t\n");
                if (e6) *e6 = 0;
            }
        }
        struct in_addr fk, rl;
        struct fake_pair x;
        memset(&x, 0, sizeof(x));
        if (inet_pton(AF_INET, t1 + 1, &fk) != 1) continue;
        if (inet_pton(AF_INET, r4, &rl) == 1) x.real = rl.s_addr;
        if (r6 && inet_pton(AF_INET6, r6, x.real6) == 1) x.has6 = 1;
        if (!x.real && !x.has6) continue;
        if (n == cap) {
            struct fake_pair *b2 = realloc(a, cap * 2 * sizeof(*a));
            if (!b2) break;
            a = b2;
            cap *= 2;
        }
        x.fake = ntohl(fk.s_addr);
        a[n++] = x;
    }
    fclose(f);
    if (!a) return;
    qsort(a, n, sizeof(*a), fp_cmp);
    free(g_fp);
    g_fp = a;
    g_fp_n = n;
}

/* Атрибут netlink в buf[*n]: заголовок и значение, с выравниванием. Возврат — смещение атрибута (для
 * вложенных: длину дописывает fk_end). */
static size_t fk_attr(unsigned char *buf, size_t *n, uint16_t type, const void *v, size_t vl) {
    size_t at = *n;
    struct nlattr *a = (struct nlattr *)(buf + at);
    a->nla_type = type;
    a->nla_len = (uint16_t)(NLA_HDRLEN + vl);
    if (vl) memcpy(buf + at + NLA_HDRLEN, v, vl);
    *n = at + NLA_ALIGN(NLA_HDRLEN + vl);
    return at;
}

static void fk_end(unsigned char *buf, size_t n, size_t at) {
    ((struct nlattr *)(buf + at))->nla_len = (uint16_t)(n - at);
}

static const struct nlattr *fk_find(const unsigned char *p, size_t len, uint16_t type) {
    while (len >= NLA_HDRLEN) {
        const struct nlattr *a = (const struct nlattr *)p;
        if (a->nla_len < NLA_HDRLEN || a->nla_len > len) return NULL;
        if ((a->nla_type & NLA_TYPE_MASK) == type) return a;
        size_t step = NLA_ALIGN(a->nla_len);
        if (step >= len) return NULL;
        p += step;
        len -= step;
    }
    return NULL;
}
#define FK_PAY(a) ((const unsigned char *)(a) + NLA_HDRLEN)
#define FK_PLEN(a) ((size_t)(a)->nla_len - NLA_HDRLEN)

/* Настоящий адрес из карты таблицы inet steer — запросом GETSETELEM (не транзакция: доли
 * миллисекунды), сокет netlink на поток. set — карта (fakeip или fakeip6), key — поддельный адрес
 * (klen байт, сетевой порядок), в out (olen байт) ложится настоящий. 1 — нашёлся, 0 — элемента нет или
 * ответа нет (тогда — файл). */
static int fake_kernel_lookup(const char *set, const void *key_p, size_t klen, void *out_p, size_t olen) {
    static __thread int fd = -2;
    static __thread uint32_t seq;
    if (fd == -2) {
        fd = socket(AF_NETLINK, SOCK_RAW | SOCK_CLOEXEC, NETLINK_NETFILTER);
        struct sockaddr_nl sa = { .nl_family = AF_NETLINK };
        if (fd >= 0 && bind(fd, (struct sockaddr *)&sa, sizeof(sa)) != 0) { close(fd); fd = -1; }
        struct timeval tv = { 0, 200000 };
        if (fd >= 0) setsockopt(fd, SOL_SOCKET, SO_RCVTIMEO, &tv, sizeof(tv));
    }
    if (fd < 0) return 0;
    int found = 0;
    _Alignas(8) unsigned char buf[256];
    memset(buf, 0, sizeof(buf));
    struct nlmsghdr *nh = (struct nlmsghdr *)buf;
    struct nfgenmsg *nfg = (struct nfgenmsg *)(buf + NLMSG_HDRLEN);
    size_t n = NLMSG_HDRLEN + NLMSG_ALIGN(sizeof(*nfg));
    const char *tbl = nft_table();
    fk_attr(buf, &n, NFTA_SET_ELEM_LIST_TABLE, tbl, strlen(tbl) + 1);
    fk_attr(buf, &n, NFTA_SET_ELEM_LIST_SET, set, strlen(set) + 1);
    size_t els = fk_attr(buf, &n, NLA_F_NESTED | NFTA_SET_ELEM_LIST_ELEMENTS, NULL, 0);
    size_t el = fk_attr(buf, &n, NLA_F_NESTED | NFTA_LIST_ELEM, NULL, 0);
    size_t key = fk_attr(buf, &n, NLA_F_NESTED | NFTA_SET_ELEM_KEY, NULL, 0);
    fk_attr(buf, &n, NFTA_DATA_VALUE, key_p, klen);
    fk_end(buf, n, key);
    fk_end(buf, n, el);
    fk_end(buf, n, els);
    nh->nlmsg_len = (uint32_t)n;
    nh->nlmsg_type = (uint16_t)((NFNL_SUBSYS_NFTABLES << 8) | NFT_MSG_GETSETELEM);
    nh->nlmsg_flags = NLM_F_REQUEST | NLM_F_ACK;
    nh->nlmsg_seq = ++seq;
    nfg->nfgen_family = NFPROTO_INET;
    nfg->version = NFNETLINK_V0;
    struct sockaddr_nl dst = { .nl_family = AF_NETLINK };
    if (sendto(fd, buf, n, 0, (struct sockaddr *)&dst, sizeof(dst)) < 0) return 0;
    _Alignas(8) unsigned char rb[2048];
    for (;;) {
        ssize_t r = recv(fd, rb, sizeof(rb), 0);
        if (r < (ssize_t)NLMSG_HDRLEN) return found;
        size_t left = (size_t)r;
        for (struct nlmsghdr *h = (struct nlmsghdr *)rb; NLMSG_OK(h, left); h = NLMSG_NEXT(h, left)) {
            if (h->nlmsg_seq != seq) continue;                  /* хвост прежнего запроса */
            if (h->nlmsg_type == NLMSG_ERROR) return found;
            if (h->nlmsg_type != ((NFNL_SUBSYS_NFTABLES << 8) | NFT_MSG_NEWSETELEM)) continue;
            size_t hl = NLMSG_ALIGN(sizeof(struct nfgenmsg));
            if (h->nlmsg_len < NLMSG_HDRLEN + hl) continue;
            const unsigned char *p = (const unsigned char *)NLMSG_DATA(h) + hl;
            size_t pl = h->nlmsg_len - NLMSG_HDRLEN - hl;
            const struct nlattr *es = fk_find(p, pl, NFTA_SET_ELEM_LIST_ELEMENTS);
            const struct nlattr *e1 = es ? fk_find(FK_PAY(es), FK_PLEN(es), NFTA_LIST_ELEM) : NULL;
            const struct nlattr *da = e1 ? fk_find(FK_PAY(e1), FK_PLEN(e1), NFTA_SET_ELEM_DATA) : NULL;
            const struct nlattr *dv = da ? fk_find(FK_PAY(da), FK_PLEN(da), NFTA_DATA_VALUE) : NULL;
            if (dv && FK_PLEN(dv) == olen) { memcpy(out_p, FK_PAY(dv), olen); found = 1; }
        }
    }
}

/* Настоящий адрес для поддельного (сетевой порядок) или 0 — не знаем: карта ядра, затем файл. */
static uint32_t fake_real(uint32_t fake_be) {
    uint32_t k = 0;
    if (fake_kernel_lookup("fakeip", &fake_be, 4, &k, 4) && k) return k;
    struct fake_pair key;
    memset(&key, 0, sizeof(key));
    key.fake = ntohl(fake_be);
    for (int pass = 0; pass < 2; pass++) {
        struct fake_pair *hit = g_fp_n ? bsearch(&key, g_fp, g_fp_n, sizeof(*g_fp), fp_cmp) : NULL;
        if (hit && hit->real) return hit->real;
        if (pass == 0) fake_load();
    }
    return 0;
}

/* Поддельный IPv6 из пула? Тогда в младших четырёх байтах — поддельный IPv4 той же записи. */
static int fake6_is(const uint8_t a[16]) { return !memcmp(a, FAKE6_PREFIX, 12); }

/* То же для IPv6: настоящий адрес в real (16 байт). 1 — найден. Сначала карта fakeip6 в ядре (её резолвер
 * ставит до ответа клиенту, как fakeip), затем файл: запись IPv4 с тем же младшим словом и её IPv6. */
static int fake_real6(const uint8_t fake[16], uint8_t real[16]) {
    if (fake_kernel_lookup("fakeip6", fake, 16, real, 16)) return 1;
    struct fake_pair key;
    memset(&key, 0, sizeof(key));
    uint32_t lo;
    memcpy(&lo, fake + 12, 4);
    key.fake = ntohl(lo);
    for (int pass = 0; pass < 2; pass++) {
        struct fake_pair *hit = g_fp_n ? bsearch(&key, g_fp, g_fp_n, sizeof(*g_fp), fp_cmp) : NULL;
        if (hit && hit->has6) { memcpy(real, hit->real6, 16); return 1; }
        if (pass == 0) fake_load();
    }
    return 0;
}

static void sock_rst_close(int fd) {
    struct linger lg = { 1, 0 };
    setsockopt(fd, SOL_SOCKET, SO_LINGER, &lg, sizeof(lg));
    close(fd);
}

/* Одно принятое соединение — в таблицу этого рабочего (R-152): назначение у ядра, поток к узлу. */
static struct conn *conn_accept(int fd, const struct flow_key *k, const struct tun_dev *tun);

static void kaccept_fd(int fd, const struct tun_dev *tun) {
    struct sockaddr_storage peer, me;
    socklen_t pl = sizeof(peer), ml = sizeof(me);
    if (getpeername(fd, (struct sockaddr *)&peer, &pl) != 0 ||
        getsockname(fd, (struct sockaddr *)&me, &ml) != 0) { close(fd); return; }
    struct flow_key key;
    memset(&key, 0, sizeof(key));
    key.proto = 6;
    /* Клиент IPv4 на сокете двойного стека приходит как ::ffff:a.b.c.d: это соединение IPv4, и назначение у
     * него спрашивается по SOL_IP (ядро отдаёт его и для такого сокета). Настоящее IPv6 — IP6T_SO_ORIGINAL_DST. */
    const struct sockaddr_in6 *p6 = (const struct sockaddr_in6 *)&peer;
    int is4 = peer.ss_family == AF_INET || (peer.ss_family == AF_INET6 && IN6_IS_ADDR_V4MAPPED(&p6->sin6_addr));
    if (is4) {
        struct sockaddr_in od, me4;
        socklen_t ol = sizeof(od);
        if (getsockopt(fd, SOL_IP, SO_ORIGINAL_DST, &od, &ol) != 0) { close(fd); return; }
        uint32_t psrc, mip;
        uint16_t pport, mport;
        if (peer.ss_family == AF_INET) {
            memcpy(&me4, &me, sizeof(me4));
            psrc = ((const struct sockaddr_in *)&peer)->sin_addr.s_addr;
            pport = ((const struct sockaddr_in *)&peer)->sin_port;
            mip = me4.sin_addr.s_addr;
            mport = me4.sin_port;
        } else {
            memcpy(&psrc, p6->sin6_addr.s6_addr + 12, 4);
            pport = p6->sin6_port;
            memcpy(&mip, ((const struct sockaddr_in6 *)&me)->sin6_addr.s6_addr + 12, 4);
            mport = ((const struct sockaddr_in6 *)&me)->sin6_port;
        }
        if (od.sin_addr.s_addr == mip && od.sin_port == mport) {
            close(fd);                  /* не перенаправленное — прямо к порту модуля */
            return;
        }
        uint32_t dst = od.sin_addr.s_addr;
        uint32_t dh = ntohl(dst);
        if (dh - FAKE4_BASE < FAKE4_SIZE) {
            uint32_t real = fake_real(dst);
            if (!real) {
                static __thread time_t said;
                if (g_now_s - said >= 10) {
                    said = g_now_s;
                    char a[INET_ADDRSTRLEN];
                    inet_ntop(AF_INET, &dst, a, sizeof(a));
                    fprintf(stderr, LOG_W "поддельный адрес %s без настоящего в fakeip.state — соединение "
                                    "сброшено\n", a);
                }
                sock_rst_close(fd);
                return;
            }
            dst = real;
        }
        key.src = psrc;
        key.dst = dst;
        key.sport = ntohs(pport);
        key.dport = ntohs(od.sin_port);
    } else {
        struct sockaddr_in6 od;
        socklen_t ol = sizeof(od);
        const struct sockaddr_in6 *m6 = (const struct sockaddr_in6 *)&me;
        if (getsockopt(fd, SOL_IPV6, IP6T_SO_ORIGINAL_DST, &od, &ol) != 0 ||
            (!memcmp(&od.sin6_addr, &m6->sin6_addr, 16) && od.sin6_port == m6->sin6_port)) {
            close(fd);                  /* не перенаправленное — прямо к порту модуля */
            return;
        }
        uint8_t dst[16];
        memcpy(dst, &od.sin6_addr, 16);
        if (fake6_is(dst)) {
            uint8_t real[16];
            if (!fake_real6(dst, real)) {
                static __thread time_t said6;
                if (g_now_s - said6 >= 10) {
                    said6 = g_now_s;
                    char a[INET6_ADDRSTRLEN];
                    inet_ntop(AF_INET6, dst, a, sizeof(a));
                    fprintf(stderr, LOG_W "поддельный адрес %s без настоящего в карте fakeip6 и fakeip.state — "
                                    "соединение сброшено\n", a);
                }
                sock_rst_close(fd);
                return;
            }
            memcpy(dst, real, 16);
        }
        key.v6 = 1;
        memcpy(key.src6, &p6->sin6_addr, 16);
        memcpy(key.dst6, dst, 16);
        key.sport = ntohs(p6->sin6_port);
        key.dport = ntohs(od.sin6_port);
    }
    conn_accept(fd, &key, tun);
}

/* Принятый сокет клиента с уже известным назначением — в таблицу этого рабочего: соединение, поток к узлу
 * (запасная сессия или установщик). Отдельно от kaccept_fd ради стенда (tests/tunnelmatch.c): назначение
 * там задаётся, а не спрашивается у ядра. NULL — соединения нет (сокет уже закрыт со сбросом). */
static struct conn *conn_accept(int fd, const struct flow_key *k, const struct tun_dev *tun) {
    struct flow_key key = *k;
    if (flow_rejected(&key, 0)) { sock_rst_close(fd); return NULL; }   /* политика хоста (stack.h) */
    struct conn *c = conn_new(tun);
    if (!c) { sock_rst_close(fd); return NULL; }
    memset(c, 0, sizeof(*c));
    c->used = 1;
    c->born_turn = g_turn;
    c->key = key;
    c->fd = -1;
    c->aux = -1;
    c->cfd1 = fd + 1;
    c->last = g_now_s;
    c->estab_ns = g_now_ns ? g_now_ns : 1;
    conn_link(c);
    int one = 1;
    setsockopt(fd, IPPROTO_TCP, TCP_NODELAY, &one, sizeof(one));
    if (g_dl->ops->flow_open(g_dl->ctx, SESS(c), &key, 0) != 0) { conn_reset(c, tun); return NULL; }
    if (g_spare_want > 0 && spare_checkout(SESS(c)) == 0) {
        c->fd = g_dl->ops->fd(SESS(c));
        conn_live(c);
        node_sock_silence(c->fd);
        spare_refill();
        return c;
    }
    if (conn_submit(c) != 0) {
        static __thread time_t said_q;
        if (g_now_s - said_q >= 5) {
            said_q = g_now_s;
            fprintf(stderr, LOG_W "нет памяти под очередь установки соединений, соединение сброшено\n");
        }
        conn_reset(c, tun);
        return NULL;
    }
    c->pending = 1;                     /* установщик заполняет сессию; сокет не трогаем до готовности */
    spare_refill();
    return c;
}

/* Раздача соединений по рабочим — ПО КРУГУ, а не хэшем SO_REUSEPORT. Хэш пятёрки не балансирует: на
 * замере четыре выгрузки при двух рабочих в двух прогонах из трёх сели на одного (99 % против 0 %, вв4 5288
 * Мбит/с против 9411 у TUN). Принявший рабочий берёт следующий номер общего счётчика и, если он чужой,
 * отдаёт сокет почтой: дескриптор общий для процесса, цена — замок и побудка на соединение, а не на байт. */
static unsigned g_accept_rr;

/* Принять перенаправленные соединения: до 64 за событие, остальные — следующим витком. -1 — кончились
 * дескрипторы процесса или системы (EMFILE, ENFILE): слушатель по уровню будил бы цикл на каждом витке впустую,
 * поэтому вызывающий снимает его с epoll на время (I-534), а соединения тем временем ждут в очереди ядра. */
static int kaccept(int lfd, const struct tun_dev *tun) {
    for (int k = 0; k < 64; k++) {
        int fd = accept4(lfd, NULL, NULL, SOCK_NONBLOCK | SOCK_CLOEXEC);
        if (fd < 0) return errno == EMFILE || errno == ENFILE ? -1 : 0;
        if (g_rw && g_nwork > 1) {
            unsigned t = __atomic_fetch_add(&g_accept_rr, 1, __ATOMIC_RELAXED) % g_nwork;
            if (t != (unsigned)g_worker && xmail_fd(t, fd) == 0) continue;
        }
        kaccept_fd(fd, tun);
    }
    return 0;
}

/* Прочитать у клиента и отдать узлу (R-152). Сокет — по фронту: читаем, пока не EAGAIN (тогда CRD снят), или
 * пока узел не перестал принимать (место дайлера, SEND_AGAIN — остаток в early, CRD остаётся: дочитаем, когда
 * место вернётся), или до SOCK_READ_BUDGET за вызов — чтобы одно соединение не держало цикл (CRD остаётся,
 * проход сроков дочитает со следующим витком).
 *
 * Читаем крупно (до SOCK_READ_MAX одним read), а узлу отдаём порциями SOCK_SEND_CHUNK — столько, сколько с
 * обёртками дайлера (кадр Vision, заголовок ws, кадр gRPC и HTTP/2) ложится в ОДНУ запись TLS (16384 байта
 * открытого текста). Прежде чтение было ровно UP_MAX = 16400 байт, на 16 больше записи: каждые 16 КБ
 * уходили двумя записями TLS и двумя write (122 вызова write на МБ против 64 у пути через TUN). */
static void sock_read(struct conn *c, const struct tun_dev *tun) {
    static __thread unsigned char buf[SOCK_READ_MAX];
    size_t got = 0;
    while (got < SOCK_READ_BUDGET && c->used && (c->carmed & CRD) && !c->early && !c->client_fin &&
           !c->srv_closed) {
        size_t chunk = conn_up_max(c);
        if (chunk > SOCK_SEND_CHUNK && chunk <= UP_MAX) chunk = SOCK_SEND_CHUNK;   /* больше UP_MAX — свой предел дайлера */
        size_t cap = sizeof(buf);
        long room = conn_room(c);
        if (room >= 0 && (size_t)room < cap) cap = (size_t)room;
        if (!cap) return;
        ssize_t n = read(conn_cfd(c), buf, cap);
        if (n > 0) {
            c->last = g_now_s;
            got += (size_t)n;
            size_t off = 0;
            int sr = SEND_OK;
            while (off < (size_t)n) {
                size_t m = (size_t)n - off < chunk ? (size_t)n - off : chunk;
                sr = upstream_send(c, buf + off, m);
                if (sr != SEND_OK) break;
                off += m;
            }
            if (sr == SEND_OK) continue;
            if (sr == SEND_AGAIN) {
                size_t rest = (size_t)n - off;
                c->early = malloc(rest);
                if (!c->early) { conn_reset(c, tun); return; }
                memcpy(c->early, buf + off, rest);
                c->early_n = c->early_cap = (uint32_t)rest;
                c->early_off = 0;
                return;
            }
            conn_node_lost(c);
            conn_reset(c, tun);
            return;
        }
        if (n == 0) { c->client_fin = 1; c->carmed &= (uint8_t)~CRD; return; }
        if (errno == EINTR) continue;
        if (errno == EAGAIN || errno == EWOULDBLOCK) { c->carmed &= (uint8_t)~CRD; return; }
        c->client_gone = 1;
        return;
    }
}

/* Читать ли сокет клиента сейчас: фронт не дочитан, узел принимает, обе стороны открыты. */
static inline int sock_want_read(const struct conn *c) {
    return (c->carmed & CRD) && !c->early && !c->client_fin && !c->srv_closed && conn_room(c) != 0;
}

struct worker {
    struct tun_dev tun;
    int id;
    /* Кольцо и почта этого рабочего; NULL — прежний путь: поток сам читает свою очередь TUN. В
     * режиме с читателем дескриптор TUN общий и принадлежит читателю: рабочий только пишет в него и
     * не закрывает. */
    struct ring_work *rw;
    /* Дошёл ли поток до цикла (1) или отказал при подготовке (2); пока 0 — ещё готовится. Читатель
     * не запускается, пока все рабочие не доложили: число рабочих и их номера должны быть
     * окончательны до первого пакета. */
    int state;
    /* Дошёл ли поток до цикла, то есть нёс ли эта очередь трафик хоть секунду. Нужно
     * ровно для одного: различить в журнале «туннель не поднялся» и «туннель работал и
     * умер». Для кода выхода разницы нет — он в обоих случаях ненулевой. */
    int served;
};

static void *worker_loop(void *arg) {
    struct worker *w = arg;
    struct tun_dev tun = w->tun;
    int tun_fd = tun.fd;
    g_stat_tun = &tun;
    struct ring_work *rw = w->rw;
    /* Общий дескриптор TUN закрывает читатель (stack_run), а не рабочий. */
    int own_tun = rw == NULL || g_steered;
    g_worker = w->id;

    uint64_t stats_at = g_stats ? now_ns() : 0;
    uint64_t spare_at = 0;  /* когда последний раз выбрасывали протухший запас */
    unsigned nodes_seen = __atomic_load_n(&g_nodes_epoch, __ATOMIC_ACQUIRE);
    /* Таблицы потока — в куче (см. «таблицы потока» у g_conns). Прежде они были в TLS и
     * отказать не могли: не дали бы памяти — не создался бы сам поток. Теперь отказ свой, и
     * он такой же, как отказ epoll ниже: поток не запускается, очередь отдаётся остальным. */
    if (conn_table_init() != 0) {
        fprintf(stderr, LOG_W "нет памяти под таблицу соединений (%s) — поток не запущен, "
                        "очередь отдана остальным\n", strerror(errno));
        if (own_tun) close(tun_fd);
        __atomic_store_n(&w->state, 2, __ATOMIC_RELEASE);
        return NULL;
    }
    unsigned char pkt[TUNNEL_BUF];

    /* epoll, а не poll, и это не вкусовщина.
     *
     * poll получает СПИСОК дескрипторов на каждый вызов: список надо собрать в памяти,
     * скопировать в ядро, а ядро — обойти целиком и опросить каждый дескриптор. При 320
     * живых соединениях и двух тысячах витков в секунду это 640 тысяч опросов в секунду,
     * из которых интересны единицы. На роутере, где один вызов poll на 320 дескрипторов
     * стоит сотни микросекунд, цикл упирался в него раньше, чем в криптографию.
     *
     * epoll хранит набор в ядре и отдаёт ТОЛЬКО готовое: цена вызова не зависит от числа
     * соединений. Взамен приходится следить за составом набора — этим и занят флаг armed:
     * epoll_ctl вызывается на изменение состояния, а не на каждом витке. */
    /* Очередь ОБЯЗАНА закрыться на любом выходе отсюда, и это не гигиена дескрипторов.
     *
     * Ядро раскладывает потоки по очередям как хэш % numqueues, а numqueues считает
     * ПРИСОЕДИНЁННЫЕ очереди, не читаемые. Оставить дескриптор открытым и уйти — значит
     * навсегда отдать долю трафика в очередь, из которой никто не читает: соединения в неё
     * попадают и молча пропадают. Снаружи это «часть сайтов не открывается никогда», причём
     * стабильно одни и те же, потому что хэш постоянен.
     *
     * close() эту очередь отсоединяет (tun_detach в ядре уменьшает numqueues), и потоки
     * расходятся по живым. Проверено опытом, а не по памяти — build/qdetach.c: после
     * закрытия второй из двух очередей все 40 потоков пришли в первую. */
    int ep = epoll_create1(0);
    if (ep < 0) {
        fprintf(stderr, LOG_W "epoll недоступен (%s) — поток не запущен, "
                        "очередь отдана остальным\n", strerror(errno));
        conn_table_free();
        if (own_tun) close(tun_fd);
        __atomic_store_n(&w->state, 2, __ATOMIC_RELEASE);
        return NULL;
    }
    /* Метки TUN, eventfd и слушателя не совпадают с номером соединения: слотов меньше SLOTS_IDX_MAX,
     * метки выше (TOK_*). */
    const uint32_t TUN_TOKEN = TOK_TUN;
    const uint32_t EFD_TOKEN = TOK_EFD;
    /* С читателем (rw) в epoll рабочего устройства нет: пакеты приходят в кольцо, а будит eventfd. */
    if (own_tun) {
        struct epoll_event e = { .events = EPOLLIN, .data = { .u32 = TUN_TOKEN } };
        if (epoll_ctl(ep, EPOLL_CTL_ADD, tun_fd, &e) != 0) {
            fprintf(stderr, LOG_W "TUN не встал в epoll (%s) — поток не запущен, "
                            "очередь отдана остальным\n", strerror(errno));
            close(ep);
            conn_table_free();
            close(tun_fd);
            return NULL;
        }
    }
    /* Побудка от установщиков: без неё готовое рукопожатие ждало опроса раз в 20 мс —
     * то есть до 20 мс сверху на КАЖДОЕ новое соединение. Отказ ядра не страшен: опрос
     * остаётся как запасной путь, просто с прежней ценой. */
    int efd = eventfd(0, EFD_NONBLOCK | EFD_CLOEXEC);
    if (efd >= 0) {
        struct epoll_event e = { .events = EPOLLIN, .data = { .u32 = EFD_TOKEN } };
        if (epoll_ctl(ep, EPOLL_CTL_ADD, efd, &e) != 0) { close(efd); efd = -1; }
    }
    g_conn_efd = efd;
    /* Слушатель TCP (R-152): у рабочего 0 — открытый в stack_run, у остальных свой (klisten_open).
     * Не встал у рабочего 1+ — соединения разберут остальные рабочие: группа SO_REUSEPORT раздаёт
     * только тем, кто в ней. */
    const uint32_t LST_TOKEN = TOK_LST;
    int lfd = -1;
    if (g_kport > 0) {
        if (w->id == 0 && g_lfd0 >= 0) {
            lfd = g_lfd0;
            g_lfd0 = -1;
        } else {
            lfd = klisten_open();
        }
        if (lfd < 0) {
            fprintf(stderr, LOG_W "рабочий %d: слушатель TCP на порту %d не встал (%s)\n", w->id,
                    g_kport, strerror(errno));
        } else {
            struct epoll_event e = { .events = EPOLLIN, .data = { .u32 = LST_TOKEN } };
            epoll_ctl(ep, EPOLL_CTL_ADD, lfd, &e);
        }
    }
    /* Читатель будит этот же eventfd: побудка от установщика и от читателя — одно и то же «проснись и
     * посмотри», а разбор всего сразу — в витке. Ставится ДО state: читатель не начнёт, пока не доложат
     * все, и увидит дескриптор. */
    if (rw) rw->ring.efd = efd;
    struct epoll_event evs[EV_BATCH];
    int tun_out = 0;            /* на устройстве стоит EPOLLOUT: в очереди записи (tun.c) есть пакеты */
    uint64_t lst_paused = 0;    /* слушатель снят с epoll (кончились дескрипторы) с этого момента, нс; 0 — стоит */
    g_ep = ep;
    /* Дайлер встаёт в цикл ДО state: его сокет должен стоять в epoll к первому витку, а соединение с
     * узлом — подниматься, пока рабочий ещё ничего не несёт. */
    if (g_inloop) g_dl->ops->loop_start(w->id, g_workers_plan);
    w->served = 1;      /* очередь встала в epoll — дальше она несёт трафик */
    __atomic_store_n(&w->state, 1, __ATOMIC_RELEASE);

    for (;;) {
        /* Читатель ушёл (ошибка устройства) или другой рабочий упал: выходим и мы, чтобы процесс
         * завершился целиком и procd поднял его заново, а не держал половину рабочих. */
        if (rw && __atomic_load_n(&g_ring_stop, __ATOMIC_RELAXED)) break;
        /* Время снимается ОДИН раз на виток и лежит в g_now_ns/g_now_s — почему, написано
         * там же, у их объявления. */
        uint64_t now = now_ns();
        g_now_ns = now;
        g_now_s = (time_t)(now / 1000000000ull);

        /* ОДИН проход по живым соединениям на весь виток. Раньше их было четырнадцать по
         * ВСЕЙ таблице — см. комментарий у struct conn, там числа.
         *
         * Здесь считается сразу всё, что нужно перед ожиданием: состав набора epoll, число
         * заявок в работе, соединения с уже прочитанными данными и ближайший срок повтора. */
        int pend = 0, forced = 0, rx_any = 0, rx_dirty = 0;
        /* Таймаут — до ближайшего срока повтора, а не всегда секунда: иначе повтор ждал бы,
         * пока цикл проснётся сам. При живом трафике это происходит сразу, а при потере
         * последнего сегмента просыпаться уже нечему — ровно тот случай, для которого
         * таймер и нужен. */
        int wait_ms = 1000;
        for (int li = 0; li < g_live_n; li++) {
            struct conn *c = &g_conns[g_live[li]];
            if (c->pending) {
                pend++;
                /* Дайлер с DC_INLOOP ответил, не дожидаясь витка (отказ на месте): будить некому, разбор
                 * заявки — в этом же ожидании без сна. */
                if (g_inloop && __atomic_load_n(&c->done, __ATOMIC_RELAXED)) forced++;
                continue;
            }

            /* Спрашивать сервер о новых данных, пока клиент не разгрёб прежние, нельзя.
             *
             * Это и есть управление потоком, которого у нас иначе нет: прочитав, мы обязаны
             * сразу записать в устройство, а очередь устройства не бесконечна. Переполнив
             * её, мы теряем сегмент — и клиент ждёт повтора там, где мог бы не ждать.
             *
             * Замер: на роутере без этой проверки передача вставала на втором мегабайте.
             *
             * У закрытых сервером читать нечего вовсе — они живут только чтобы додать
             * клиенту остаток. */
            /* У потока UDP окна нет, а значит нет и повода не читать: датаграмма уходит
             * клиенту сразу и целиком, копить её негде и не нужно. Придерживать чтение
             * было бы не управлением потоком, а задержкой на пустом месте. */
            int want = !c->srv_closed && (c->is_udp || client_can_take_record(c));
            if (!want && !c->srv_closed && g_stats) g_st.win_skips++;
            /* Чтение стоит в наборе всегда (по фронту, EPOLLET), а не только пока клиент готов принять: прежде
             * закрытое окно снимало дескриптор с epoll (DEL), открытое — ставило (ADD), и это 36-41 вызова
             * epoll_ctl на МБ, 2,7 % цикла (замер профилировщика). По уровню так нельзя — готовый на чтение
             * сокет будил бы цикл на каждом витке впустую, пока окно закрыто, — поэтому фронт: событие приходит
             * один раз на новые данные, а решает цикл, читать ли сейчас. Событие при закрытом окне не теряется,
             * а откладывается в rx_ready (см. разбор событий ниже), и когда окно откроется, соединение прочтёт
             * проход после разбора TUN. Фронт обязывает читать до пустого сокета или помнить, что недочитали:
             * drain_conn_reads так и делает (rx_ready). У дайлера с DC_INLOOP дескриптора нет, и в набор
             * нечего ставить: события потока приходят из loop_poll (stack_sess_rx). EPOLLOUT (по уровню) — только
             * пока узел не принял данные клиента сокета: SEND_AGAIN у дайлера без своего окна (room -1, сокет
             * узла полон) ждёт записи узла событием, а не опросом (R-152). */
            unsigned arm = ARM_IN | (((c->cfd1 && c->early && conn_room(c) < 0) || conn_out_pending(c)) ? ARM_OUT : 0u);
            if (!g_inloop && arm != c->armed) {
                struct epoll_event e = { .events = EPOLLIN | EPOLLET | (arm & ARM_OUT ? EPOLLOUT : 0u),
                                         .data = { .u32 = (uint32_t)(c - g_conns) } };
                int op = !c->armed ? EPOLL_CTL_ADD : EPOLL_CTL_MOD;
                if (epoll_ctl(ep, op, c->fd, &e) == 0)
                    c->armed = (uint8_t)arm;
            }
            aux_sync(ep, c);
            if (c->cfd1) {
                /* Сокет клиента — в набор один раз, по фронту, на чтение и запись сразу; что из этого готово,
                 * помнят CRD и CWR, и подписку больше не трогаем. Сразу после ADD ядро само сообщит о
                 * готовом (данные, пришедшие до установки потока, ждут в сокете). */
                if (!(c->carmed & CARM_ADDED)) {
                    struct epoll_event e = { .events = EPOLLIN | EPOLLOUT | EPOLLRDHUP | EPOLLET,
                                             .data = { .u32 = SOCK_BIT | (uint32_t)(c - g_conns) } };
                    if (epoll_ctl(ep, EPOLL_CTL_ADD, conn_cfd(c), &e) == 0) c->carmed |= CARM_ADDED;
                }
                /* Недочитанное, которое можно читать, — без ожидания: фронт потрачен, ядро не напомнит. */
                if (sock_want_read(c)) forced++;
                /* Узел не принял (SEND_AGAIN), и у дайлера нет своего окна (room -1: сокет узла полон) —
                 * ждём записи узла событием (ARM_OUT выше). Окно HTTP/2 (room ≥ 0)
                 * открывается чтением узла (WINDOW_UPDATE), а не записью: там событием служит чтение, и
                 * запасной срок — 10 мс. */
                if (c->early && conn_room(c) >= 0 && wait_ms > 10) wait_ms = 10;
            }
            /* Данные уже у нас, и ядро о них не сообщит: разберём их без ожидания. */
            if (want && c->rx_ready) forced++;
            if (c->rx_ready) rx_any = 1;

        }
        if (g_stats) g_st.conns = (uint32_t)g_live_n;

        /* Заявки в работе больше не заставляют просыпаться часто: установщик будит цикл сам,
         * через eventfd, и готовность разбирается в тот же миг, а не на следующем опросе.
         *
         * Частый опрос остаётся ЗАПАСНЫМ путём — ровно на случай, когда ядро дескриптора не
         * дало. Двадцать миллисекунд там были худшей добавкой к времени соединения; теперь
         * добавки нет вовсе, а строка ниже нужна, чтобы отказ eventfd стоил прежней цены, а
         * не зависшего рукопожатия. */
        if (pend && efd < 0 && wait_ms > 20) wait_ms = 20;
        if (forced) wait_ms = 0;
        /* Порция из TUN оборвалась на пределе посреди склеенного кадра: остаток лежит в нашем буфере, и
         * epoll о нём не скажет (tun_buffered). Не спим — разбираем дальше в этом же витке. */
        if (own_tun && tun_buffered(&tun)) wait_ms = 0;
        /* Дайлер в цикле: доделать накопленное витком и сказать, когда ему нужен следующий (таймер QUIC). */
        if (g_inloop) {
            int dw = g_dl->ops->loop_wait();
            if (dw >= 0 && dw < wait_ms) wait_ms = dw;
        }

        /* Событий за виток может прийти на одно больше, чем соединений: TUN и побудка — тоже
         * дескрипторы. Меньший предел не терял бы событие (уровневый epoll покажет его
         * снова), но откладывал бы его на виток, а откладывать здесь нечего. */
        /* Кольцо от читателя. Спать можно, только объявив себя спящим и проверив кольцо ещё раз
         * (spsc_sleep_begin): иначе пакет, пришедший между проверкой и сном, будил бы нас лишь со
         * следующим. Почта будит безусловно (eventfd уровневый), ей проверки достаточно. Без eventfd
         * (ядро не дало) будить нечем — просыпаемся раз в миллисекунду. */
        int sleeping = 0;
        if (rw && wait_ms > 0) {
            if (__atomic_load_n(&rw->mail.n, __ATOMIC_RELAXED) || __atomic_load_n(&rw->mail.nfd, __ATOMIC_RELAXED))
                wait_ms = 0;
            else if (g_steered) { /* своя очередь TUN и побудка почты — обе в epoll */ }
            else if (efd < 0) { if (wait_ms > 1) wait_ms = 1; }
            else if (spsc_sleep_begin(&rw->ring)) sleeping = 1;
            else wait_ms = 0;
        }
        /* Слушатель, снятый за нехваткой дескрипторов, возвращается через LST_PAUSE_MS: к тому времени
         * закрытые соединения вернули часть номеров. Пока снят — цикл просыпается к этому сроку. */
        if (lst_paused) {
            uint64_t el = (now_ns() - lst_paused) / 1000000ull;
            if (el >= LST_PAUSE_MS) {
                struct epoll_event le = { .events = EPOLLIN, .data = { .u32 = TOK_LST } };
                if (epoll_ctl(ep, EPOLL_CTL_MOD, lfd, &le) == 0) lst_paused = 0;
                else lst_paused = now_ns();
            } else if ((int)(LST_PAUSE_MS - el) < wait_ms) {
                wait_ms = (int)(LST_PAUSE_MS - el);
            }
        }
        /* Очередь записи в устройство (tun.c, I-534): датаграмму, которую устройство не приняло, цикл не
         * ждёт, а доставит, когда оно освободится. Пока очередь не пуста — на устройстве стоит EPOLLOUT. */
        if (tun_wq_pending()) tun_wq_flush();
        int want_out = tun_wq_pending();
        if (want_out != tun_out) {
            tun_out = want_out;
            struct epoll_event oe = { .events = (own_tun ? (uint32_t)EPOLLIN : 0u) | (want_out ? (uint32_t)EPOLLOUT : 0u),
                                      .data = { .u32 = TUN_TOKEN } };
            if (own_tun) epoll_ctl(ep, EPOLL_CTL_MOD, tun_fd, &oe);
            else epoll_ctl(ep, want_out ? EPOLL_CTL_ADD : EPOLL_CTL_DEL, tun_fd, &oe);
        }
        int r = epoll_wait(ep, evs, EV_BATCH, wait_ms);
        if (sleeping) spsc_sleep_end(&rw->ring);
        g_turn++;
        uint64_t after_poll = now_ns();
        g_now_ns = after_poll;
        g_now_s = (time_t)(after_poll / 1000000000ull);
        if (g_stats) {
            g_st.poll_ns += after_poll - now;
            g_st.iters++;
            if (after_poll - stats_at >= 2000000000ull) {
                stats_dump(after_poll - stats_at);
                stats_at = after_poll;
            }
        }
        if (r < 0) {
            if (errno == EINTR) continue;
            break;
        }

        /* Дайлер в цикле разбирает свой сокет и сроки ПЕРВЫМ: исход открытия (stack_sess_ready) нужен
         * проходу по заявкам ниже, а пришедшие данные и подтверждения — проходу чтения. Ему же принадлежит
         * весь ввод-вывод связи с узлом, так что отдельного потока и круга через сокеты у него нет. */
        if (g_inloop) {
            int lr = 0;
            for (int i = 0; i < r; i++)
                if (evs[i].data.u32 == LOOP_TOKEN) { lr = 1; break; }
            g_dl->ops->loop_poll(lr);
            if (g_rx_kick) { g_rx_kick = 0; rx_dirty = 1; }
        }

        /* Готовые заявки. SYN-ACK клиенту ушёл ещё на SYN — здесь поток к узлу либо
         * готов (и получает ранние данные из буфера), либо не открылся (и клиент
         * получает RST). Разбираем ДО чтения из TUN — свежие данные клиента пусть
         * попадут в этот же проход, а не в следующий.
         *
         * Обход по живым, и только когда заявки вообще есть: в устоявшемся состоянии их
         * нет, и проход не делается вовсе. */
        /* Индекс двигается ВРУЧНУЮ: conn_drop переставляет в g_live последний элемент на
         * место освободившегося, и обычный li++ проскочил бы его не глядя. Один раз это уже
         * стоило соединений, живших до таймаута вместо разбора. */
        for (int li = 0; pend && li < g_live_n; ) {
            struct conn *c = &g_conns[g_live[li]];
            if (!c->pending || !__atomic_load_n(&c->done, __ATOMIC_ACQUIRE)) { li++; continue; }
            pend--;
            if (!conn_ready(c, &tun)) li++;
        }

        /* Готовность TUN ищем среди событий. Разбираем его ПЕРВЫМ, до чтения у серверов:
         * подтверждения клиента открывают окно, и разобрав их раньше, мы в этом же витке
         * успеваем взять у сервера следующую порцию. Счётчик побудки просто вычерпываем —
         * само событие уже сделало своё дело, подняв epoll_wait. */
        int tun_ready = own_tun && tun_buffered(&tun);
        for (int i = 0; i < r; i++) {
            if (evs[i].data.u32 == TUN_TOKEN) tun_ready = 1;
            else if (evs[i].data.u32 == LST_TOKEN && lfd >= 0) {
                if (kaccept(lfd, &tun) < 0 && !lst_paused) {
                    /* Снять слушателя с epoll до LST_PAUSE_MS: принимать нечем, а будить цикл незачем. */
                    struct epoll_event le = { .events = 0, .data = { .u32 = TOK_LST } };
                    if (epoll_ctl(ep, EPOLL_CTL_MOD, lfd, &le) == 0) lst_paused = g_now_ns;
                    static __thread time_t said_fd;
                    if (g_now_s - said_fd >= 10) {
                        said_fd = g_now_s;
                        fprintf(stderr, LOG_W "кончились дескрипторы процесса (%zu соединений у потока) — новые "
                                        "соединения ждут в очереди ядра; поднимите предел открытых файлов (ulimit -n)\n",
                                g_nslots);
                    }
                }
            }
            else if (evs[i].data.u32 == EFD_TOKEN && efd >= 0) {
                uint64_t drained;
                ssize_t rd = read(efd, &drained, sizeof(drained));
                (void)rd;
            }
        }

        if (rw && __atomic_load_n(&rw->mail.nfd, __ATOMIC_RELAXED)) {
            /* Сокеты клиентов, отданные другими рабочими (раздача по кругу, kaccept). */
            struct xfd *l = xmail_take_fds(&rw->mail);
            while (l) {
                struct xfd *x = l;
                l = x->next;
                kaccept_fd(x->fd, &tun);
                free(x);
            }
        }
        if (rw && g_steered && __atomic_load_n(&rw->mail.n, __ATOMIC_RELAXED)) {
            /* Раздаёт ядро: почта — только датаграммы, собранные из фрагментов у другого рабочего (их
             * владелец — по хэшу пятёрки). */
            struct xpkt *mail = xmail_take(&rw->mail);
            while (mail) {
                struct xpkt *x = mail;
                mail = x->next;
                handle_packet(&tun, x->d, x->n);
                free(x);
            }
        }
        if (rw && !g_steered) {
            /* ПЕРВЫМ — пакеты клиента от читателя, и только потом чтение у узлов (rx_ready ниже): по
             * подтверждению открывается окно, и обратный порядок читал бы у узла на виток позже
             * (отчёт по R-147/R-148). Порция — те же TUN_DRAIN_MAX пакетов, что и у прямого чтения. */
            int k = 0;
            struct xpkt *mail = __atomic_load_n(&rw->mail.n, __ATOMIC_RELAXED) ? xmail_take(&rw->mail) : NULL;
            while (mail) {
                struct xpkt *x = mail;
                mail = x->next;
                handle_packet(&tun, x->d, x->n);
                free(x);
                k++;
            }
            /* Кольцо разбирается ЦЕЛИКОМ за виток (до RING_SLOTS пакетов), порциями по TUN_DRAIN_MAX. По одной
             * порции за виток, как у прямого чтения, было мало: между витками рабочий читает у узлов, и за это
             * время читатель успевал выложить пачку склеенных кадров выгрузки (до 45 пакетов каждый) —
             * стенд run-tunnel-mt ловил переполнение кольца при 2, 4 и 8 рабочих (106–1355 пакетов на
             * 70–100 тыс.). У прямого чтения запас давала очередь устройства в ядре (txqueuelen). */
            uint32_t rn;
            const unsigned char *rp;
            uint64_t t1 = 0;
            unsigned taken = 0;
            for (;;) {
                while (k < TUN_DRAIN_MAX && (rp = spsc_peek(&rw->ring, &rn)) != NULL) {
                    if (g_stats) t1 = now_ns();
                    handle_packet(&tun, rp, rn);
                    spsc_pop(&rw->ring);
                    g_ring_pkts++;
                    if (g_stats) { g_st.tun_reads++; g_st.pkt_ns += now_ns() - t1; }
                    k++;
                }
                if (!k) break;
                spsc_room(&rw->ring);     /* место освободилось — разбудить читателя, если ждёт */
                taken += (unsigned)k;
                if (k < TUN_DRAIN_MAX || taken >= RING_SLOTS) break;
                k = 0;
            }
        } else if (tun_ready) {
            /* ВЫЧЕРПЫВАЕМ устройство, а не читаем по пакету за проход.
             *
             * Во время скачивания из TUN приходят подтверждения клиента, и именно они
             * открывают окно. Читая по одному за проход, мы ограничивали скорость числом
             * проходов цикла: замерено 1900 проходов в секунду × ~2920 байт на
             * подтверждение = 5,5 МБ/с, ровно тот потолок, который и наблюдался.
             *
             * Устройство переведено в неблокирующий режим, поэтому «больше нечего» приходит
             * как EAGAIN, а не как сон. Предел на проход всё равно нужен: иначе поток
             * пакетов от одного клиента не даст дойти до чтения у серверов. */
            int k;
            for (k = 0; k < TUN_DRAIN_MAX; k++) {
                uint64_t t0 = g_stats ? now_ns() : 0;
                ssize_t rn = tun_read_packet(&tun, pkt, sizeof(pkt));
                uint64_t t1 = g_stats ? now_ns() : 0;
                if (rn <= 0) break;
                if (g_stats) { g_st.tun_reads++; g_st.tun_read_ns += t1 - t0; }
                handle_packet(&tun, pkt, (size_t)rn);
                if (g_stats) g_st.pkt_ns += now_ns() - t1;
                if (rw) g_ring_pkts++;      /* раздаёт ядро: «пакетов от раздачи» — из своей очереди */
            }
        }
        for (int i = 0; i < r; i++) {
            if (evs[i].data.u32 & AUX_BIT) {
                aux_event(ep, &g_conns[evs[i].data.u32 & ~AUX_BIT]);
                continue;
            }
            if (evs[i].data.u32 & SOCK_BIT) {
                struct conn *c = &g_conns[evs[i].data.u32 & ~SOCK_BIT];
                if (!c->used || !c->cfd1) continue;
                /* Готовность запоминается и у ждущего установщика: прочтём, когда поток встанет. Событие
                 * могло достаться и новому соединению в том же слоте — лишний флаг стоит одного EAGAIN. */
                if (evs[i].events & EPOLLOUT) c->carmed |= CWR;
                if (evs[i].events & (EPOLLIN | EPOLLRDHUP | EPOLLHUP | EPOLLERR)) c->carmed |= CRD;
                if (c->pending) continue;
                if ((c->carmed & CWR) && c->rtx.len &&
                    sock_flush(c) == 0 && c->rx_ready && client_can_take_record(c)) rx_dirty = 1;
                if (sock_want_read(c)) sock_read(c, &tun);
                continue;
            }
            if (evs[i].data.u32 >= TOK_TUN) continue;  /* TUN, eventfd, слушатель */
            struct conn *c = &g_conns[evs[i].data.u32];
            /* Слот мог освободиться в этом же витке — на FIN или RST от клиента — и даже
             * достаться новому соединению. Пропускаем свободный слот, соединение, ждущее
             * установщика (его сессию трогать нельзя: её прямо сейчас заполняет установщик), и
             * любое родившееся в этом же витке: событие было его предшественника. Без последней
             * проверки новое соединение, взявшее запасную сессию (оно НЕ pending), получало
             * чужое событие, читало свежую связь — блокирующую и пока пустую — и весь цикл
             * вставал на срок соединения. */
            if (!c->used || c->pending || c->born_turn == g_turn) continue;
            /* Узел снова принимает запись: дослать то, что связь держит в очереди (живая запись, I-534). Отказ —
             * связь сломана, как при отказе send. */
            if ((evs[i].events & EPOLLOUT) && g_dl->ops->out_flush && c->fd >= 0 &&
                g_dl->ops->out_flush(g_dl->ctx, SESS(c)) < 0) {
                conn_node_lost(c);
                conn_reset(c, &tun);
                continue;
            }
            /* Только запись: узел снова принимает — ранние данные досылает проход сроков (conn_deadlines). */
            if (!(evs[i].events & ~(uint32_t)EPOLLOUT)) continue;
            /* Уже прочитанное разбирает второй проход ниже — здесь пропускаем, чтобы одно
             * соединение не получило двойную порцию за виток и не отняло её у остальных. */
            if (c->rx_ready) continue;
            /* Готовность посчитана ДО разбора порции из TUN, а в ней могло приехать
             * подтверждение с меньшим окном. Читать в этом случае нельзя: отданное за окно
             * приёмник молча выбросит, и закрывать дыру придётся повтором. Проверка стоит
             * копейки и снимает зависимость от того, успел ли epoll узнать о снятии.
             *
             * У потока UDP окна нет: спрашивать про него — значит не читать НИКОГДА, потому
             * что окно там нулевое по определению (см. client_room). Ровно на этом UDP и не
             * работал в первой версии: датаграмма уходила серверу, ответ лежал в сокете, а
             * читать его никто не приходил. */
            if (c->srv_closed) continue;
            /* Окно закрыто — фронт уже потрачен, а сокет, возможно, полон: запоминаем, что читать надо, и
             * читаем, когда окно откроется (проход ниже, в этом же витке, если подтверждение уже разобрано). */
            if (!c->is_udp && !client_can_take_record(c)) { c->rx_ready = 1; rx_dirty = 1; continue; }
            drain_conn(c, &tun);
        }

        /* Соединения, у которых данные уже лежат в буфере или у сокета, но читать было нельзя или нечем
         * разбудить: ядро о них не сообщит (буфер записей — для epoll не существует, а фронт EPOLLET уже
         * потрачен). Проход стоит ПОСЛЕ разбора событий: сокет клиента, принявший кольцо (EPOLLOUT), и есть то,
         * чего соединение ждало, — читаем у узла в этом же витке, а не со следующего. Проход делается, только когда
         * такие есть: у кого-то стоял флаг до ожидания (rx_any) или он встал в этом витке (rx_dirty). */
        for (int li = 0; (rx_any || rx_dirty) && li < g_live_n; li++) {
            struct conn *c = &g_conns[g_live[li]];
            if (!c->rx_ready || c->pending) continue;
            /* Тот же отказ, что у разбора событий: читать у узла, когда кольцу клиента некуда принять запись,
             * нельзя. Флаг при этом остаётся (ждёт места в кольце клиента). */
            if (c->srv_closed || (!c->is_udp && !client_can_take_record(c))) continue;
            drain_conn(c, &tun);
        }

        /* Один проход на все сроки: ранние данные, недочитанное у клиента, закрытие после сервера, уборка
         * задержавшихся.
         * Раньше это были три отдельных обхода ВСЕЙ таблицы — то есть три прохода по 5,8 МБ
         * ради нескольких соединений.
         *
         * Время обновляем: между ожиданием и этим местом мог пройти весь разбор порции из
         * TUN и чтение у серверов, то есть миллисекунды. */
        g_now_ns = now_ns();
        g_now_s = (time_t)(g_now_ns / 1000000000ull);
        now = g_now_ns;
        /* Протухший запас — тоже срок, и здесь ему место. Раз в секунду, а не каждый виток:
         * витков при трафике тысячи, а протухает запас за секунды. */
        if (now - spare_at >= 1000000000ull) {
            spare_at = now;
            spare_sweep();
        }
        nodes_sweep(&nodes_seen, now);
        for (int li = 0; li < g_live_n; ) {
            struct conn *c = &g_conns[g_live[li]];
            /* Заявка в работе — установщик пишет в сессию, не трогать. */
            if (c->pending || !conn_deadlines(c, &tun, now)) li++;
        }
    }
    /* Сначала отпустить установщиков, только потом закрывать сессии: иначе закрываем то,
     * с чем они работают. Почему это важно — у connq_release. eventfd — тоже только
     * после: установщик пишет в него по готовности, и закрытый раньше времени номер
     * ядро успело бы отдать кому-то другому. */
    if (connq_release(g_conns) == 0) {
        while (g_live_n) conn_drop(&g_conns[g_live[0]]);
        if (g_inloop) g_dl->ops->loop_stop();
        conn_table_free();
    }
    tun_wq_free();
    if (efd >= 0) close(efd);
    g_conn_efd = -1;
    close(ep);
    if (own_tun) close(tun_fd);
    if (lfd >= 0) close(lfd);
    /* Рабочий вышел — читателю больше некому отдавать, и процесс должен завершиться. */
    if (rw) __atomic_store_n(&g_ring_stop, 1, __ATOMIC_RELAXED);
    return NULL;
}

/* Читатель: единственный, кто читает TUN в режиме с несколькими рабочими. Читает до пустоты,
 * считает хэш соединения, копирует пакет в кольцо владельца и будит его, если он спит. Крутится в
 * потоке stack_run (так процесс остаётся тем, чем был для procd: вышел цикл — вышел процесс).
 *
 * Ничего не ждёт: кольцо полно — пакет отбрасывается и считается. Ждать значило бы остановить
 * чтение для всех рабочих из-за одного медленного, а TCP повторит потерянное сам.
 *
 * Выход — только по ошибке устройства или останову рабочего (g_ring_stop): штатно процесс умирает от
 * сигнала. */
#define READER_BATCH 256
#define READER_WAIT_NS 20000000ull
static void reader_loop(struct tun_dev *t, struct ring_work *rws, int nw) {
    unsigned char pkt[TUNNEL_BUF];
    struct pollfd pf = { .fd = t->fd, .events = POLLIN };
    uint64_t stats_at = now_ns(), said_full = 0;
    unsigned long long last_pkts = 0, last_full = 0;
    uint64_t busy_ns = 0;
    for (;;) {
        if (__atomic_load_n(&g_ring_stop, __ATOMIC_RELAXED)) return;
        uint64_t t0 = g_stats ? now_ns() : 0;
        int drained = 0;     /* устройство отдало EAGAIN: пусто */
        for (int k = 0; k < READER_BATCH; k++) {
            ssize_t rn = tun_read_packet(t, pkt, sizeof(pkt));
            if (rn < 0) {
                if (errno == EAGAIN || errno == EINTR) { drained = 1; break; }
                fprintf(stderr, LOG_W "чтение из TUN отказало (%s) — туннель останавливается\n",
                        strerror(errno));
                __atomic_store_n(&g_ring_stop, 1, __ATOMIC_RELAXED);
                return;
            }
            if (rn == 0) continue;
            unsigned o = stack_owner(pkt, (size_t)rn, (unsigned)nw);
            struct ring_work *w = &rws[o];
            if ((size_t)rn > spsc_cap(&w->ring)) {
                /* Не влезает в слот: почта, медленный путь (см. «цифры» у g_rw). */
                if (xmail_put(o, pkt, (size_t)rn) == 0) w->rd_pkts++; else w->rd_full++;
                continue;
            }
            unsigned char *slot = spsc_reserve(&w->ring);
            if (!slot) {
                /* Кольцо полно — рабочий занят (читает у узлов, шифрует). Ждём место (спим, а не крутимся:
                 * spsc_reserve_wait), а не бросаем сразу: пока читатель ждёт, пакеты копятся в очереди
                 * устройства в ядре, ровно как при одном потоке, а брошенный пакет выгрузки стоил бы клиенту
                 * повтора и сброса окна (без ожидания стенд run-tunnel-mt при 2 рабочих: 830–1253 брошенных
                 * пакета, 1,1–1,5 с против 0,4). Ждать вечно нельзя — остальные рабочие ждут вместе с
                 * читателем, — поэтому не дольше READER_WAIT_NS, 20 мс. Не меньше: порция разбора — десятки
                 * микросекунд, но запись к узлу у TCP и TLS блокирующая и при полном сокете узла занимает
                 * миллисекунды (при 2 мс стенд run-tunnel-mt ловил 3 брошенных на 250 тыс.), а брошенный
                 * пакет стоит клиенту повтора не раньше 200 мс. Рабочий, не освободивший ни слота за 20 мс,
                 * завис, а не отстал, и тогда пакет бросается со счётом, как раньше. */
                w->rd_waits++;
                slot = spsc_reserve_wait(&w->ring, READER_WAIT_NS);
            }
            if (!slot) {
                w->rd_full++;
                if (now_ns() - said_full > 5000000000ull) {
                    said_full = now_ns();
                    fprintf(stderr, LOG_W "кольцо рабочего %u переполнено: пакеты отбрасываются (всего "
                                    "%llu) — рабочий не успевает\n", o, w->rd_full);
                }
                continue;
            }
            memcpy(slot, pkt, (size_t)rn);
            spsc_commit(&w->ring, (uint32_t)rn);
            w->rd_pkts++;
        }
        if (g_stats) {
            uint64_t t1 = now_ns();
            busy_ns += t1 - t0;
            if (t1 - stats_at >= 2000000000ull) {
                unsigned long long pk = 0, full = 0, waits = 0;
                char per[256] = "";
                size_t pl = 0;
                for (int i = 0; i < nw; i++) {
                    pk += rws[i].rd_pkts;
                    full += rws[i].rd_full;
                    waits += rws[i].rd_waits;
                    if (pl < sizeof(per) - 24)
                        pl += (size_t)snprintf(per + pl, sizeof(per) - pl, "%s%llu", i ? " " : "",
                                               rws[i].rd_pkts);
                }
                double sec = (double)(t1 - stats_at) / 1e9;
                fprintf(stderr, "tun-reader: пакетов %.0f/с | занят %.0f%% | кольцо переполнено %llu "
                                "(за период %llu) | ждали места %llu | по рабочим всего [%s]\n",
                        (double)(pk - last_pkts) / sec, 100.0 * (double)busy_ns / (double)(t1 - stats_at),
                        full, full - last_full, waits, per);
                last_pkts = pk;
                last_full = full;
                busy_ns = 0;
                stats_at = t1;
            }
        }
        if (!drained) continue;
        /* Пусто — ждём пакет, но не вечно: раз в секунду проверяем останов рабочих. */
        if (poll(&pf, 1, 1000) < 0 && errno != EINTR) {
            fprintf(stderr, LOG_W "poll по TUN отказал (%s) — туннель останавливается\n", strerror(errno));
            __atomic_store_n(&g_ring_stop, 1, __ATOMIC_RELAXED);
            return;
        }
    }
}

/* Сколько рабочих потоков поднимать (R-146): по числу ядер, которыми процесс вправе пользоваться.
 *
 * Решение владельца — «пусть ядра = потоки». Считаем ядра, которые процесс действительно может занять:
 * min(онлайн, число в маске affinity). Процесс под taskset на двух ядрах восьмиядерной машины с восемью
 * рабочими получил бы борьбу за два ядра вместо работы — а на роутере с cpuset так бывает.
 *
 * Читатель TUN — ещё один поток сверх этого числа: большую часть времени он спит в poll и занимает
 * ядро только пока пакеты идут (чтение и копия в кольцо, на пакет их доли микросекунды).
 *
 * Одно ядро — один поток и прежний путь без читателя: раздавать там некому, а лишний поток только
 * добавил бы переключений. STEER_TUN_THREADS=N задаёт число вручную, и STEER_TUN_THREADS=1 — это тот
 * самый прежний путь, одной переменной: утверждение «стало быстрее от второго ядра» надо уметь
 * перепроверить на том же железе (тот же довод, что у STEER_TUN_NOGSO). Предела сверху нет: число задаёт
 * человек и ядра, а у каждого рабочего своя растущая таблица (CONN_CHUNK), так что и
 * соединений у процесса столько, сколько хватит памяти. */
static int worker_count(void) {
    const char *env = getenv("STEER_TUN_THREADS");
    if (env) {
        int n = atoi(env);
        if (n >= 1) return n;
    }
    long on = sysconf(_SC_NPROCESSORS_ONLN);
    int n = on < 1 ? 1 : (int)on;
    cpu_set_t cs;
    if (sched_getaffinity(0, sizeof(cs), &cs) == 0) {
        int a = CPU_COUNT(&cs);
        if (a >= 1 && a < n) n = a;
    }
    return n;
}

time_t stack_now_s(void) { return g_now_s; }
uint64_t stack_now_ns(void) { return g_now_ns; }

/* ---- что дайлер с DC_INLOOP говорит стеку (dialer.h) ---------------------------------------------- */

/* Соединение по сессии: сессии лежат в таблице потока подряд с шагом g_sess_stride, и индекс слота — это
 * номер сессии (SESS наоборот). Зовут только из потока цикла: у каждого рабочего своя таблица. */
static struct conn *conn_of_sess(void *sess) {
    return &g_conns[(size_t)((unsigned char *)sess - g_sess) / g_sess_stride];
}

int stack_loop_watch(int fd) {
    struct epoll_event e = { .events = EPOLLIN, .data = { .u32 = LOOP_TOKEN } };
    return g_ep >= 0 ? epoll_ctl(g_ep, EPOLL_CTL_ADD, fd, &e) : -1;
}

void stack_sess_ready(void *sess, int rc) {
    struct conn *c = conn_of_sess(sess);
    c->rc = rc;
    __atomic_store_n(&c->done, 1, __ATOMIC_RELEASE);
}

void stack_sess_rx(void *sess) {
    conn_of_sess(sess)->rx_ready = 1;
    g_rx_kick = 1;
}

void stack_sess_room(void *sess) {
    /* Место у дайлера выросло: недочитанное у клиента дочитает проход сроков (sock_want_read) — без сна. */
    (void)sess;
    g_rx_kick = 1;
}

/* Шаг сессий и пул запасных — по размеру сессии дайлера. До запуска любых потоков: дальше
 * g_dl, g_sess_stride и g_spares[].sess только читают. */
static void stack_setup(const struct dialer *d) {
    g_dl = d;
    g_inloop = (d->ops->caps & DC_INLOOP) != 0;
    g_sess_stride = (d->ops->sess_size + SESS_ALIGN - 1) & ~(size_t)(SESS_ALIGN - 1);
    if (!(d->ops->caps & DC_PRECONNECT)) g_spare_want = 0;
    if (g_spare_want <= 0) return;
    /* Весь пул одним блоком: SPARE_MAX сессий, а не g_spare_want, — слоты g_spares не
     * меняются от числа запасных, и так проще, чем помнить, какие из них с памятью. Страницы
     * под слоты, которые не заполнятся никогда, calloc большого размера не трогает. */
    unsigned char *m = calloc(SPARE_MAX, g_sess_stride);
    if (!m) {
        fprintf(stderr, LOG_W "нет памяти под запасные сессии — каждый SYN платит "
                        "рукопожатие\n");
        g_spare_want = 0;
        return;
    }
    for (int i = 0; i < SPARE_MAX; i++) g_spares[i].sess = m + (size_t)i * g_sess_stride;
}

/* Дескрипторы: соединению клиента нужно два-три (сокет клиента, связь с узлом, вторая связь), потоку UDP —
 * связь с узлом. При мягком пределе 1024 таблица без предела упёрлась бы в него на пятой сотне соединений
 * (I-529), и мягкий поднимался до жёсткого. Жёсткий у службы роутера — 4096 (procd), и это тоже чужое
 * число, а не причина: дом, где через выход идёт всё (десятки устройств, торрент, QUIC), упирался в него,
 * и выход «отваливался» — новые соединения получали EMFILE, пока старые не уйдут. Поэтому у кого есть
 * право (CAP_SYS_RESOURCE: служба роутера — root) жёсткий предел поднимается до fs.nr_open ядра; без
 * права — мягкий до жёсткого, как прежде. Возвращает итоговый мягкий предел. */
static unsigned long stack_nofile_raise(void) {
    struct rlimit rl;
    if (getrlimit(RLIMIT_NOFILE, &rl) != 0) return 0;
    rlim_t want = 0;
    FILE *f = fopen("/proc/sys/fs/nr_open", "r");
    if (f) {
        unsigned long v;
        if (fscanf(f, "%lu", &v) == 1) want = (rlim_t)v;
        fclose(f);
    }
    if (want > rl.rlim_max) {
        struct rlimit up = { want, want };
        if (setrlimit(RLIMIT_NOFILE, &up) == 0) return (unsigned long)want;
    }
    if (rl.rlim_cur < rl.rlim_max) {
        rl.rlim_cur = rl.rlim_max;
        if (setrlimit(RLIMIT_NOFILE, &rl) != 0) getrlimit(RLIMIT_NOFILE, &rl);
    }
    return (unsigned long)rl.rlim_cur;
}

/* host_fd < 0 — устройство заводит и поднимает сам стек (stack_run); иначе это готовый TUN хоста
 * (stack_run_fd), и ни очередей, ни адреса, ни программы раздачи стек не трогает. */
static int stack_run_impl(const struct tun_out *o, const struct dialer *d, stack_ready_fn ready, void *arg,
                          int host_fd) {
    const char *dev = o->device;
    g_trace = getenv("STEER_TUN_TRACE") != NULL;
    g_stats = getenv("STEER_TUN_STATS") != NULL;
    /* Порт слушателя TCP (R-152): соединения клиентов, перенаправленные правилом nft, принимаются здесь, а не
     * пакетами через TUN. Порт выводится из метки выхода (out_tcp_port) — так же его выводит демон, ставя
     * элемент карты перенаправления; STEER_TUN_TCPPORT — для стендов без демона. */
    stack_nofile_raise();
    if (o->mark) g_kport = o->tcp_port;
    if (getenv("STEER_TUN_TCPPORT")) {
        int pt = atoi(getenv("STEER_TUN_TCPPORT"));
        if (pt > 0 && pt < 65536) g_kport = pt;
    }

    /* Читается ЗДЕСЬ, до запуска потоков: дальше поле только читают, и getenv в пути
     * пакета не нужен. Ноль выключает пул совсем — тогда каждый SYN платит рукопожатие,
     * как раньше (но SYN-ACK всё равно уходит сразу). */
    const char *sp = getenv("STEER_TUN_SPARES");
    g_spare_want = sp ? atoi(sp) : 4;
    if (g_spare_want < 0) g_spare_want = 0;
    if (g_spare_want > SPARE_MAX) g_spare_want = SPARE_MAX;
    stack_setup(d);

    /* Узел, который заведомо не годится (у VLESS — негодный UUID, I-097), модуль протокола
     * отвергает ДО этой функции, пока узел ещё можно назвать: здесь устройство уже поднимется. */

    /* Очереди устройства: по одной на рабочего, если пакеты раздаст ядро (программа на устройстве,
     * tun_steer_attach), и одна — если раздаёт читатель (см. «несколько рабочих потоков» у g_rw). Без
     * программы ядро разводит половины соединения по разным очередям (12 против 292 Мбит/с на роутере),
     * поэтому несколько очередей без неё не остаются: лишние закрываются, и раздаёт читатель. */
    int want = worker_count();
    g_workers_plan = want;
    struct tun_dev *qs = calloc((size_t)want, sizeof(*qs));
    if (!qs) { fprintf(stderr, LOG_W "нет памяти под очереди устройства\n"); return 1; }
    int nq = host_fd >= 0 ? tun_adopt_fd(qs, host_fd) : tun_open(qs, want, dev);
    /* Код выхода — ОДИН, и он положительный. Возвращая сюда -40 или -41, движок отдавал
     * их main, а тот отдавал ядру: отрицательное обрезается до байта, и procd получал 216
     * или 215. Число, которое ничего не значит ни для человека, ни для splify2. Причину
     * называет tun_open своим сообщением, здесь остаётся признак отказа. */
    if (nq < 0) return 1;
    char steer_why[256] = "";
    if (want > 1 && host_fd >= 0)
        snprintf(steer_why, sizeof(steer_why), "устройство дал хост, очередь у него одна");
    else if (want > 1 && nq < 2)
        snprintf(steer_why, sizeof(steer_why), "ядро не дало нескольких очередей (IFF_MULTI_QUEUE)");
    else if (want > 1 && tun_steer_attach(qs[0].fd, (unsigned)nq, steer_why, sizeof(steer_why)) == 0)
        g_steered = 1;
    if (g_steered) {
        want = nq;                      /* очередь на рабочего: сколько очередей дали, столько рабочих */
        g_workers_plan = want;
    } else {
        for (int i = 1; i < nq; i++) close(qs[i].fd);
        nq = 1;
    }
    struct tun_dev q0 = qs[0];
    /* Неблокирующее чтение: цикл вычерпывает устройство до EAGAIN, и без этого флага
     * последнее чтение засыпало бы, останавливая все соединения. */
    for (int i = 0; i < nq; i++) {
        int fl = fcntl(qs[i].fd, F_GETFL, 0);
        if (fl >= 0) fcntl(qs[i].fd, F_SETFL, fl | O_NONBLOCK);
    }
    if (host_fd < 0) tun_bring_up(dev, o->table);   /* устройство хоста: адрес и маршруты — его */
    /* Слушатель TCP — до up: с up демон начнёт перенаправлять сюда TCP выхода. Порт занят (чужая служба,
     * второй экземпляр с другой спекой) — выхода без слушателя не бывает: перенаправление отдало бы
     * соединения тому, кто на порту, или сбросу. Модуль выходит, супервизор повторит по паузе. */
    if (g_kport > 0 && (g_lfd0 = klisten_open()) < 0) {
        fprintf(stderr, LOG_W "%s: порт %d для TCP выхода занят или недоступен (%s)\n", dev, g_kport,
                strerror(errno));
        return 1;
    }

    /* Устройство готово — сказать об этом модулю, а маршрут НЕ трогать.
     *
     * apply к этому моменту уже прошёл и, не найдя устройства, поставил запрет, а момент
     * готовности TUN знает только тот, кто его создал, — стек. Но привязка — работа демона
     * (решение владельца; docs/architecture.md, «4а», «Дети и здоровье»): там же страж правил,
     * сторож и postrouting_guard, и маршрутизация с её моделью не должна ехать в бинарник модуля
     * на libsteer. Поэтому стек только зовёт ready, модуль пишет демону up с именем устройства
     * (evline.h, поле dev), и демон привязывает тем же bind_device в своём процессе. Зовётся ДО
     * потоков цикла: порядок «сначала устройство, потом маршрут в него». До привязки таблица
     * выхода держит то, что поставили apply или сторож (запрет у on_fail=drop, «напрямую» у
     * direct), а помеченный пакет не в устройство выхода
     * отбрасывает postrouting_guard, так что окно — «ещё не работает», а не «мимо туннеля». */
    if (ready) ready(arg, dev);
    char desc[512];
    d->ops->describe(d->ctx, desc, sizeof(desc));
    fprintf(stderr, LOG_I "%s -> %s\n", dev, desc);

    struct worker *workers = calloc((size_t)want, sizeof(*workers));
    pthread_t *tids = calloc((size_t)want, sizeof(*tids));
    /* Выровнено по строке кэша: в кольце головы и хвосты разнесены по строкам, и сбитое выравнивание
     * свело бы их обратно. */
    struct ring_work *rws = NULL;
    if (want > 1 && posix_memalign((void **)&rws, SPSC_LINE, (size_t)want * sizeof(*rws)) == 0)
        memset(rws, 0, (size_t)want * sizeof(*rws));
    if (!workers || !tids || (want > 1 && !rws)) {
        fprintf(stderr, LOG_W "нет памяти под %d рабочих потоков\n", want);
        return 1;
    }

    int n = 1;                          /* сколько рабочих встало */
    int started = 0;
    int served;
    if (want == 1) {
        /* Прежний путь: один поток читает устройство сам, читателя и колец нет. Ничем не отличается от
         * того, что было до R-146 (STEER_TUN_THREADS=1 и одноядерные). */
        workers[0].tun = q0;
        workers[0].id = 0;
        workers[0].rw = NULL;
    } else {
        /* Рабочие встают ПО ОДНОМУ, и следующий — когда предыдущий доложил: номер рабочего — это его
         * место в хэше (stack_owner), и отказавший при подготовке (нет памяти, нет epoll) не должен
         * оставить в нумерации дыру, в которую читатель стал бы класть пакеты. */
        int made = 0;
        pthread_attr_t at;
        pthread_attr_init(&at);
        /* Стек задан явно: у musl он по умолчанию 128 КБ, а цикл держит на стеке буферы и вызывает
         * шифр и рукопожатия. Миб виртуальной памяти, трогаются только нужные страницы. */
        pthread_attr_setstacksize(&at, thread_stack(1024 * 1024));
        for (int i = 0; i < want; i++) {
            struct ring_work *rw = &rws[made];
            if (g_steered) {
                /* Кольцо не нужно — рабочий читает свою очередь; почта остаётся (фрагменты). */
                rw->ring.efd = -1;
            } else if (spsc_init(&rw->ring, RING_SLOTS, RING_SLOT_DATA) != 0) {
                fprintf(stderr, LOG_W "нет памяти под кольцо рабочего %d — потоков будет %d\n", i, made);
                break;
            }
            pthread_mutex_init(&rw->mail.mu, NULL);
            struct worker *w = &workers[made];
            memset(w, 0, sizeof(*w));
            if (g_steered) {
                w->tun = qs[i];             /* своя очередь, со своим буфером склейки */
            } else {
                w->tun = q0;
                w->tun.rx = NULL;           /* читает только читатель: у рабочих буфера склейки нет */
                w->tun.rx_gso = 0;
            }
            w->id = made;
            w->rw = rw;
            int failed = pthread_create(&tids[made], &at, worker_loop, w) != 0;
            if (failed) {
                fprintf(stderr, LOG_W "поток %d не создался\n", i);
            } else {
                while (!__atomic_load_n(&w->state, __ATOMIC_ACQUIRE)) {
                    struct timespec ts = { 0, 1000000 };
                    nanosleep(&ts, NULL);
                }
                if (__atomic_load_n(&w->state, __ATOMIC_ACQUIRE) == 2) {
                    pthread_join(tids[made], NULL);   /* уже вышел, причину назвал сам */
                    failed = 1;
                }
            }
            if (failed && g_steered) {
                /* Раздаёт ядро: очередь без рабочего — пакеты, которые никто не прочтёт, а номер очереди
                 * зашит в программу. Работать на части рабочих нельзя — выходим, procd поднимет заново. */
                fprintf(stderr, LOG_W "%s: рабочий %d не встал, а пакеты в его очередь раздаёт ядро — "
                                "туннель останавливается\n", dev, i);
                __atomic_store_n(&g_ring_stop, 1, __ATOMIC_RELAXED);
                for (int k = 0; k < made; k++) {
                    if (rws[k].ring.efd >= 0) {
                        uint64_t one = 1;
                        ssize_t wr = write(rws[k].ring.efd, &one, sizeof(one));
                        (void)wr;
                    }
                }
                for (int k = 0; k < made; k++) pthread_join(tids[k], NULL);
                return 1;
            }
            if (failed) {
                spsc_free(&rw->ring);       /* номер не занят — следующий рабочий встанет на него */
                continue;
            }
            made++;
        }
        pthread_attr_destroy(&at);
        started = made;
        n = made;
        if (!made) {
            fprintf(stderr, LOG_W "%s не поднялся ни одним рабочим потоком\n", dev);
            return 1;
        }
        /* Остался один рабочий (на остальных не хватило памяти или потока) — читатель всё равно
         * нужен: рабочий уже запущен без устройства в epoll. Хэш при одном рабочем даёт 0. */
        g_nwork = (unsigned)made;
        g_rw = rws;
    }

    /* Печатается всегда: без второй очереди скорость падает в разы, и знать, что досталось, надо до
     * замеров, а не после. */
    fprintf(stderr, LOG_I "%s: потоков %d из %d запрошенных%s\n", dev,
            n, want, want <= 1 ? "" : g_steered ? " (рабочих; пакеты раздаёт ядро — программа на устройстве)"
                                                   : " (рабочих; пакеты раздаёт читатель TUN)");
    if (want > 1 && !g_steered)
        fprintf(stderr, LOG_I "раздача пакетов ядром недоступна: %s — раздаёт читатель\n", steer_why);
    fprintf(stderr, LOG_I "запасных сессий к узлу: %d (STEER_TUN_SPARES)\n", g_spare_want);
    if (n < want)
        fprintf(stderr, LOG_W "рабочих потоков меньше запрошенного (%d из %d)\n", n, want);

    if (want == 1) {
        worker_loop(&workers[0]);
        served = workers[0].served;
    } else if (g_steered) {
        /* Читателя нет: рабочие читают свои очереди. Ждём их; вышедший ставит g_ring_stop, остальные
         * замечают его не позже чем через секунду. */
        for (int i = 0; i < started; i++) pthread_join(tids[i], NULL);
        served = 1;
    } else {
        reader_loop(&q0, rws, n);
        /* Читатель вышел: рабочих просим закончить (флаг уже стоит) и будим — они ждут в epoll. */
        for (int i = 0; i < n; i++) {
            if (rws[i].ring.efd >= 0) {
                uint64_t one = 1;
                ssize_t wr = write(rws[i].ring.efd, &one, sizeof(one));
                (void)wr;
            }
        }
        for (int i = 0; i < started; i++) pthread_join(tids[i], NULL);
        served = 1;
        close(q0.fd);
    }

    /* Досюда мы доходим ТОЛЬКО когда все очереди завершились, а завершиться они могут
     * лишь по ошибке: успешного выхода у worker_loop нет ни одного. Штатное окончание
     * работы выглядит иначе — procd присылает сигнал, и процесс умирает, не возвращаясь
     * сюда вовсе.
     *
     * Поэтому ноль здесь неверен всегда. Возвращая его, движок сообщал procd и splify2
     * «завершился успешно» в тот момент, когда туннель не нёс трафик: интерфейс показывал
     * выход настроенным, журнал — ни одной жалобы, а сайты не открывались. Ровно тот
     * тихий сбой, который в этом коде вычищен везде, кроме этой строки. */
    if (!served)
        fprintf(stderr, LOG_W "%s не поднялся ни одной очередью из %d\n", dev, n);
    else
        fprintf(stderr, LOG_W "%s больше не несёт трафик — все потоки (%d) "
                        "завершились\n", dev, n);
    return 1;
}

int stack_run(const struct tun_out *o, const struct dialer *d, stack_ready_fn ready, void *arg) {
    return stack_run_impl(o, d, ready, arg, -1);
}

int stack_run_fd(const struct tun_out *o, const struct dialer *d, int fd, stack_ready_fn ready, void *arg) {
    if (fd < 0) {
        fprintf(stderr, LOG_W "%s: дескриптор устройства от хоста не задан (%d)\n", o->device, fd);
        return 1;
    }
    return stack_run_impl(o, d, ready, arg, fd);
}
