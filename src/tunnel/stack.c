/* Стек туннеля: соединения клиентов и датаграммы из TUN — в потоки к узлу и обратно.
 *
 * TCP клиента завершает ядро Linux (R-152): правило nat steer перенаправляет соединение по метке выхода к
 * слушателю модуля, и сюда оно приходит готовым сокетом (kaccept). На каждое соединение мы открываем свой
 * поток к узлу и переносим байты: из сокета клиента — дайлеру (sock_read), от дайлера — в сокет одной
 * записью за проход (emit_to_client, sock_flush). Окно, повторы, порядок сегментов, SACK — у ядра. Свой
 * TCP-стек поверх TUN здесь был до шага 5 R-152 и удалён: он держал у клиента не больше 64 КБ в пути и не
 * умел SACK — на линии с задержкой 2 мс это было около 95 Мбит/с на соединение (хаб, STEER_REBUILD.md).
 *
 * Через TUN идёт UDP: датаграммы клиента — в потоки к узлу (udp_packet), ответы — датаграммами обратно.
 * TCP, всё-таки попавший в устройство (перенаправления нет), получает сброс (handle_packet_one).
 *
 * ПРОТОКОЛА ЗДЕСЬ НЕТ. Всё, что знает про узел, — у дайлера (dialer.h): сессия соединения для стека
 * непрозрачна, а VLESS, прокси и hysteria2 — дайлеры в своих модулях.
 */
