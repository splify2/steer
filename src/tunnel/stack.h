/* Стек туннеля: пакеты из TUN в потоки к узлу через дайлер (dialer.h). Границы — в stack.c. */
#ifndef STEER_STACK_H
#define STEER_STACK_H
#include "dialer.h"
#include <stdint.h>

/* Выход глазами стека: только то, что стеку нужно знать о своём выходе. Не struct output модели
 * спеки ядра: стек живёт в библиотеке net1 у программ плагинов, а они спеку не разбирают — всё это
 * им дал файл настройки выхода {conf} (plugin-sdk/docs/steer-api.md, 1.4). */
struct tun_out {
    char name[32];              /* имя выхода (журнал) */
    char device[32];            /* TUN, который стек создаёт */
    int table;                  /* таблица выхода: из неё — адрес устройства */
    uint32_t mark;              /* метка выхода (значение поля steer), 0 — нет */
    int tcp_port;               /* порт слушателя TCP выхода с tcp-redir, 0 — нет */
};

/* Устройство поднято, у него есть адрес, и оно готово нести трафик: зовётся один раз, из потока
 * stack_run, до запуска потоков цикла. Модуль протокола говорит здесь демону up с именем
 * устройства (evline.h, поле dev), и маршрут выхода к устройству привязывает демон. */
typedef void (*stack_ready_fn)(void *arg, const char *dev);

/* Поднять TUN выхода и нести через него трафик дайлером d, пока не кончатся очереди.
 *
 * Выход передаётся целиком, а не именем устройства: туннель сам поднимает устройство и сам даёт
 * ему адрес, а адрес берётся из таблицы выхода. Маршрут выхода к устройству стек НЕ
 * привязывает: это работа демона, рядом со стражем правил и postrouting_guard, а
 * стек о моменте готовности только сообщает — ready (может быть NULL).
 *
 * Возвращает всегда 1: успешного выхода у цикла нет (см. конец stack_run). */
int stack_run(const struct tun_out *o, const struct dialer *d, stack_ready_fn ready, void *arg);
/* То же поверх готового TUN хоста (по PR #11): приложение на Android с VpnService получает
 * устройство от системы (VpnService.Builder.establish) уже с адресом и маршрутами, и завести его
 * самому стеку там нечем и незачем — ни прав на /dev/net/tun, ни права трогать маршруты телефона.
 * fd — пакеты IP без заголовка (как IFF_TUN|IFF_NO_PI). Стек берёт его копию (F_DUPFD_CLOEXEC):
 * дескриптор хоста остаётся у хоста, закрывать его стек не будет. Очередь одна, адрес, маршруты и
 * программа раздачи — забота хоста; рабочих потоков столько же, сколько у stack_run, пакеты
 * раздаёт читатель. Флаг O_NONBLOCK стек ставит на копию, а он общий у всех копий одного открытого
 * файла: дескриптор хоста тоже станет неблокирующим. o->device — только имя для журнала и ready.
 *
 * ОГРАНИЧЕНИЕ, о котором надо знать хосту: TCP через устройство стек не несёт (R-152) — соединения
 * клиентов на роутере завершает ядро Linux, правило nat ведёт их к слушателю модуля, а TCP, дошедший
 * до TUN, получает сброс. У VpnService правила nat нет, и TCP по этому пути сейчас сбрасывается;
 * несёт он UDP (QUIC, DNS и прочее). Путь TCP для устройства хоста — отдельная работа.
 * Возвращает всегда 1, как stack_run. */
int stack_run_fd(const struct tun_out *o, const struct dialer *d, int fd, stack_ready_fn ready, void *arg);
/* Таблица fake-IP резолвера (только чтение): помощнику плагина путь даёт ядро в {conf}
 * (paths.fakeip, steer-api.md 1.4); NULL или не задан — <каталог состояния>/fakeip.state, как в 2.0. */
void stack_set_fakeip_path(const char *path);

/* Политика нового потока у хоста (по PR #13): filter зовётся на первом пакете нового потока UDP и на
 * каждом новом соединении TCP (принятом слушателем), ДО сессии и до соединения с узлом. Не 0 —
 * поток отвергнут: TCP получает сброс, UDP — ICMP «порт недоступен», чтобы приложение не ждало
 * своего срока. k — пятёрка как её видит стек (адреса — flow_src_bytes/flow_dst_bytes), udp — 1
 * у UDP. Зачем: приложению с VpnService своя политика (какое приложение, какой адрес куда)
 * нужна без правил в ядре steer — их там на телефоне без root и нет. Зовётся из потоков рабочих
 * одновременно; ставится до stack_run, ctx живёт, пока идут потоки. NULL — все потоки, как прежде. */
typedef int (*stack_flow_filter_fn)(void *ctx, const struct flow_key *k, int udp);
void stack_set_flow_filter(stack_flow_filter_fn filter, void *ctx);

/* Набор активных узлов изменился (пул узлов, pool.c): соединения, чей узел больше не активен
 * (dialer_ops.stale), стек сбрасывает — RST клиенту, — чтобы приложения переподключались сразу, а не
 * ждали своего таймаута на повисшем соединении. Зовётся из любого потока; поток цикла замечает это на
 * ближайшем витке (не позже секунды). */
void stack_nodes_changed(void);

/* Поднять устройство и дать ему адрес из таблицы выхода. Каждый отказ `ip` называется в
 * журнале своим тоном (I-114). Отдельно от stack_run — ради стенда devupmatch. */
void tun_bring_up(const char *dev, int table);

#endif
