/* Страж правил выходов в демоне (`steerd daemon --watch`) — устройство и доводы в шапке rulewd.c. */
#ifndef STEER_RULEWD_H
#define STEER_RULEWD_H

#include <stddef.h>

struct steerd;
struct spec;
struct output;
struct rulewd;

struct rulewd_conf {
    /* Идёт своя команда демона, после которой не разобрать, что в правилах снято ею, а что снаружи
     * (починка ребёнком, выключатель, restart…): проверка ждёт её конца. apply и reload сюда не
     * входят — у них решает held (srv_rules_busy в ctl.c). NULL — не спрашивать. */
    int (*busy)(void *arg);
    /* Выход o — тот, чьи правила идущий сейчас apply или reload САМ снимает или может снять
     * (метка --drop, выход --route с изменившейся подписью): его правила проверка не возвращает,
     * пока команда не кончится. Остальные выходы возвращаются сразу. NULL — таких нет. */
    int (*held)(void *arg, const struct output *o);
    /* Правил не хватает, а сам страж вернуть их не смог: починить (сервер сокета ставит починку
     * в очередь изменяющих команд). */
    void (*repair)(void *arg);
    /* Страж вернул снятое сам, в процессе демона: сказать в журнал и подписчикам, позвать
     * внеочередной проход сторожа. Выходы через запятую: all — все тронутые, rules — из них те, чьи
     * правила возвращены, bs6 — чей запасной запрет IPv6 возвращён (любой из двух бывает пуст).
     * NULL — сам страж не чинит, всё идёт через repair. */
    void (*restored)(void *arg, const char *all, const char *rules, const char *bs6);
    void *arg;
};

/* Завести стража. on — движок включён: только тогда открыт сокет событий правил. NULL — нет
 * памяти. */
struct rulewd *rulewd_start(struct steerd *d, const struct rulewd_conf *c, int on);
/* Движок включили или выключили: сокет событий открывается или закрывается, отложенная
 * проверка снимается. */
void rulewd_enable(struct rulewd *r, int on);
/* Своя операция кончилась: отложенная из-за неё проверка — сейчас. NULL — ничего. */
void rulewd_kick(struct rulewd *r);
/* Проверить и вернуть снятое сейчас, не дожидаясь события и пачки, — перед решением сверки
 * (commit_start в ctl.c), чтобы оно не перепривязывало выходы ребёнком из-за правила, которое
 * страж вернул бы одним сообщением. NULL или выключен — ничего. */
void rulewd_settle(struct rulewd *r);

/* Каких правил выходов спеки sp не хватает (и запасных запретов IPv6, которые ядро снимает вместе
 * с lo): имена через запятую в list (n байт). Возврат — сколько выходов без правила или запрета;
 * 0 — всё на месте или нечего чинить; -1 — ядро не спросить. */
int rulewd_missing(const struct spec *sp, char *list, size_t n);
/* Сколько выходов с устройством держат своё правило IPv4 в ядре Linux; -1 — правил не прочитать. */
int rulewd_present(const struct spec *sp);

#endif
