/* Состояние сторожа между проходами и события прохода — шов между логикой прохода (failover.c)
 * и тем, кто его крутит.
 *
 * ЗАЧЕМ ШОВ. Проход сторожа помнит между проходами четыре вещи: какое устройство несёт трафик
 * выхода и сколько тиков подряд ожило более предпочтительное (файл `active`), замеры задержки
 * (`latency`) и время последнего оживления каждого устройства (`restart-<устройство>`). Пока
 * сторожем был `steer failover` — один проход на процесс, — помнить было негде, кроме файлов
 * каталога состояния. Демон (docs/architecture.md, «4а») держит это в памяти, а одиночный
 * `steer failover` и `steer status` подкомандой по-прежнему читают `active` из файла. Поэтому
 * проход ОДИН — автомат fo_pass_start (синхронно — failover_pass), — а где лежит его память,
 * решает тот, кто его зовёт:
 *
 *   `steer failover`, apply, status и diag подкомандой — fo_store_files: файлы каталога
 *     состояния того же формата (его пишет и читает тот же код прохода);
 *   демон с `--watch` — хранилище в памяти (src/daemon/watchd.c).
 *
 * ХРАНИЛИЩЕ — ИМЕНОВАННЫЕ ТЕКСТЫ, а не поля. Запись — это ровно тот текст, что лежал бы в
 * файле с этим именем, и читает его тот же fscanf прохода, только из памяти (fmemopen). Так
 * «формат байт в байт тот же» — не обещание двух реализаций, а одна реализация: разбор и печать
 * не раздвоены, раздвоено только место. Имена: `active`, `latency`, `restart-<устройство>`.
 *
 * СОБЫТИЯ. Проход сообщает о переменах тому, кто его позвал: демон шлёт их подписчикам
 * управляющего сокета (switched, failed, revived — docs/ctl.md). У `steer failover` получателя
 * нет, и проход печатает то же, что печатал всегда. */
#ifndef STEER_FOSTATE_H
#define STEER_FOSTATE_H

#include <stdio.h>
#include <stddef.h>

#include "spec.h"

struct fo_store;
struct fo_store_ops {
    /* Открыть запись name на чтение. NULL — записи нет (как нет файла). */
    FILE *(*open_r)(struct fo_store *st, const char *name);
    /* Заменить запись целиком. Читатель видит либо прежний текст, либо новый. */
    void (*put)(struct fo_store *st, const char *name, const char *data, size_t n);
};
struct fo_store {
    const struct fo_store_ops *ops;
};

/* Файлы каталога состояния (steer_state_dir): прежний путь. */
extern struct fo_store fo_store_files;

/* События прохода. Строки живут до возврата из обратного вызова. */
enum fo_ev_kind {
    FO_EV_SWITCHED,   /* выход сменил устройство: from (NULL — не было), to, why */
    FO_EV_FAILED,     /* живых устройств нет, on_fail применён: from (NULL — не было), why */
    FO_EV_REVIVED,    /* сторож оживил устройство (перезапуск, перенастройка, ожидание), и оно ответило */
    FO_EV_BALANCE,    /* группа balance: сменился состав живых членов (alive) — карта переписана */
};
struct fo_event {
    enum fo_ev_kind kind;
    const char *out;
    const char *from, *to;
    /* switched: start — первый выбор (записи не было); recovered — выход был в отказе;
     *   spec — прежнее устройство больше не кандидат; down — прежнее не отвечает;
     *   preferred — более предпочтительное ожило и подтвердило здоровье (гистерезис);
     *   latency — выбор по замеру задержки; select — выбор человека у pick: manual.
     * failed: down — ни одно устройство не ответило; via — не работает выход, через который
     *   идёт этот. */
    const char *why;
    const char *on_fail;   /* режим отказа выхода: drop | direct | zapret */
    /* Группа с именованными членами (v2): выбранный член (switched), NULL — не группа v2 (у пула
     * v1 членов по имени нет, и событие остаётся прежним до байта). */
    const char *member;
    /* Кто переключил: NULL — сторож; "select" — команда select. */
    const char *by;
    /* balance: живые члены через запятую ("" — ни одного). */
    const char *alive;
};
typedef void (*fo_event_fn)(void *arg, const struct fo_event *e);

/* ПРОХОД — конечный автомат на цикле событий (устройство — в failover.c, «ПРОХОД — КОНЕЧНЫЙ
 * АВТОМАТ»). Один и тот же автомат у всех, кто проход зовёт; разница только в том, чей цикл он
 * крутит и где лежит его память. */
struct loop;
struct fo_run;
/* Проход кончился: res — 0 или FO_PASS_REVIVE. Зовётся один раз, после того как проход освободил
 * себя сам. */
typedef void (*fo_done_fn)(void *arg, int res);
/* Итог прохода с fo_pass_defer_revive: у члена группы v2 оживление отложено — нужен ещё проход,
 * с оживлением. */
#define FO_PASS_REVIVE 1

/* Начать проход по спеке sp (разобранной, с метками реестра) на цикле l. sp меняется: device
 * каждого выхода — выбранное устройство; sp и st обязаны жить до done (или до отмены). Память
 * между проходами — st; ev (может быть NULL) — получатель событий. Первый шаг — оборотом цикла,
 * так что done никогда не зовётся изнутри этого вызова. NULL — нет памяти (done не позовётся). */
struct fo_run *fo_pass_start(struct loop *l, struct spec *sp, struct fo_store *st, int verbose,
                             fo_event_fn ev, void *ev_arg, fo_done_fn done, void *done_arg);
/* Прервать идущий проход: снять пробу (правило пробы, сокет), убить команду оживления,
 * бросить разрешение имён. done не зовётся. Решения, уже применённые к ядру, остаются. */
void fo_pass_abort(struct fo_run *r);

/* Тот же проход синхронно (`steer failover`): свой цикл, крутится до конца прохода. Возврат — 0. */
int failover_pass(struct spec *sp, struct fo_store *st, int verbose, fo_event_fn ev, void *arg);

/* При старте сторожа (однократный проход, круг, демон): снять правило пробы, оставшееся от
 * прохода, убитого SIGKILL, и снимать своё по SIGTERM/SIGINT вне цикла (как `steer failover`).
 * cleanup_probe_rule — та же уборка отдельно (объявление и в failover_int.h, для стенда). */
void failover_pass_guard(void);
void cleanup_probe_rule(void);

/* outputs_adopt_active (spec.h) по записи выбора из st, а не из файла. */
void outputs_adopt_active_st(struct spec *sp, struct fo_store *st);

/* ИСТОЧНИК ЗДОРОВЬЯ ПОМОЩНИКА — второй шов между проходом и тем, кто его зовёт.
 *
 * Проход спрашивает о процессах, которые держат туннели выходов, в трёх местах: жив ли туннель,
 * чьё устройство создаёт наш процесс (vless, xsteer); почему он не поднимается (перебор узлов
 * подписки, номер узла вне подписки); как оживить обфускатор выхода interface. Пока помощников
 * держал procd, ответы брались из файлов, которые помощники писали для сторожа, а оживление шло
 * сигналом экземпляру procd через ubus. Демон с --supervise держит помощников сам и знает их
 * состояние по событиям из трубы (helpers.h, helper_state_of) — файлы там не нужны, и помощники
 * их при трубе событий не пишут. Поэтому источник — параметр прохода:
 *
 *   fo_hsrc_files — `steer failover`, демон с --watch без --supervise;
 *   память демона — демон с --watch и --supervise (watchd.c).
 *
 * РЕШЕНИЯ ОДНИ. Источник только отвечает на вопрос; что с ответом делать, решает проход, одним
 * кодом для обоих источников: «не поднят» (DOWN, STARTING, PROBING, NONODE) — устройство не
 * живо, без пробы; «поднят» (UP) — дальше прежняя мера устройства (наличие, мера вида, проба
 * TCP у vless). Перебор узлов (PROBING) при оживлении — ожидание, а не отказ; номер узла вне
 * подписки (NONODE) — отказ с причиной, ждать нечего.
 *
 * ПОМОЩНИК, КОТОРЫЙ СЛЕДИТ САМ (watch). Клиент vless под демоном следит за узлом (слежка за
 * узлом, src/tunnel/pool.c) и говорит down, когда узел перестал отвечать, и up, когда нашёл
 * узел, — его up приходит с watch. Тогда UP — уже приговор: устройство живо, если оно есть, и
 * пробы TCP нет. Проба эта узла и не мерила: SYN-ACK клиент отдаёт сам, до рукопожатия с узлом,
 * и connect пробы удавался на мёртвом узле. Оставить её «на всякий случай» — платить пробой
 * каждый период за одно знание: цикл клиента читает устройство; а выход процесса демон и так
 * видит (loop_child). Запасной пробой на случай «клиент давно молчит» она быть не может: клиент по
 * договору молчит, пока узел жив (события — только на смене, evline.h), и молчание здорового
 * от молчания зависшего не отличить. DOWN с watch — оживлять нечего: процесс жив и ищет узел
 * сам, его up позовёт внеочередной проход (watchd_helper_changed), и ждать внутри прохода, как
 * ждут поднимающийся туннель, незачем. Без watch (источник-файлы, клиент без трубы, поток
 * слежки не завёлся) — всё прежнее. */
enum fo_hs {
    FO_HS_UNKNOWN = 0,   /* сказать нечего: прежняя мера устройства */
    FO_HS_UP,            /* помощник поднят и сообщил up */
    FO_HS_DOWN,          /* сообщил down, или процесса нет */
    FO_HS_STARTING,      /* процесс запущен и ещё ничего не сообщил */
    FO_HS_PROBING,       /* перебирает узлы подписки: проверяется node из total */
    FO_HS_NONODE,        /* выбранного номера узла (node) нет в подписке из total пригодных */
};
struct fo_hstate {
    enum fo_hs st;
    int node, total;
    int watch;           /* помощник сам следит за узлом (см. выше): UP — приговор, DOWN — ждать его up */
};
struct fo_hsrc;
struct fo_hsrc_ops {
    /* Помощник выхода out — выхода, чьё устройство создаёт наш процесс. 0 — источнику есть что
     * сказать (*h заполнено); -1 — нечего (файла нет, помощник не наш): прежняя мера. */
    int (*state)(struct fo_hsrc *s, const char *out, struct fo_hstate *h);
    /* dev — туннель xsteer, поднятый netifd (не выход спеки, а устройство в пуле interface):
     * 1 — да, up — есть живое соединение с хабом, fresh — клиент писал недавно (оба
     * необязательны). Такой клиент — не ребёнок демона ни в каком режиме, и спрашивается его
     * файл xsteer-<устройство>.json у обоих источников. */
    int (*xsdev)(struct fo_hsrc *s, const char *dev, int *up, int *fresh);
    /* Перезапустить помощника cmd выхода out (оживление обфускатора). 0 — перезапуск заказан;
     * NULL или -1 — нечем, прежний путь: сигнал экземпляру procd через ubus. */
    int (*restart)(struct fo_hsrc *s, const char *out, const char *cmd);
    /* Кто поднимет упавший процесс туннеля — для строки журнала при ожидании. */
    const char *respawn;
};
struct fo_hsrc {
    const struct fo_hsrc_ops *ops;
};

/* Файлы каталога состояния и procd: прежний путь. */
extern struct fo_hsrc fo_hsrc_files;

/* ТРАФИК ЧЕРЕЗ ГРУППУ — для idle_timeout замера urltest (fogroup.c): пакеты правил каналов, ведущих
 * в группу g (и в группы, которые выбирают g), по счётчикам nft. Счётчики знает только тот, у кого
 * есть группы каналов спеки (демон: struct groups в памяти), поэтому это шов: демон его ставит,
 * у `steer failover` его нет — и трафик тогда считается идущим (замер по интервалу, как прежде).
 * 0 — *pkts заполнен; -1 — узнать не вышло. */
typedef int (*fo_traffic_fn)(void *arg, const struct spec *sp, const struct output *g,
                             unsigned long long *pkts);
/* Звать сразу после fo_pass_start, как fo_pass_helpers. */
void fo_pass_traffic(struct fo_run *r, fo_traffic_fn fn, void *arg);
/* ОЖИВЛЕНИЕ ЧЛЕНОВ ГРУПП v2 — НЕ В ЭТОМ ПРОХОДЕ. Член группы — выход со своим проходом, и молчащий
 * член в нём оживляется: ifdown/ifup и до десяти шагов ожидания с пробой (≈70 с), либо ожидание
 * подъёма туннеля. Группа судит по приговору члена в том же обходе и идёт после него (fog_order),
 * поэтому всё это время она держала трафик на мёртвом члене: переключение группы запаздывало на
 * длину оживления — вдвое против пула v1, который при живом запасном не оживляет вовсе. С этим
 * флагом молчащий член в проходе сразу получает приговор «не отвечает» (группа переходит на
 * живого в том же проходе), а его оживление ждёт следующего прохода — итог FO_PASS_REVIVE, и
 * сторож демона заводит его через успокоение, не дожидаясь периода. Только когда оживление
 * вообще разрешено (не чаще раза в RESTART_COOLDOWN на устройство), иначе оно и так мгновенное.
 * Демону; у `steer failover` флага нет — там проход один. Звать сразу после fo_pass_start. */
void fo_pass_defer_revive(struct fo_run *r);
/* ЗАМЕРЫ ГРУПП latency — НЕ ПО СРОКУ В ПРОХОДЕ. У демона замер по интервалу группы идёт своим
 * таймером (src/daemon/folat.c) и зовёт внеочередной проход, только если выбор меняется; проход с
 * этим флагом меряет лишь тогда, когда у живого члена замера нет вовсе (первый проход, член ожил),
 * а замер, который не ответил, помнит строкой с -1, чтобы не мерить его заново каждый проход.
 * Демону; у `steer failover` флага нет — там замер по сроку в проходе, как был. Звать сразу после
 * fo_pass_start. */
void fo_pass_lat_extern(struct fo_run *r);
/* Спрашивать о помощниках hs, а не файлы (умолчание прохода — fo_hsrc_files). Звать сразу после
 * fo_pass_start: первый шаг прохода идёт оборотом цикла. hs живёт до конца прохода. */
void fo_pass_helpers(struct fo_run *r, struct fo_hsrc *hs);

#endif
