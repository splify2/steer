/* @wan_dev на лету: устройства маршрутов по умолчанию таблицы main (v4 и v6) — в набор wan_dev
 * таблицы steer по событию rtnetlink, без apply и reload.
 *
 * ЗАЧЕМ. Набор @wan_dev читают правила плагинов (steer-api 1.2: recheck ставит в очередь прямой
 * трафик в WAN). Печатает его компилятор при apply и reload, и между ними набор жил прежним:
 * сменился WAN (PPPoE переподнялся с другим pppN, переключился резервный канал, сотовый модем) —
 * правила плагина до следующего reload смотрели на устройство, которого уже нет, и трафик шёл мимо.
 *
 * Подписка — только на маршруты (RTMGRP_IPV4_ROUTE, RTMGRP_IPV6_ROUTE), отбор — маршрут по
 * умолчанию в таблице main: свои таблицы выходов демон меняет сам, и они сюда не будят. Список
 * устройств сверяется с прошлым, и набор переписывается одной транзакцией netlink (сброс и новые
 * элементы), только когда список сменился. Набора нет (ни один плагин не читает @wan_dev) — молча. */
#ifndef STEER_WANDEV_H
#define STEER_WANDEV_H

struct loop;

/* 0 или -1 (сокет rtnetlink не открылся — набор живёт от reload до reload, как прежде). */
int wandev_start(struct loop *l);

/* Сверить сейчас; force — переписать набор без сверки с прошлым (после apply и reload). */
void wandev_sync(int force);

#endif
