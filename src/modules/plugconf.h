/* Файл настройки выхода {conf} у программ протоколов (plugin-sdk/docs/steer-api.md, 1.4).
 *
 * Помощник плагина запускается по манифесту как `<prog> <cmd> {out} --conf {conf}` и о своём выходе
 * знает ТОЛЬКО то, что в {conf}: ключи вида (уже проверенные схемой манифеста), устройство, метку,
 * таблицу, IPv6, метку своих сокетов, порт слушателя TCP, свои каталоги, таблицу fake-IP. Спеку
 * человека и файлы ядра он не читает.
 *
 * Как это сделано, не переписывая протоколы: из {conf} строится спека из ОДНОГО выхода
 * (<каталог {conf}>/<выход>.spec.json — каталог плагина), её разбирает своя копия модели плагина
 * теми же записями видов, что всегда, а то, что модель вычислила бы сама по всей спеке (метка, таблица,
 * метка сокетов), берётся из {conf} — plugconf_out после registry_assign. Каталог состояния процесса —
 * каталог {conf} (<state>/plugin/<id>), файл состояния для status — <выход>.status.json там же.
 *
 * Подкоманды (`vless-nodes` и соседи) идут без --conf: им ядро передаёт --spec и --state-dir само
 * (manifest.md, commands[].ctl.spec) — это они и были. */
#ifndef STEER_PLUGCONF_H
#define STEER_PLUGCONF_H

#include "plugout.h"

/* Переписать argv: `--conf ФАЙЛ` → `--spec <спека из одного выхода> --state-dir <каталог {conf}>`.
 * Возвращает новый argv (в куче, живёт до конца процесса) и число слов в *argc; без --conf — прежний
 * argv. Файл не читается или в нём нет нужного — отказ кодом 2 со словами (steer-api.md, 1.5).
 * Заодно выключает в процессе реестр плагинов: свой вид помощник берёт из встроенной записи своей
 * копии модели. */
char **plugconf_argv(int *argc, char **argv);

#endif
