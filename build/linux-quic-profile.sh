#!/bin/sh
# Optional Linux transport archive profile; never changes production defaults.
# Usage: client|server OUTPUT_DIRECTORY WOLFSSL_ARCHIVE NGTCP2_ARCHIVE
set -eu
MODE=${1:?client or server profile required}
OUT=${2:?isolated output directory required}
WLIB=${3:?wolfSSL archive required}
NGLIB=${4:?ngtcp2 archive required}
CC=${CC:-cc}
AR=${AR:-ar}
HERE=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
[ "$(uname -s)" = Linux ] || { echo 'Linux profile required' >&2; exit 2; }
case "$MODE" in client) DEFS= ;; server) DEFS=-DQC_WITH_ENDPOINT ;; *) exit 2 ;; esac
[ -r "$WLIB.cflags" ] && [ -r "$NGLIB.cflags" ]
if grep -q -- '-DSTEER_WOLFSSL_SERVER' "$WLIB.cflags"; then HAS_SERVER=1; else HAS_SERVER=0; fi
if [ "$MODE" = server ] && [ "$HAS_SERVER" != 1 ]; then echo 'server profile requires server-enabled wolfSSL' >&2; exit 2; fi
if [ "$MODE" = client ] && [ "$HAS_SERVER" != 0 ]; then echo 'minimal baseline requires client-only wolfSSL' >&2; exit 2; fi
mkdir -p "$OUT"
OUT=$(CDPATH= cd -- "$OUT" && pwd)
cd "$HERE"
WFLAGS=$(cat "$WLIB.cflags")
NGFLAGS=$(cat "$NGLIB.cflags")
find src -type d -print | sed 's|.*|"-I&"|' > "$OUT/includes.rsp"
for file in quic qcssl; do
    # Same optimization/configuration for comparable client/server object sizes.
    # Flags are generated by trusted dependency recipes, never peer input.
    # shellcheck disable=SC2086
    $CC -O2 -g0 -Wall -Wextra -Werror -ffunction-sections -fdata-sections \
        $DEFS $WFLAGS $NGFLAGS @"$OUT/includes.rsp" -c "src/proto/quic/$file.c" -o "$OUT/$file.o"
done
$AR rcs "$OUT/libsteer-quic-$MODE.a" "$OUT/quic.o" "$OUT/qcssl.o"
# Identical source/flags; optional server branch is additive to the client.
# Size only: this link probe is not an installed or tested product executable.
# shellcheck disable=SC2086
$CC -O2 -g0 -s -ffunction-sections -fdata-sections -Wl,--gc-sections $DEFS $WFLAGS $NGFLAGS \
    @"$OUT/includes.rsp" -Itests tests/qcprofile_size.c "$OUT/libsteer-quic-$MODE.a" \
    "$NGLIB" "$WLIB" -lpthread -lm -o "$OUT/quic-profile-link-probe"
{
    printf 'profile=%s\nendpoint=%s\n' "$MODE" "$HAS_SERVER"
    printf 'dependency-archive-bytes\n'
    wc -c "$WLIB" "$NGLIB"
    printf 'transport-archive-bytes\n'
    wc -c "$OUT/libsteer-quic-$MODE.a"
    printf 'stripped-comparable-link-probe-bytes\n'
    wc -c "$OUT/quic-profile-link-probe"
    printf 'transport-text-data-bss\n'
    size -t "$OUT/quic.o" "$OUT/qcssl.o"
} > "$OUT/profile.txt"
cat "$OUT/profile.txt"
