#!/bin/sh
# Собирает расширенный бинарник под одну архитектуру — в одной из двух РОЛЕЙ.
#
# Роли появились вместе со звездой xsteer, и не ради удобства. Хабу нужна криптография, то
# есть wolfSSL, то есть расширенная сборка; а на роутере хабу делать нечего — подкоманды,
# поднимающей слушателя на публичном порту, там быть не должно. Отсюда две роли:
#
#   router (по умолчанию) — движок, клиент VLESS/Reality и клиент xsteer. Едет в пакет.
#   server                — движок, хаб xsteer. Едет в архив для VPS.
#
# Гейт стоит на СПИСКАХ ФАЙЛОВ, а не внутри их тел, и это важно: цель ext-syntax в Makefile
# гоняет -fsyntax-only по всем файлам расширенной части, и файл, целиком спрятанный под #ifdef, проходил
# бы проверку «пустым» — то есть ровно тот откат, ради которого ext-syntax и появилась.
# Поэтому цикл спицы живёт в xsclient.c, цикл хаба в xshub.c, а различаются только списки.
#
# Вынесено из build.sh отдельным файлом, а не оставлено строкой в `docker run -c`: там всё
# это жило внутри двойных кавычек с экранированием, и флаги -I терялись при подстановке —
# ошибка выглядела как «заголовок не найден», то есть будто заголовков нет в образе.
# Скрипт в файле читается буквально, и подобный класс ошибок в нём невозможен.
set -eu

TARGET="$1"
MCPU="${2:-}"
OUT="$3"
# Версия приходит четвёртым аргументом, а не читается из VERSION: скрипт работает внутри
# контейнера, и умолчание нужно ради ручного запуска с тремя аргументами.
VERSION="${4:-dev}"
# Роль: router (умолчание) или server. Пятым аргументом, чтобы прежние вызовы с четырьмя
# аргументами продолжали значить то же, что значили.
ROLE="${5:-router}"
# Ревизия сборки — шестым аргументом и по той же причине, что версия: git внутри образа нет,
# а каталога .git там нет и подавно (смонтирован только рабочий каталог). Умолчание честное:
# «неизвестна» лучше числа, которое ничему не соответствует, — печатает её `steer --version`
# (R-045).
REV="${6:-неизвестна}"
# Клиент сокета `steer` (src/client, docs/architecture.md, раздел 4а) — седьмым аргументом, по
# желанию: путь, куда положить второй бинарник пакета рядом с движком (OUT — это steerd). Пакеты
# build.sh собирают клиент сами, один на оба пакета; здесь он — для сборок в образе без build.sh
# (проверка ролей, рецепты SDK). Клиенту криптография не нужна, и собирается он с -Os: весь его
# смысл в том, чтобы весить десятки килобайт.
CLIENT_OUT="${7:-}"

# Исходники wolfSSL — в образе (build/Dockerfile, версия и сумма — build/wolfssl/fetch.sh).
WOLFSSL_DIR="${WOLFSSL_DIR:-/opt/wolfssl}"

# Оптимизация: -O2, а не -Os, и только для этой половины сборки.
#
# Через AEAD проходит ВЕСЬ трафик туннеля, и потолок шифрования — это потолок скорости. -Os
# на крипто экономит десятки килобайт и стоит десятков процентов пропускной способности:
# обмен, который для базового движка выгоден (там размер решает, влезет ли пакет), а здесь
# ровно наоборот. Базовый пакет собирается с -Os по-прежнему, см. build.sh.
OPT=-O2

# wolfSSL — своим рецептом (build/wolfssl/build.sh: список файлов, опции, ассемблер x86_64), в
# каталог сборки дерева, а не во /tmp контейнера. Причина — число запусков: build.sh зовёт этот
# скрипт по разу на роль и архитектуру (extended, hub), каждый раз в новом контейнере, и
# библиотека во /tmp собиралась бы каждый раз. Архив в смонтированном build/ переживает контейнер,
# а build.sh пересобирает его, только если изменились опции, флаги или компилятор (отпечаток
# рядом с архивом).
#
# АППАРАТНЫЙ AES НА x86_64 — ассемблер wolfSSL с выбором по CPUID (AES-NI, PCLMUL, AVX для
# AES-GCM, ChaCha20, Poly1305 и SHA). Флаги набора команд получает только aes.c (-maes, ради
# интринсиков разворота ключа), остальная библиотека и весь движок собираются под baseline, то
# есть бинарник запускается там, где запускался. Подробности — в build/wolfssl/build.sh и
# user_settings.h. Прежняя ловушка mbedtls с выравниванием контекста AES (интринсики в aesni.c при
# ассемблерном пути в aes.c) здесь закрыта типом: хранилище контекстов слоя выровнено на 16
# (SC_ALIGN в src/lib/scrypto.h).
#
# -ffunction-sections и -fdata-sections у библиотеки, --gc-sections у компоновки: в статическом
# бинарнике остаётся только то, что зовут, — TLS-стек, QUIC и слой EVP wolfSSL (их опции включены
# заранее, под ngtcp2) на флеш не попадают, пока их никто не зовёт.
WTAG=$(echo "$TARGET$MCPU" | tr -c 'a-zA-Z0-9' '_')
WLIB="/src/build/wolfssl-obj/$WTAG/libwolfssl.a"
# Через env: переменные — окружение рецепта, а не этого скрипта (tests/buildmatch.sh ищет здесь
# присвоенные и никем не читаемые переменные).
# shellcheck disable=SC2086
env CC="zig cc -target $TARGET ${MCPU:+-mcpu=$MCPU}" AR="zig ar" \
    CFLAGS="$OPT -ffunction-sections -fdata-sections" \
    sh /src/build/wolfssl/build.sh "$WOLFSSL_DIR" "$WLIB" asm
WCFLAGS=$(cat "$WLIB.cflags")

# -s обязателен: zig cc при -Os убирает отладочную информацию сам, при -O2 — оставляет,
# и бинарник разом вырастает с 540 КБ до 4,9 МБ. На overlay в 6,9 МБ это разница между
# «пакет ставится» и «места нет», причём отладочная информация на роутере не нужна никому.
# Списки файлов ролей — из build/sources.mk (профили extended, server), одни на все
# сборки: Makefile, build.sh, этот скрипт и рецепты SDK читают один манифест.
export SOURCES_MK=/src/build/sources.mk
. /src/build/sources.sh
case "$ROLE" in
  router) FILES="$(profile_src extended /src/)" && ROLEDEF="$(profile_var PROFILE_DEFS_extended)" ;;
  # Клиентской половины в серверном профиле нет нарочно: на VPS нет ни спеки, ни выходов, ни
  # каналов, и клиентские подкоманды там отказывают штатной заглушкой (слабые ссылки в
  # src/daemon/main.c), а не ссылаются на код, которого в этой сборке нет. PROFILE_DEFS_* пусты
  # (ключей профилей больше нет) и читаются ради единообразия с умолчанием платформы.
  server) FILES="$(profile_src server /src/)" && ROLEDEF="$(profile_var PROFILE_DEFS_server)" ;;
  # Мини-сборки моста (роль tgws, микропакет stgws) с 2.1 нет: мост — программа плагина tgws
  # (build/build-libs.sh, PLUGINS_TLS).
  *) echo "неизвестная роль: $ROLE (router|server)" >&2; exit 2 ;;
esac
[ -n "${FILES:-}" ] || { echo "нет списка файлов для роли $ROLE" >&2; exit 2; }
STEER_INC="$(for d in $(profile_var INC_DIRS); do printf -- '-I/src/%s ' "$d"; done)"
# Определения стороннего кода в ядре (libyaml: -DHAVE_CONFIG_H) — см. THIRD_DEFS в sources.mk.
THIRD_DEFS="$(profile_var THIRD_DEFS)"

# Ключи wolfSSL ($WCFLAGS: -DWOLFSSL_USER_SETTINGS, -I на опции и исходники) нужны только
# src/lib/scrypto.c — единственному файлу, который включает её заголовки. Остальным они ничего
# не значат, поэтому идут общей строкой: отдельная команда на один файл была бы ещё одним местом,
# где ключи слоя и библиотеки могут разойтись.
# shellcheck disable=SC2086
zig cc -target "$TARGET" ${MCPU:+-mcpu=$MCPU} -static $OPT -s -Wl,--gc-sections \
    $STEER_INC $THIRD_DEFS $WCFLAGS $ROLEDEF -DSTEER_VERSION="\"$VERSION\"" \
    -DSTEER_REV="\"$REV\"" \
    -o "$OUT" \
    $FILES \
    "$WLIB"

if [ -n "$CLIENT_OUT" ]; then
    CLIENT_FILES="$(for f in $(profile_var CLIENT_SRC); do printf '/src/%s ' "$f"; done)"
    # shellcheck disable=SC2086
    zig cc -target "$TARGET" ${MCPU:+-mcpu=$MCPU} -static -Os -s $STEER_INC \
        -o "$CLIENT_OUT" $CLIENT_FILES
fi
